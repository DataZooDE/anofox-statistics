# R reference values for test/sql/reference/effects_reference.test (#319):
#
#  * effects_summary_agg = rms::summary(fit)            (datadist limits of the data)
#  * contrast_agg        = rms::contrast(fit, a, b)
#  * double_contrast_agg = rms::contrast(fit, a, b, a2, b2)
#  * predict_grid_agg    = rms::Predict(fit, x)          (pointwise and conf.type = "simultaneous")
#  * nomogram_agg        = rms::nomogram(fit, fun = plogis)
#
# for an ols and an lrm fit of y ~ rcs(x1, 4) * x2 + g (g a three-level factor), an ols fit
# with lsp(x2) and one with rcs(x1, 4) %ia% rcs(x2, 3), and a main-effects lrm for the
# nomogram. The SQL test fits the same models with ols_fit_agg / logistic_fit_agg on
# effects_design(...) and compares the coefficients too.
#
# Usage (from the repository root):
#   Rscript validation/generators/make_reference_effects.R
# writes test/sql/reference/effects_reference.test.
suppressMessages(library(rms))

out_file <- file.path("test", "sql", "reference", "effects_reference.test")
fmt <- function(x) ifelse(is.na(x), "NULL", sprintf("%.17g", x))
lst <- function(x) paste0("[", paste(fmt(as.numeric(x)), collapse = ", "), "]")
L <- character()
emit <- function(...) L <<- c(L, paste0(...))

set.seed(20261106)
n <- 300
x1 <- round(rnorm(n, 50, 10), 2)
x2 <- round(runif(n, 0, 10), 1)
g <- sample(c(1, 2, 3), n, replace = TRUE, prob = c(0.3, 0.45, 0.25))
lin <- -2 + 0.04 * x1 + 0.0015 * (x1 - 50)^2 + 0.1 * x2 + 0.005 * x1 * x2 + c(0, 0.5, -0.4)[g]
yc <- round(lin + rnorm(n), 4)
yb <- rbinom(n, 1, plogis(lin))
d <- data.frame(x1, x2, g = factor(g), yc, yb)
dd <- datadist(d)
options(datadist = "dd")
k1 <- attr(rcs(x1, 4), "parms")
k2 <- attr(rcs(x2, 3), "parms")

emit("# name: test/sql/reference/effects_reference.test")
emit("# description: #319 effects, contrasts, Predict grids and nomograms vs R rms")
emit("# group: [reference]")
emit("#")
emit("# Generated by validation/generators/make_reference_effects.R (rms ", as.character(packageVersion("rms")),
     ", multcomp ", as.character(packageVersion("multcomp")), ", R ",
     paste(R.version$major, R.version$minor, sep = "."), "). Do not edit by hand.")
emit("# Models: ols / lrm(y ~ rcs(x1, 4) * x2 + g), ols(yc ~ rcs(x1, 4) + lsp(x2, c(3, 6)) + g),")
emit("# ols(yc ~ rcs(x1, 4) + rcs(x2, 3) + g + rcs(x1, 4) %ia% rcs(x2, 3)), nomogram of lrm(yb ~ rcs(x1, 4) + x2 + g).")
emit("")
emit("require anofox_statistics")
emit("")
emit("statement ok")
emit("CREATE MACRO max_rel_diff(a, b) AS CASE WHEN len(a) = len(b) THEN coalesce(list_max(list_transform(",
     "range(1, len(a) + 1), lambda i: abs(a[i] - b[i]) / greatest(1, abs(b[i])))), 0) ELSE 1e300 END;")
emit("")
emit("statement ok")
emit("CREATE TABLE d AS SELECT unnest(", lst(x1), "::DOUBLE[]) AS x1, unnest(", lst(x2),
     "::DOUBLE[]) AS x2, unnest(", lst(g), "::DOUBLE[]) AS g, unnest(", lst(yc), "::DOUBLE[]) AS yc, unnest(",
     lst(yb), "::DOUBLE[]) AS yb;")
emit("")

# Term lists
emit("statement ok")
emit("CREATE TABLE specs AS SELECT ",
     "[effects_term('x1', spline_spec('rcs', ", lst(k1), ")), effects_term('x2', 'linear'), ",
     "effects_term('g', 'categorical', [1, 2, 3]), effects_interaction('x1', 'x2')] AS t_int, ",
     "[effects_term('x1', spline_spec('rcs', ", lst(k1), ")), effects_term('x2', spline_spec('lsp', [3, 6])), ",
     "effects_term('g', 'categorical', [1, 2, 3])] AS t_lsp, ",
     "[effects_term('x1', spline_spec('rcs', ", lst(k1), ")), effects_term('x2', spline_spec('rcs', ", lst(k2), ")), ",
     "effects_term('g', 'categorical', [1, 2, 3]), effects_interaction('x1', 'x2', true)] AS t_ia, ",
     "[effects_term('x1', spline_spec('rcs', ", lst(k1), ")), effects_term('x2', 'linear'), ",
     "effects_term('g', 'categorical', [1, 2, 3])] AS t_main;")
emit("")

fit_sql <- function(name, fitter, y, terms) {
  emit("statement ok")
  emit("CREATE TABLE ", name, " AS SELECT ", fitter, "(", y, ", effects_design([x1, x2, g], s.", terms,
       "), {'compute_inference': true}) AS m, any_value(s.", terms, ") AS t FROM d, specs s;")
  emit("")
}

check <- function(comment, expr, ref, tol) {
  emit("# ", comment)
  emit("query I")
  emit("SELECT max_rel_diff(", expr, ", ", lst(ref), ") < ", tol, " FROM ", attr(expr, "from"), ";")
  emit("----")
  emit("true")
  emit("")
}
# the effects aggregates run over the data rows d joined with the fitted model
q <- function(expr, tab) structure(expr, from = if (tab == "nom") "nom" else paste0("d, ", tab))

summary_checks <- function(tab, f, tol, ratio = FALSE) {
  s <- summary(f)
  eff <- s[s[, "Type"] == 1, , drop = FALSE]
  agg <- "effects_summary_agg([x1, x2, g], m, t)"
  emit("# ", tab, ": summary(fit) rows ", paste(rownames(eff), collapse = ", "))
  emit("query I")
  emit("SELECT array_to_string(list_transform(", agg, ", lambda r: r.label), '|') FROM d, ", tab, ";")
  emit("----")
  emit(paste(rownames(eff), collapse = "|"))
  emit("")
  for (col in list(c("low", "Low"), c("high", "High"), c("diff", "Diff."), c("estimate", "Effect"),
                   c("std_error", "S.E."), c("conf_low", "Lower 0.95"), c("conf_high", "Upper 0.95"))) {
    check(paste0(tab, ": summary ", col[2]),
          q(paste0("list_transform(", agg, ", lambda r: r.", col[1], ")"), tab), eff[, col[2]], tol)
  }
  if (ratio) {
    or <- s[s[, "Type"] == 2, , drop = FALSE]
    check(paste0(tab, ": summary odds ratio"), q(paste0("list_transform(", agg, ", lambda r: r.ratio)"), tab),
          or[, "Effect"], tol)
    check(paste0(tab, ": summary odds ratio lower"),
          q(paste0("list_transform(", agg, ", lambda r: r.ratio_low)"), tab), or[, "Lower 0.95"], tol)
    check(paste0(tab, ": summary odds ratio upper"),
          q(paste0("list_transform(", agg, ", lambda r: r.ratio_high)"), tab), or[, "Upper 0.95"], tol)
  }
}

contrast_check <- function(tab, k, call, tol, what = c("Contrast", "SE", "Lower", "Upper", "Pvalue")) {
  fields <- c(Contrast = "estimate", SE = "std_error", Lower = "conf_low", Upper = "conf_high", Pvalue = "p_value")
  expr <- structure(paste0("[", paste0("c.", fields[what], collapse = ", "), "]"),
                    from = paste0("(SELECT ", call, " AS c FROM d, ", tab, ")"))
  check(paste0(tab, ": ", call), expr, unlist(k[what]), tol)
}

grid_checks <- function(tab, p, var, tol, opts = "") {
  agg <- paste0("predict_grid_agg([x1, x2, g], m, t, '", var, "'", opts, ")")
  for (col in list(c("x", var), c("yhat", "yhat"), c("yhat_lower", "lower"), c("yhat_upper", "upper"))) {
    check(paste0(tab, ": Predict(fit, ", var, ")$", col[2], if (nzchar(opts)) " (simultaneous)"),
          q(paste0("list_transform(", agg, ", lambda r: r.", col[1], ")"), tab), p[[col[2]]], tol)
  }
}

# ---- ols / lrm with rcs(x1, 4) * x2 + g -----------------------------------------------------
for (m in c("ols", "lrm")) {
  f <- if (m == "ols") ols(yc ~ rcs(x1, 4) * x2 + g, data = d) else lrm(yb ~ rcs(x1, 4) * x2 + g, data = d)
  tab <- paste0("fit_", m)
  tol <- if (m == "ols") "1e-8" else "1e-6"
  emit("# ---- ", m, "(y ~ rcs(x1, 4) * x2 + g) ----")
  emit("")
  fit_sql(tab, if (m == "ols") "ols_fit_agg" else "logistic_fit_agg", if (m == "ols") "yc" else "yb", "t_int")
  check(paste0(tab, ": coefficients"), structure("list_prepend((m).intercept, (m).coefficients)", from = tab), coef(f), tol)
  summary_checks(tab, f, tol, ratio = m == "lrm")
  k <- contrast(f, list(x1 = 60, x2 = 2), list(x1 = 45, x2 = 2))
  contrast_check(tab, k, "contrast_agg([x1, x2, g], m, t, {'x1': 60, 'x2': 2}, {'x1': 45, 'x2': 2})", tol)
  k2 <- contrast(f, list(x1 = 60, x2 = 8), list(x1 = 45, x2 = 8), list(x1 = 60, x2 = 2), list(x1 = 45, x2 = 2))
  contrast_check(tab, k2, paste0("double_contrast_agg([x1, x2, g], m, t, {'x1': 60, 'x2': 8}, {'x1': 45, 'x2': 8}, ",
                                 "{'x1': 60, 'x2': 2}, {'x1': 45, 'x2': 2})"), tol)
  kg <- contrast(f, list(g = "3"), list(g = "2"))
  contrast_check(tab, kg, "contrast_agg([x1, x2, g], m, t, MAP {'g': 3}, MAP {'g': 2})", tol)
  kl <- contrast(f, list(x1 = 55, x2 = 5, g = "1"), list(x1 = 40, x2 = 3, g = "3"), conf.int = 0.9)
  contrast_check(tab, kl, paste0("contrast_agg([x1, x2, g], m, t, {'x1': 55, 'x2': 5, 'g': 1}, ",
                                 "{'x1': 40, 'x2': 3, 'g': 3}, {'level': 0.9})"), tol)
  grid_checks(tab, Predict(f, x1), "x1", tol)
  grid_checks(tab, Predict(f, x2 = c(0, 2.5, 5, 7.5, 10)), "x2", tol, ", {'values': [0, 2.5, 5, 7.5, 10]}")
  # Simultaneous bands: multcomp's randomised Genz-Bretz quadrature is accurate to about 1e-3.
  set.seed(1)
  ps <- Predict(f, x1 = seq(30, 70, by = 5), conf.type = "simultaneous")
  grid_checks(tab, ps, "x1", "2e-3", ", {'values': [30, 35, 40, 45, 50, 55, 60, 65, 70], 'simultaneous': true}")
}

# ---- lsp and %ia% -------------------------------------------------------------------------------
for (m in c("lsp", "ia")) {
  f <- if (m == "lsp") ols(yc ~ rcs(x1, 4) + lsp(x2, c(3, 6)) + g, data = d) else
    ols(yc ~ rcs(x1, 4) + rcs(x2, 3) + g + rcs(x1, 4) %ia% rcs(x2, 3), data = d)
  tab <- paste0("fit_", m)
  emit("# ---- ols with ", if (m == "lsp") "lsp(x2, c(3, 6))" else "rcs(x1, 4) %ia% rcs(x2, 3)", " ----")
  emit("")
  fit_sql(tab, "ols_fit_agg", "yc", paste0("t_", m))
  check(paste0(tab, ": coefficients"), structure("list_prepend((m).intercept, (m).coefficients)", from = tab), coef(f), "1e-8")
  s <- summary(f)
  eff <- s[s[, "Type"] == 1, , drop = FALSE]
  for (col in list(c("estimate", "Effect"), c("std_error", "S.E."), c("conf_low", "Lower 0.95"))) {
    check(paste0(tab, ": summary ", col[2]),
          q(paste0("list_transform(effects_summary_agg([x1, x2, g], m, t), lambda r: r.", col[1], ")"), tab),
          eff[, col[2]], "1e-8")
  }
  k <- contrast(f, list(x1 = 60, x2 = 7), list(x1 = 45, x2 = 2))
  contrast_check(tab, k, "contrast_agg([x1, x2, g], m, t, {'x1': 60, 'x2': 7}, {'x1': 45, 'x2': 2})", "1e-8")
  grid_checks(tab, Predict(f, x2), "x2", "1e-8")
}

# ---- nomogram -----------------------------------------------------------------------------------
f <- lrm(yb ~ rcs(x1, 4) + x2 + g, data = d)
nom <- nomogram(f, fun = plogis, funlabel = "Risk")
info <- attr(nom, "info")
emit("# ---- nomogram(lrm(yb ~ rcs(x1, 4) + x2 + g), fun = plogis) ----")
emit("")
fit_sql("fit_nom", "logistic_fit_agg", "yb", "t_main")
emit("statement ok")
emit("CREATE TABLE nom AS SELECT nomogram_agg([x1, x2, g], predict(m, effects_design([x1, x2, g], t), ",
     "{'type': 'link'}), m, t, {'fun': 'plogis'}) AS n FROM d, fit_nom;")
emit("")
emit("query I")
emit("SELECT array_to_string(list_transform((n).axes, lambda a: a.term), '|') FROM nom;")
emit("----")
emit("x1|x2|g")
emit("")
for (i in seq_along(c("x1", "x2", "g"))) {
  v <- c("x1", "x2", "g")[i]
  a <- nom[[v]]
  check(paste0("nomogram ", v, " values"), q(paste0("(n).axes[", i, "].values"), "nom"),
        as.numeric(as.character(a[[v]])), "1e-9")
  check(paste0("nomogram ", v, " xbeta"), q(paste0("(n).axes[", i, "].xbeta"), "nom"), a$Xbeta, "1e-6")
  check(paste0("nomogram ", v, " points"), q(paste0("(n).axes[", i, "].points"), "nom"), a$points, "1e-6")
}
check("nomogram scale and intercept", q("[(n).scale, (n).intercept]", "nom"), c(info$sc, info$Intercept), "1e-6")
check("nomogram total points", q("(n).total_points", "nom"), nom$total.points$x, "1e-9")
check("nomogram lp axis", q("(n).lp_at", "nom"), nom$lp$x.real, "1e-9")
check("nomogram lp points", q("(n).lp_points", "nom"), nom$lp$x, "1e-6")
check("nomogram risk axis", q("(n).fun_at", "nom"), nom$Risk$x.real, "1e-9")
check("nomogram risk points", q("(n).fun_points", "nom"), nom$Risk$x, "1e-5")

writeLines(L, out_file)
cat("wrote", out_file, "\n")
