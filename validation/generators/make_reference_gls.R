# Relative tolerance: the variance-covariance parameters come from two
# different optimisers (nlme: nlminb / optim; upstream: L-BFGS), so they agree
# to the optimiser tolerance, not to machine precision.
check <- function(comment, call, exprs, refs, tol = "1e-5", from = "d") {
  if (!all(is.finite(refs))) stop("non-finite reference in: ", comment)
  stopifnot(length(exprs) == length(refs))
  emit("# ", comment)
  emit("query ", strrep("I", length(exprs)))
  emit("SELECT")
  conds <- sprintf("    abs((%s) - (%s)) <= %s * (1 + abs(%s))", exprs, fmt(refs), tol, fmt(refs))
  emit(paste(conds, collapse = ",\n"))
  emit("FROM (SELECT ", call, " AS r FROM ", from, ") s;")
  emit("----")
  emit(paste(rep("true", length(exprs)), collapse = "\t"))
  emit("")
}

# Coefficients with their t tests and 95% intervals (summary / intervals),
# sigma, logLik, AIC, BIC and the natural-scale correlation / variance
# parameters (coef(modelStruct, unconstrained = FALSE)).
block <- function(label, fit, call, from = "d", data = d, tol = "1e-5") {
  tt <- summary(fit)$tTable
  ci <- intervals(fit, which = "coef")$coef
  k <- nrow(tt)
  ex <- c("r.intercept", "r.intercept_std_error", "r.intercept_statistic", "r.intercept_p_value",
          "r.intercept_conf_low", "r.intercept_conf_high")
  rf <- c(tt[1, 1], tt[1, 2], tt[1, 3], tt[1, 4], ci[1, 1], ci[1, 3])
  for (j in 2:k) {
    ex <- c(ex, sprintf("r.coefficients[%d]", j - 1), sprintf("r.std_errors[%d]", j - 1),
            sprintf("r.t_values[%d]", j - 1), sprintf("r.p_values[%d]", j - 1),
            sprintf("r.conf_low[%d]", j - 1), sprintf("r.conf_high[%d]", j - 1))
    rf <- c(rf, tt[j, 1], tt[j, 2], tt[j, 3], tt[j, 4], ci[j, 1], ci[j, 3])
  }
  check(paste0(label, ": coefficients, t tests, intervals(fit, 'coef')"), call, ex, rf, tol, from)
  ex <- c("r.sigma", "r.log_likelihood", "r.aic", "r.bic", "r.df_residual")
  rf <- c(fit$sigma, as.numeric(logLik(fit)), AIC(fit), BIC(fit), fit$dims$N - fit$dims$p)
  ms <- fit$modelStruct
  if (!is.null(ms$corStruct)) {
    cp <- coef(ms$corStruct, unconstrained = FALSE)
    ex <- c(ex, sprintf("r.correlation_params[%d]", seq_along(cp)))
    rf <- c(rf, cp)
  }
  if (!is.null(ms$varStruct)) {
    vp <- coef(ms$varStruct, unconstrained = FALSE)
    ex <- c(ex, sprintf("r.variance_params[%d]", seq_along(vp)))
    rf <- c(rf, vp)
  }
  check(paste0(label, ": sigma, logLik, AIC, BIC, df, correlation / variance parameters"), call, ex, rf, tol,
        from)
  emit("# ", label, ": counts")
  emit("query IIII")
  emit("SELECT r.n_observations, r.n_groups, r.n_params, len(r.correlation_params) + len(r.variance_params) ",
       "FROM (SELECT ", call, " AS r FROM ", from, ") s;")
  emit("----")
  np <- length(coef(fit)) + length(coef(ms, unconstrained = FALSE)) + 1
  emit(fit$dims$N, "\t", length(unique(data$subject)), "\t", np, "\t",
       length(coef(ms, unconstrained = FALSE)))
  emit("")
}

inf <- "'compute_inference': true"

## Independent errors = lm (sigma interval from the chi-square distribution).
f <- gls(y ~ dose + week, d)
l <- lm(y ~ dose + week, d)
stopifnot(max(abs(coef(f) - coef(l))) < 1e-10)
call <- sprintf("gls_fit_agg(y, [dose, week], subject, week, {%s})", inf)
block("independent, REML", f, call)
iv <- intervals(f, which = "var-cov")$sigma
check("independent: sigma interval", call, c("r.sigma_conf_low", "r.sigma_conf_high"), iv[c(1, 3)])

## AR(1), REML and ML.
f <- gls(y ~ dose + week, d, correlation = corAR1(form = ~ week | subject))
call <- sprintf("gls_fit_agg(y, [dose, week], subject, week, {'correlation': 'ar1', %s})", inf)
block("corAR1(form = ~ week | subject), REML", f, call)
iv <- intervals(f, which = "var-cov")
check("corAR1 REML: var-cov intervals (phi, sigma)", call,
      c("r.correlation_conf_low[1]", "r.correlation_conf_high[1]", "r.sigma_conf_low", "r.sigma_conf_high"),
      c(iv$corStruct[1, 1], iv$corStruct[1, 3], iv$sigma[1], iv$sigma[3]), tol = "1e-3")
# Standard error of x'b (sqrt(x' vcov x)), fitted values and residuals.
X <- model.matrix(~ dose + week, d)
se_fit <- sqrt(rowSums((X %*% vcov(f)) * X))
pick <- c(1, 2, 17, 40, n)
aug <- "gls_augment_agg(y, [dose, week], subject, week, {'correlation': 'ar1'}) OVER w"
emit("# corAR1 REML: gls_augment_agg rows ", paste(pick, collapse = ", "),
     ": fitted(fit), sqrt(x' vcov(fit) x), resid(fit), resid(type = 'pearson' / 'normalized')")
emit("query IIIII")
emit("SELECT")
refs <- list(fitted(f)[pick], se_fit[pick], resid(f)[pick], resid(f, type = "pearson")[pick],
             resid(f, type = "normalized")[pick])
fields <- c("fitted", "se_fit", "residual", "pearson_residual", "normalized_residual")
conds <- sapply(seq_along(fields), function(j) {
  sprintf("bool_and(abs((a).%s - [%s][list_position([%s], rn)]) <= 1e-5 * (1 + abs((a).%s)))", fields[j],
          paste(fmt(refs[[j]]), collapse = ", "), paste(pick, collapse = ", "), fields[j])
})
emit(paste0("    ", conds, collapse = ",\n"))
emit("FROM (SELECT rn, l[rn] AS a FROM (SELECT row_number() OVER w AS rn, ", aug, " AS l FROM d ",
     "WINDOW w AS (ORDER BY subject, week ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING))) ",
     "WHERE rn IN (", paste(pick, collapse = ", "), ");")
emit("----")
emit(paste(rep("true", 5), collapse = "\t"))
emit("")
# The empirical semivariogram of the Pearson residuals (Variogram(fit, form = ~ week | subject)).
vg <- Variogram(f, form = ~ week | subject)
call_vg <- "gls_fit_agg(y, [dose, week], subject, week, {'correlation': 'ar1', 'variogram': 20})"
check("corAR1 REML: Variogram(fit, form = ~ week | subject) (pearson residuals, one class per distance)", call_vg,
      c(sprintf("r.variogram[%d].variog", seq_len(nrow(vg))), sprintf("r.variogram[%d].dist", seq_len(nrow(vg))),
        sprintf("r.variogram[%d].n_pairs", seq_len(nrow(vg)))),
      c(vg$variog, vg$dist, vg$n.pairs))

f <- gls(y ~ dose + week, d, correlation = corAR1(form = ~ week | subject), method = "ML")
block("corAR1(form = ~ week | subject), ML", f,
      sprintf("gls_fit_agg(y, [dose, week], subject, week, {'correlation': 'ar1', 'method': 'ml', %s})", inf))

## Compound symmetry, REML and ML.
