  "gls_fit_agg(y, [dose, week], subject, week, {'correlation': 'ar1', 'fit_intercept': false, %s})", inf),
  c("r.coefficients[1]", "r.coefficients[2]", "r.std_errors[1]", "r.std_errors[2]", "r.correlation_params[1]",
    "r.log_likelihood"),
  c(tt[1, 1], tt[2, 1], tt[1, 2], tt[2, 2], coef(f$modelStruct$corStruct, unconstrained = FALSE),
    as.numeric(logLik(f))))

## Likelihood-ratio test of nested ML fits: anova(full, reduced).
f1 <- gls(y ~ dose + week, d, correlation = corAR1(form = ~ week | subject), method = "ML")
f0 <- gls(y ~ dose, d, correlation = corAR1(form = ~ week | subject), method = "ML")
a <- anova(f1, f0)
check("lr_test of nested ML fits = anova(full, reduced)", paste0(
  "lr_test(gls_fit_agg(y, [dose, week], subject, week, {'correlation': 'ar1', 'method': 'ml'}), ",
  "gls_fit_agg(y, [dose], subject, week, {'correlation': 'ar1', 'method': 'ml'}))"),
  c("r.statistic", "r.p_value", "r.df1"), c(a$L.Ratio[2], a$`p-value`[2], 1))

