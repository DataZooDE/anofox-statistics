#!/usr/bin/env Rscript
# =============================================================================
# make_reference_glmm_inference.R
#
# Generates test/sql/reference/glmm_inference.test (issue #218): GLMM inference
# in glmm_fit_agg (Satterthwaite / Wald, BLUP standard errors) and the
# contract macros glmm_tidy_by / glmm_glance_by / glmm_augment_by, against
#   lmerTest::contest1D(..., confint = TRUE)   Satterthwaite t tests
#   summary(glmer) / confint(method = "Wald")   Wald z tests
#   ranef(m, condVar = TRUE)                    BLUP conditional SEs
#   broom.mixed::tidy / glance / augment        the macro outputs
#
#   Rscript validation/generators/make_reference_glmm_inference.R   # from repo root
#
# Requires: lme4, lmerTest, broom.mixed. The data is the d4 panel of
# test/sql/reference/glm_glmm.test (read from that file, so both stay in sync).
# The fits use tight optimizer / PIRLS tolerances: glmer's default
# tolPwrss = 1e-7 leaves the nAGQ = 0 deviance noisy enough to move the
# variance component, and so the SEs, by ~1%.
# =============================================================================
suppressPackageStartupMessages({
  library(lme4); library(lmerTest); library(broom.mixed)
})

out_dir <- "test/sql/reference"
num <- function(v) ifelse(is.na(v), "NULL", sprintf("%.17g", v))
checks <- function(comment, from, exprs, refs, tol) {
  stopifnot(length(exprs) == length(refs))
  out <- character()
  idx <- seq_along(exprs)
  for (chunk in split(idx, ceiling(idx / 6))) {
    cols <- vapply(chunk, function(i)
      sprintf("abs((%s) - (%s)) <= %g * (1 + abs(%s))", exprs[i], num(refs[i]), tol, num(refs[i])), "")
    out <- c(out, paste0("# ", comment), paste0("query ", strrep("I", length(chunk))),
             paste0("SELECT\n    ", paste(cols, collapse = ",\n    ")), paste0("FROM ", from, ";"), "----",
             paste(rep("true", length(chunk)), collapse = "\t"), "")
  }
  out
}

# ---- data: the d4 panel of glm_glmm.test ----
src <- readLines(file.path(out_dir, "glm_glmm.test"))
start <- grep("^INSERT INTO d4 VALUES", src)
end <- start + which(grepl(";$", src[(start + 1):length(src)]))[1]
rows <- src[(start + 1):end]
rows <- gsub("[();]", "", sub(",$", "", rows))
d4 <- read.csv(text = rows, header = FALSE, quote = "'", strip.white = TRUE,
               col.names = c("g", "q1", "ly", "pc", "bb", "h", "nc", "lc"))
d4$g <- factor(d4$g)
d4$hf <- factor(d4$h)
stopifnot(nrow(d4) == 48)

opt <- list(xtol_abs = 1e-12, ftol_abs = 1e-14, xtol_rel = 1e-12, ftol_rel = 1e-14, maxeval = 1e5)
lctl <- lmerControl(calc.derivs = FALSE, optCtrl = opt)
gctl <- glmerControl(optimizer = "nloptwrap", calc.derivs = FALSE, tolPwrss = 1e-12, optCtrl = opt)

satt <- function(m) {
  mt <- as_lmerModLmerTest(m)
  p <- length(fixef(m))
  do.call(rbind, lapply(seq_len(p), function(j) {
    L <- numeric(p); L[j] <- 1
    contest1D(mt, L, confint = TRUE, level = 0.95)
  }))
}
condvar_se <- function(m, f) {
  pv <- attr(ranef(m, condVar = TRUE)[[f]], "postVar")
  do.call(rbind, lapply(seq_len(dim(pv)[3]), function(i) sqrt(diag(as.matrix(pv[, , i])))))
}

L <- c("# name: test/sql/reference/glmm_inference.test",
       "# description: GLMM inference (#218): glmm_fit_agg Satterthwaite / Wald tests and BLUP SEs, glmm_tidy_by / glmm_glance_by / glmm_augment_by against lmerTest, lme4 and broom.mixed",
       "# group: [reference]",
       "#",
       "# GENERATED by validation/generators/make_reference_glmm_inference.R -- do not edit",
       "# by hand; change the generator and re-run it instead.",
       sprintf("# Reference: %s; lme4 %s, lmerTest %s, broom.mixed %s", R.version.string, packageVersion("lme4"),
               packageVersion("lmerTest"), packageVersion("broom.mixed")),
       "", "require anofox_statistics", "",
       "statement ok",
       "CREATE TABLE d4 (g VARCHAR, q1 DOUBLE, ly DOUBLE, pc DOUBLE, bb DOUBLE, h DOUBLE, nc DOUBLE, lc DOUBLE);", "",
       "statement ok",
       paste0("INSERT INTO d4 VALUES\n", paste(src[(start + 1):end], collapse = "\n")), "",
       "# One outer group: the macros fit one model per group_col.",
       "statement ok",
       "CREATE TABLE d4o AS SELECT 'all' AS grp, * FROM d4;", "")

# =============================================================================
# A. Gaussian random intercept, REML: Satterthwaite (the gaussian default)
# =============================================================================
fa <- lmer(ly ~ q1 + (1 | g), d4, REML = TRUE, control = lctl)
sa <- satt(fa)
fit_a <- "(SELECT glmm_fit_agg(ly, [q1], g, {'compute_inference': true}) AS r FROM d4) s"
L <- c(L, checks("gaussian: lmerTest contest1D(lmer(ly ~ q1 + (1|g)), e_j, confint = TRUE): slope SE, t, df, p, 95% t interval",
  fit_a, c("r.std_errors[1]", "r.t_values[1]", "r.df[1]", "r.p_values[1]", "r.ci_lower[1]", "r.ci_upper[1]"),
  c(sa[2, "Std. Error"], sa[2, "t value"], sa[2, "df"], sa[2, "Pr(>|t|)"], sa[2, "lower"], sa[2, "upper"]), 1e-6))
L <- c(L, checks("gaussian: the intercept's Satterthwaite df, p and interval",
  fit_a, c("r.intercept_df", "r.intercept_p_value", "r.intercept_conf_low", "r.intercept_conf_high"),
  c(sa[1, "df"], sa[1, "Pr(>|t|)"], sa[1, "lower"], sa[1, "upper"]), 1e-6))
se_a <- condvar_se(fa, "g")
L <- c(L, checks("gaussian: BLUP conditional SEs, sqrt(attr(ranef(m, condVar = TRUE)$g, 'postVar'))",
  fit_a, sprintf("r.ranef[%d].se", 1:8), se_a[, 1], 1e-6))
# Wald on request
za <- coef(summary(fa))[, "t value"]
ciw <- confint(fa, parm = "beta_", method = "Wald")
fit_aw <- "(SELECT glmm_fit_agg(ly, [q1], g, {'compute_inference': true, 'ddf': 'wald'}) AS r FROM d4) s"
L <- c(L, checks("gaussian, ddf := 'wald': z = t value, p = 2 pnorm(-|z|), confint(method = 'Wald')",
  fit_aw, c("r.z_values[1]", "r.p_values[1]", "r.ci_lower[1]", "r.ci_upper[1]", "r.intercept_p_value"),
  c(za[2], 2 * pnorm(-abs(za[2])), ciw[2, 1], ciw[2, 2], 2 * pnorm(-abs(za[1]))), 1e-6))
L <- c(L, "# Satterthwaite fills t_values (z_values NULL); Wald fills z_values (t_values and df NULL)",
  "query II", paste("SELECT r.z_values IS NULL, r.t_values IS NOT NULL FROM", fit_a, ""), "----", "true\ttrue", "",
  "query III", paste("SELECT r.df IS NULL, r.intercept_df IS NULL, r.t_values IS NULL FROM", fit_aw, ""), "----",
  "true\ttrue\ttrue", "")

# glmm_tidy_by: fixed rows (Satterthwaite), ran_pars, ran_vals
tdy <- "glmm_tidy_by('d4o', grp, ly, [q1], g, names := ['q1'], re_names := ['g'])"
fx <- function(term, col) sprintf("(SELECT %s FROM %s WHERE effect = 'fixed' AND term = '%s')", col, tdy, term)
L <- c(L, checks("glmm_tidy_by fixed rows: estimate, std_error, statistic, df, p_value, conf_low (lmerTest)",
  "(SELECT 1) s", c(fx("q1", "estimate"), fx("q1", "std_error"), fx("q1", "statistic"), fx("q1", "df"),
                    fx("q1", "p_value"), fx("(Intercept)", "conf_low")),
  c(sa[2, "Estimate"], sa[2, "Std. Error"], sa[2, "t value"], sa[2, "df"], sa[2, "Pr(>|t|)"], sa[1, "lower"]), 1e-6))
rp <- as.data.frame(tidy(fa, effects = "ran_pars"))
rv <- as.data.frame(tidy(fa, effects = "ran_vals", conf.int = TRUE))
rv3 <- rv[rv$level == "g3", ]
rpq <- function(grp, term) sprintf("(SELECT estimate FROM %s WHERE effect = 'ran_pars' AND re_group = '%s' AND term = '%s')", tdy, grp, term)
rvq <- function(col) sprintf("(SELECT %s FROM %s WHERE effect = 'ran_vals' AND re_level = 'g3')", col, tdy)
L <- c(L, checks("glmm_tidy_by ran_pars / ran_vals: broom.mixed::tidy(effects = 'ran_pars' / 'ran_vals', conf.int = TRUE)",
  "(SELECT 1) s", c(rpq("g", "sd__(Intercept)"), rpq("Residual", "sd__Observation"), rvq("estimate"), rvq("std_error"),
                    rvq("conf_low"), rvq("conf_high")),
  c(rp$estimate[rp$group == "g"], rp$estimate[rp$group == "Residual"], rv3$estimate, rv3$std.error,
    rv3$conf.low, rv3$conf.high), 1e-6))

# glmm_glance_by
gl <- as.data.frame(glance(fa))
glq <- function(metric) sprintf("(SELECT value FROM glmm_glance_by('d4o', grp, ly, [q1], g) WHERE metric = '%s')", metric)
L <- c(L, checks("glmm_glance_by: broom.mixed::glance (nobs, sigma, logLik, AIC, BIC, df.residual)",
  "(SELECT 1) s", glq(c("n_observations", "sigma", "log_likelihood", "aic", "bic", "df_residual")),
  c(gl$nobs, gl$sigma, gl$logLik, gl$AIC, gl$BIC, gl$df.residual), 1e-6))

# glmm_augment_by
au <- as.data.frame(augment(fa))
pop <- predict(fa, re.form = NA)
aug <- "glmm_augment_by('d4o', grp, ly, [q1], g)"
auq <- function(col, row) sprintf("(SELECT %s FROM %s WHERE row_id = %d)", col, aug, row)
L <- c(L, checks("glmm_augment_by rows 1 / 20 / 48: broom.mixed::augment .fitted / .resid, predict(re.form = NA)",
  "(SELECT 1) s", c(auq("fitted", 1), auq("residual", 1), auq("fitted", 20), auq("residual", 48),
                    auq("fitted_population", 20), auq("pearson_residual", 48)),
  c(au$.fitted[1], au$.resid[1], au$.fitted[20], au$.resid[48], pop[20], residuals(fa, type = "pearson")[48]), 1e-6))

# =============================================================================
# B. Gaussian random slope: pc ~ q1 + (1 + q1 | g) (ly's slope variance is on the
#    boundary there, a singular fit)
# =============================================================================
fb <- lmer(pc ~ q1 + (1 + q1 | g), d4, REML = TRUE, control = lctl)
sb <- satt(fb)
fit_b <- "(SELECT glmm_fit_agg(pc, [q1], g, {'compute_inference': true, 'random': [1]}) AS r FROM d4) s"
se_b <- condvar_se(fb, "g")
L <- c(L, checks("random slope, lmer(pc ~ q1 + (1 + q1 | g)): lmerTest Satterthwaite df and p; BLUP SEs of g1 (intercept, slope)",
  fit_b, c("r.df[1]", "r.intercept_df", "r.p_values[1]", "r.ranef[1].effects_se[1]", "r.ranef[1].effects_se[2]",
           "r.std_errors[1]"),
  c(sb[2, "df"], sb[1, "df"], sb[2, "Pr(>|t|)"], se_b[1, 1], se_b[1, 2], sb[2, "Std. Error"]), 1e-5))
rpb <- as.data.frame(tidy(fb, effects = "ran_pars"))
tdb <- "glmm_tidy_by('d4o', grp, pc, [q1], g, options := {'random': [1]}, names := ['q1'], re_names := ['g'])"
rpbq <- function(term) sprintf("(SELECT estimate FROM %s WHERE effect = 'ran_pars' AND term = '%s')", tdb, term)
L <- c(L, checks("random slope: glmm_tidy_by ran_pars sd__(Intercept), sd__q1, cor__(Intercept).q1 (broom.mixed)",
  "(SELECT 1) s", c(rpbq("sd__(Intercept)"), rpbq("sd__q1"), rpbq("cor__(Intercept).q1")),
  c(rpb$estimate[rpb$term == "sd__(Intercept)"], rpb$estimate[rpb$term == "sd__q1"],
    rpb$estimate[rpb$term == "cor__(Intercept).q1"]), 1e-5))

# =============================================================================
# C. Poisson random intercept: Wald (the non-gaussian default)
# =============================================================================
fc <- glmer(pc ~ q1 + (1 | g), d4, family = poisson, nAGQ = 0, control = gctl)
cc <- coef(summary(fc))
cic <- confint(fc, parm = "beta_", method = "Wald")
se_c <- condvar_se(fc, "g")
fit_c <- "(SELECT glmm_fit_agg(pc, [q1], g, {'family': 'poisson', 'compute_inference': true}) AS r FROM d4) s"
L <- c(L, checks("poisson: summary(glmer(nAGQ = 0)) z / Pr(>|z|), confint(method = 'Wald'), BLUP SE of g1",
  fit_c, c("r.std_errors[1]", "r.z_values[1]", "r.p_values[1]", "r.ci_lower[1]", "r.ci_upper[1]", "r.ranef[1].se"),
  c(cc[2, 2], cc[2, 3], cc[2, 4], cic[2, 1], cic[2, 2], se_c[1, 1]), 1e-5))
L <- c(L, "# poisson: Wald inference, no degrees of freedom",
  "query I", paste("SELECT r.df IS NULL FROM", fit_c, ""), "----", "true", "")
auc <- "glmm_augment_by('d4o', grp, pc, [q1], g, options := {'family': 'poisson'})"
aucq <- function(col, row) sprintf("(SELECT %s FROM %s WHERE row_id = %d)", col, auc, row)
L <- c(L, checks("poisson: glmm_augment_by fitted (response scale), population fitted, Pearson residual",
  "(SELECT 1) s", c(aucq("fitted", 5), aucq("fitted_population", 5), aucq("pearson_residual", 5), aucq("residual", 30)),
  c(fitted(fc)[5], predict(fc, re.form = NA, type = "response")[5], residuals(fc, type = "pearson")[5],
    residuals(fc, type = "response")[30]), 1e-5))
L <- c(L, "# poisson has no residual SD row",
  "query I",
  "SELECT count(*) FROM glmm_tidy_by('d4o', grp, pc, [q1], g, options := {'family': 'poisson'}) WHERE re_group = 'Residual';",
  "----", "0", "")

# =============================================================================
# D. Crossed random intercepts: (1 | g) + (1 | h)
# =============================================================================
fd <- lmer(lc ~ q1 + (1 | g) + (1 | hf), d4, REML = TRUE, control = lctl)
sd_ <- satt(fd)
rpd <- as.data.frame(tidy(fd, effects = "ran_pars"))
tdd <- "glmm_tidy_by('d4o', grp, lc, [q1, h], g, options := {'groups': [2]}, names := ['q1'], re_names := ['g', 'h'])"
rpdq <- function(grp) sprintf("(SELECT estimate FROM %s WHERE effect = 'ran_pars' AND re_group = '%s')", tdd, grp)
fxd <- function(col) sprintf("(SELECT %s FROM %s WHERE effect = 'fixed' AND term = 'q1')", col, tdd)
L <- c(L, checks("crossed: Satterthwaite df / p (lmerTest) and the SD of each factor (broom.mixed ran_pars)",
  "(SELECT 1) s", c(fxd("df"), fxd("p_value"), rpdq("g"), rpdq("h"), rpdq("Residual")),
  c(sd_[2, "df"], sd_[2, "Pr(>|t|)"], rpd$estimate[rpd$group == "g"], rpd$estimate[rpd$group == "hf"],
    rpd$estimate[rpd$group == "Residual"]), 1e-5))
se_d <- condvar_se(fd, "g")
L <- c(L, checks("crossed: BLUP SE of the first factor (g1, g8)",
  "(SELECT glmm_fit_agg(lc, [q1, h], g, {'groups': [2]}) AS r FROM d4) s", c("r.ranef[1].se", "r.ranef[8].se"),
  se_d[c(1, 8), 1], 1e-5))

writeLines(L, file.path(out_dir, "glmm_inference.test"))
cat("wrote", file.path(out_dir, "glmm_inference.test"), "\n")
