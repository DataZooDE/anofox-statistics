#!/usr/bin/env Rscript
# R references for test/sql/reference/pspline_reference.test (#316).
#
#   Rscript validation/generators/make_reference_pspline.R
#
# pspline_fit_agg / pspline_fit_predict_agg / pspline_fit_predict_by against
# mgcv::gam(y ~ s(x, bs = "ps", k, m = c(2, penalty_order)), method = "GCV.Cp").
#
# * lambda is mgcv's sp / S.scale (upstream's penalty is lambda * ||D beta||^2 on
#   the unscaled penalty matrix; mgcv rescales the penalty by S.scale).
# * edf is sum(gam$edf) (intercept included), sigma2 gam$sig2, se_fit
#   predict.gam(se.fit = TRUE) and r_squared 1 - RSS / TSS.
# * log_likelihood / aic / bic are logLik(gam), AIC(gam) and BIC(gam).
# * predict(model, [x]) rebuilds the stored smoother (FittedPSpline::from_parts)
#   and is checked against predict.gam(se.fit = TRUE) and the intervals below.
# * Intervals: fit -/+ qt((1 + level) / 2, n - edf) * s with s = se.fit
#   (confidence) or sqrt(se.fit^2 + sig2) (prediction); mgcv itself has no
#   prediction interval, so this is the textbook formula on mgcv's se.fit / sig2.
# * GCV-selected fits are compared at a relative 1e-5 (mgcv's Newton optimiser
#   and upstream's grid + golden-section search stop at slightly different
#   lambdas); fixed-lambda fits at 1e-8.

suppressMessages(library(mgcv))

fmt <- function(v) sprintf("%.17g", v)
close <- function(expr, value, tol) {
  sprintf("abs((%s) - (%s)) <= %s * (1 + abs(%s))", expr, fmt(value), tol, fmt(value))
}

check <- function(out, title, query, conds) {
  c(out,
    paste0("# ", title),
    paste0("query ", strrep("I", length(conds))),
    "SELECT",
    paste0("    ", conds, collapse = ",\n"),
    query,
    "----",
    paste(rep("true", length(conds)), collapse = "\t"),
    "")
}

insert <- function(out, table, df, types) {
  rows <- apply(df, 1, function(r) {
    paste0("(", paste(ifelse(is.na(r), "NULL", fmt(suppressWarnings(as.numeric(r)))), collapse = ", "), ")")
  })
  c(out, "statement ok",
    paste0("CREATE TABLE ", table, " (", paste(names(df), types, collapse = ", "), ");"), "",
    "statement ok", paste0("INSERT INTO ", table, " VALUES"), paste0(paste(rows, collapse = ",\n"), ";"), "")
}

set.seed(316)
n <- 60
d <- data.frame(t = 1:n, x = round(runif(n, 0, 10), 3))
d$y <- round(sin(d$x) + 0.3 * d$x + rnorm(n, sd = 0.3), 3)
grid <- sort(unique(d$x))
future <- c(-1, 0.5, 5, 11)  # two of them outside the data range: linear extension

out <- c("# name: test/sql/reference/pspline_reference.test",
         "# description: pspline_fit_agg / pspline_fit_predict_agg / pspline_fit_predict_by against mgcv::gam(y ~ s(x, bs = 'ps')) (#316)",
         "# group: [reference]",
         "#",
         "# GENERATED by validation/generators/make_reference_pspline.R -- do not edit",
         "# by hand; change the generator and re-run it instead.",
         paste0("# Reference: ", R.version.string, ", mgcv ", as.character(packageVersion("mgcv"))),
         "",
         "require anofox_statistics",
         "")
out <- insert(out, "d", d, "DOUBLE")
# The training rows plus four prediction rows (NULL y), in a scrambled order.
fut <- data.frame(t = n + seq_along(future), x = future, y = NA)
out <- c(out, "statement ok",
         paste0("CREATE TABLE p AS SELECT * FROM d UNION ALL SELECT * FROM (VALUES ",
                paste(sprintf("(%s, %s, NULL::DOUBLE)", fmt(fut$t), fmt(fut$x)), collapse = ", "),
                ") v(t, x, y);"), "")

gam_ps <- function(data, k, m, sp = NULL) {
  if (is.null(sp)) {
    gam(y ~ s(x, bs = "ps", k = k, m = c(2, m)), data = data, method = "GCV.Cp")
  } else {
    gam(y ~ s(x, bs = "ps", k = k, m = c(2, m), sp = sp), data = data)
  }
}
lambda_of <- function(g) g$full.sp[[1]] / g$smooth[[1]]$S.scale

fit_case <- function(out, title, call, g, tol) {
  p <- predict(g, newdata = data.frame(x = grid), se.fit = TRUE)
  rss <- sum(residuals(g)^2)
  tss <- sum((d$y - mean(d$y))^2)
  conds <- c(sprintf("len(m.x) = %d", length(grid)),
             sprintf("m.n_basis = %d", length(coef(g))),
             sprintf("m.n_observations = %d", n),
             close("m.lambda", lambda_of(g), tol),
             close("m.edf", sum(g$edf), tol),
             close("m.sigma2", g$sig2, tol),
             close("m.r_squared", 1 - rss / tss, tol),
             # mgcv's logLik.gam (Gaussian, sigma^2 = RSS / n, df = edf + 1), AIC and BIC
             close("m.log_likelihood", as.numeric(logLik(g)), tol),
             close("m.aic", AIC(g), tol),
             close("m.bic", BIC(g), tol))
  for (k in c(1, 17, 33, length(grid))) {
    conds <- c(conds, close(sprintf("m.x[%d]", k), grid[k], "1e-12"),
               close(sprintf("m.fitted[%d]", k), p$fit[k], tol),
               close(sprintf("m.se_fit[%d]", k), p$se.fit[k], tol))
  }
  check(out, title, sprintf("FROM (SELECT %s AS m FROM d)", call), conds)
}

# GCV-selected smoothing parameter
for (spec in list(list(k = 10, m = 2, opt = "{'n_basis': 10}"),
                  list(k = 20, m = 2, opt = "{'n_basis': 20}"),
                  list(k = 12, m = 3, opt = "{'n_basis': 12, 'penalty_order': 3}"),
                  list(k = 15, m = 1, opt = "{'k': 15, 'penalty_order': 1}"))) {
  g <- gam_ps(d, spec$k, spec$m)
  out <- fit_case(out, sprintf("GCV: s(x, bs = 'ps', k = %d, m = c(2, %d)), method = 'GCV.Cp'", spec$k, spec$m),
                  sprintf("pspline_fit_agg(y, x, %s)", spec$opt), g, "1e-5")
}

# Fixed smoothing parameter: sp = lambda * S.scale
g0 <- gam_ps(d, 10, 2, sp = 1)
lambda <- 0.25
gl <- gam_ps(d, 10, 2, sp = lambda * g0$smooth[[1]]$S.scale)
out <- fit_case(out, "fixed lambda 0.25: s(x, bs = 'ps', k = 10, sp = 0.25 * S.scale)",
                sprintf("pspline_fit_agg(y, x, {'n_basis': 10, 'lambda': %s})", fmt(lambda)), gl, "1e-8")

# fit_predict: the training rows' fits and the extrapolated / interpolated future rows
band_case <- function(out, title, call, g, interval, level, tol) {
  p <- predict(g, newdata = data.frame(x = future), se.fit = TRUE)
  ptr <- predict(g, newdata = data.frame(x = d$x), se.fit = TRUE)
  df <- n - sum(g$edf)
  q <- qt((1 + level) / 2, df)
  s <- if (interval == "confidence") p$se.fit else sqrt(p$se.fit^2 + g$sig2)
  conds <- c("count(*) = 64", "count(*) FILTER (WHERE r.is_training) = 60")
  for (j in seq_along(future)) {
    sel <- sprintf("max(r.%%s) FILTER (WHERE t = %d)", fut$t[j])
    conds <- c(conds, close(sprintf(sel, "yhat"), p$fit[j], tol),
               close(sprintf(sel, "yhat_lower"), p$fit[j] - q * s[j], tol),
               close(sprintf(sel, "yhat_upper"), p$fit[j] + q * s[j], tol))
  }
  for (t in c(1, 30, 60)) {
    conds <- c(conds, close(sprintf("max(r.yhat) FILTER (WHERE t = %d)", t), ptr$fit[t], tol))
  }
  query <- sprintf(paste0("FROM (SELECT unnest(l) AS r, unnest(ts) AS t FROM (SELECT %s AS l, ",
                          "list(t ORDER BY t) AS ts FROM p))"), call)
  check(out, title, query, conds)
}
out <- band_case(out, "fit_predict, fixed lambda, 90% prediction interval",
                 sprintf("pspline_fit_predict_agg(y, x, {'n_basis': 10, 'lambda': %s, 'confidence_level': 0.9} ORDER BY t)",
                         fmt(lambda)), gl, "prediction", 0.9, "1e-8")
out <- band_case(out, "fit_predict, fixed lambda, 95% confidence interval",
                 sprintf("pspline_fit_predict_agg(y, x, {'n_basis': 10, 'lambda': %s, 'interval': 'confidence'} ORDER BY t)",
                         fmt(lambda)), gl, "confidence", 0.95, "1e-8")
out <- band_case(out, "fit_predict, GCV, k = 12, m = c(2, 3), 95% prediction interval",
                 "pspline_fit_predict_agg(y, x, {'n_basis': 12, 'penalty_order': 3} ORDER BY t)",
                 gam_ps(d, 12, 3), "prediction", 0.95, "1e-5")

# predict(model, [x]) from the stored smoother: the fit at new x (two outside the data range),
# se_fit and the interval, as the fit_predict aggregate
stored_case <- function(out, title, call, g, interval, level, tol) {
  p <- predict(g, newdata = data.frame(x = future), se.fit = TRUE)
  q <- qt((1 + level) / 2, n - sum(g$edf))
  s <- if (interval == "confidence") p$se.fit else sqrt(p$se.fit^2 + g$sig2)
  conds <- character()
  for (j in seq_along(future)) {
    e <- sprintf("predict(m, [%s], {'interval': '%s', 'level': %s})", fmt(future[j]), interval, fmt(level))
    conds <- c(conds, close(sprintf("predict(m, [%s])", fmt(future[j])), p$fit[j], tol),
               close(sprintf("(%s).se_fit", e), p$se.fit[j], tol),
               close(sprintf("(%s).yhat_lower", e), p$fit[j] - q * s[j], tol),
               close(sprintf("(%s).yhat_upper", e), p$fit[j] + q * s[j], tol))
  }
  check(out, title, sprintf("FROM (SELECT %s AS m FROM d)", call), conds)
}
out <- stored_case(out, "predict(model, [x]) of a stored fit, fixed lambda, 90% prediction interval",
                   sprintf("pspline_fit_agg(y, x, {'n_basis': 10, 'lambda': %s})", fmt(lambda)), gl,
                   "prediction", 0.9, "1e-8")
out <- stored_case(out, "predict(model, [x]) of a stored fit, GCV, k = 12, m = c(2, 3), 95% confidence interval",
                   "pspline_fit_agg(y, x, {'n_basis': 12, 'penalty_order': 3})", gam_ps(d, 12, 3),
                   "confidence", 0.95, "1e-5")

# pspline_fit_predict_by: one smooth per group (group b is the mirrored response)
db <- d
db$y <- -d$y
ga <- gam_ps(d, 10, 2)
gb <- gam_ps(db, 10, 2)
out <- c(out, "statement ok",
         "CREATE TABLE g AS SELECT 'a' AS grp, t, x, y FROM p UNION ALL SELECT 'b', t, x, -y FROM p;", "")
pa <- predict(ga, newdata = data.frame(x = c(d$x[c(1, 45)], future)), se.fit = TRUE)
pb <- predict(gb, newdata = data.frame(x = c(d$x[c(1, 45)], future)), se.fit = TRUE)
ts <- c(1, 45, fut$t)
conds <- c("count(*) = 128", "count(*) FILTER (WHERE is_training) = 120")
for (j in seq_along(ts)) {
  conds <- c(conds,
             close(sprintf("max(yhat) FILTER (WHERE grp = 'a' AND t = %d)", ts[j]), pa$fit[j], "1e-5"),
             close(sprintf("max(yhat) FILTER (WHERE grp = 'b' AND t = %d)", ts[j]), pb$fit[j], "1e-5"))
}
q <- qt(0.975, n - sum(ga$edf))
conds <- c(conds, close("max(yhat_upper) FILTER (WHERE grp = 'a' AND t = 64)",
                        pa$fit[6] + q * sqrt(pa$se.fit[6]^2 + ga$sig2), "1e-5"))
out <- check(out, "pspline_fit_predict_by: per group, GCV, k = 10",
             "FROM pspline_fit_predict_by('g', grp, y, x, options := {'n_basis': 10})", conds)

writeLines(out, "test/sql/reference/pspline_reference.test")
cat("wrote test/sql/reference/pspline_reference.test\n")
