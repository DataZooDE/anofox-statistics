# --- Box-Cox ----------------------------------------------------------------
bc_ref <- function(fit, level = 0.95) {
  ll <- function(l) boxcox(fit, lambda = l, plotit = FALSE)$y
  grid <- seq(-2, 2, 1 / 10)
  g <- sapply(grid, ll)
  k <- which.max(g)
  opt <- optimize(ll, c(grid[max(k - 1, 1)], grid[min(k + 1, length(grid))]), maximum = TRUE, tol = 1e-12)
  cut <- opt$objective - qchisq(level, 1) / 2
  lo <- if (ll(-2) < cut) uniroot(function(l) ll(l) - cut, c(-2, opt$maximum), tol = 1e-13)$root else NA
  hi <- if (ll(2) < cut) uniroot(function(l) ll(l) - cut, c(opt$maximum, 2), tol = 1e-13)$root else NA
  list(lambda = opt$maximum, max = opt$objective, lo = lo, hi = hi, grid = grid, ll = g)
}
bc_conds <- function(r, n) c(close("b.lambda_hat", r$lambda, "1e-6"),
                             close("b.max_log_likelihood", r$max, "1e-9"),
                             close("b.ci_lower", r$lo, "1e-6"),
                             close("b.ci_upper", r$hi, "1e-6"),
                             close_list("b.lambdas", r$grid),
                             close_list("b.log_likelihood", r$ll),
                             sprintf("b.n_observations = %d", n))
query_true("boxcox(lm(mpg ~ wt + hp))", bc_conds(bc_ref(lm(mpg ~ wt + hp, data = d)), 32),
           "FROM (SELECT box_cox_agg(mpg, [wt, hp]) AS b FROM cars);")
query_true("boxcox(lm(mpg ~ 1)): intercept only", bc_conds(bc_ref(lm(mpg ~ 1, data = d)), 32),
           "FROM (SELECT box_cox_agg(mpg) AS b FROM cars);")
query_true("boxcox(lm(disp ~ hp)) at level 0.9", bc_conds(bc_ref(lm(disp ~ hp, data = d), 0.9), 32),
           "FROM (SELECT box_cox_agg(disp, [hp], {'confidence_level': 0.9}) AS b FROM cars);")

