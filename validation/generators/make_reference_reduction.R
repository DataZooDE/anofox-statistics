# --- spearman2 ------------------------------------------------------------
s2 <- function(s, expr) c(close(paste0(expr, ".rho2"), s[["rho2"]]),
                          close(paste0(expr, ".statistic"), s[["F"]], "1e-8"),
                          sprintf("%s.df1 = %d AND %s.df2 = %d AND %s.n = %d", expr, s[["df1"]], expr, s[["df2"]], expr, s[["n"]]),
                          close(paste0(expr, ".p_value"), s[["P"]], "1e-8"),
                          close(paste0(expr, ".adjusted_rho2"), s[["Adjusted rho2"]]))
