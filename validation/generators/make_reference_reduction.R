# --- varclus ----------------------------------------------------------------
vc_cols <- c("mpg", "disp", "hp", "drat", "wt", "qsec")
X <- as.matrix(d[, vc_cols])
vc_conds <- function(v, cut = NULL) {
  p <- ncol(v$sim)
  c(paste(sapply(1:p, function(j) close_list(sprintf("v.similarity_matrix[%d]", j), v$sim[j, ])), collapse = " AND "),
    sprintf("v.merges = %s", str_list(apply(v$hclust$merge, 1, function(m) str_list(m)))),
    close_list("v.height", v$hclust$height),
    sprintf("v.dendrogram_order = %s", str_list(v$hclust$order)),
    if (is.null(cut)) "v.clusters IS NULL" else sprintf("v.clusters = %s", str_list(cutree(v$hclust, h = cut))),
    sprintf("v.variables = %s", str_list(sprintf("'%s'", vc_cols))))
}
x_sql <- paste0("[", paste(vc_cols, collapse = ", "), "]")
names_sql <- str_list(sprintf("'%s'", vc_cols))
query_true("varclus(x): squared Spearman, complete linkage",
           vc_conds(varclus(X)),
           sprintf("FROM (SELECT varclus_agg(%s, {'feature_names': %s}) AS v FROM cars);", x_sql, names_sql))
query_true("varclus(x, similarity = 'pearson', method = 'average'), cut at 0.5",
           vc_conds(varclus(X, similarity = "pearson", method = "average"), 0.5),
           sprintf("FROM (SELECT varclus_agg(%s, {'similarity': 'pearson', 'method': 'average', 'cut_height': 0.5, 'feature_names': %s}) AS v FROM cars);",
                   x_sql, names_sql))
query_true("varclus(x, similarity = 'hoeffding')",
           vc_conds(varclus(X, similarity = "hoeffding")),
           sprintf("FROM (SELECT varclus_agg(%s, {'similarity': 'hoeffding', 'feature_names': %s}) AS v FROM cars);",
                   x_sql, names_sql))

# --- redun ------------------------------------------------------------------
rd_conds <- function(r, vars) {
  later <- r$r2later[-1]
  c(sprintf("r.kept = %s", str_list(sprintf("'%s'", r$In))),
    sprintf("r.removed = %s", str_list(sprintf("'%s'", r$Out))),
    close_list("r.r_squared", unname(r$rsquared)),
    sprintf("len(r.r_squared_later) = %d", length(later)),
    if (length(later) == 0) "true" else
      paste(sapply(seq_along(later), function(k) close_list(sprintf("r.r_squared_later[%d]", k), unname(later[[k]]))),
            collapse = " AND "),
    close_list("r.r_squared_first", unname(r$rsq1[vars])),
    "len(r.too_few) = 0")
}
rd_vars <- c("mpg", "disp", "hp", "drat", "wt", "qsec")
rd_sql <- paste0("[", paste(rd_vars, collapse = ", "), "]")
rd_names <- str_list(sprintf("'%s'", rd_vars))
query_true("redun(~ mpg + disp + hp + drat + wt + qsec, r2 = 0.8)",
           rd_conds(redun(~ mpg + disp + hp + drat + wt + qsec, data = d, r2 = 0.8), rd_vars),
           sprintf("FROM (SELECT redun_agg(%s, {'r2': 0.8, 'feature_names': %s}) AS r FROM cars);", rd_sql, rd_names))
query_true("redun(..., r2 = 0.8, type = 'adjusted')",
           rd_conds(redun(~ mpg + disp + hp + drat + wt + qsec, data = d, r2 = 0.8, type = "adjusted"), rd_vars),
           sprintf("FROM (SELECT redun_agg(%s, {'r2': 0.8, 'type': 'adjusted', 'feature_names': %s}) AS r FROM cars);",
                   rd_sql, rd_names))
query_true("redun(..., r2 = 0.8, nk = 4)",
           rd_conds(redun(~ mpg + disp + hp + drat + wt + qsec, data = d, r2 = 0.8, nk = 4), rd_vars),
           sprintf("FROM (SELECT redun_agg(%s, {'r2': 0.8, 'nk': 4, 'feature_names': %s}) AS r FROM cars);", rd_sql, rd_names))
