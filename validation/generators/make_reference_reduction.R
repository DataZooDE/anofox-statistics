# |a - b| <= tol (1 + |b|) for a scalar SQL expression a
close <- function(expr, ref, tol = "1e-9") {
  if (is.na(ref)) return(sprintf("(%s) IS NULL", expr))
  sprintf("abs((%s) - (%s)) <= %s * (1 + abs(%s))", expr, sprintf("%.15g", ref), tol, sprintf("%.15g", ref))
}
# the same per element of a list (and equal length)
close_list <- function(expr, ref, tol = "1e-9") {
  sprintf("len(%s) = %d AND list_max(list_transform(range(1, %d), lambda _i: abs((%s)[_i] - (%s)[_i]) / (1 + abs((%s)[_i])))) <= %s",
          expr, length(ref), length(ref) + 1, expr, lst(ref), lst(ref), tol)
}
str_list <- function(v) paste0("[", paste(v, collapse = ", "), "]")

