#!/usr/bin/env Rscript
# R references for test/sql/reference/areg_reference.test (#320 follow-up).
#
#   Rscript validation/generators/make_reference_areg.R
#
# areg_fit_agg / areg_predict / areg_transform / areg_inverse against
# Hmisc::areg(x, y, xtype, ytype, nk): the coefficients of the predictor and
# response bases (xcoefficients / ycoefficients, intercept first), rsquared,
# mad / med, xdf / ydf, the knots (xparms / yparms); predict.areg(type = 'lp'
# and 'fitted') at new rows, the response transformation f$ytrans(y, coef =
# f$ycoefficients) and its inverse f$yinv(t). For a linear response Hmisc's
# ycoefficients is 1; the extension reports the intercept-first [0, 1]. The scalars rebuild the stored
# model (upstream Areg::from_parts) from the STRUCT.

suppressMessages(library(Hmisc))

fmt <- function(v) sprintf("%.17g", v)
close <- function(expr, value, tol) {
  sprintf("abs((%s) - (%s)) <= %s * (1 + abs(%s))", expr, fmt(value), tol, fmt(value))
}

out <- c("# name: test/sql/reference/areg_reference.test",
         "# description: areg_fit_agg / areg_predict / areg_transform / areg_inverse against Hmisc::areg (#320 follow-up)",
         "# group: [reference]",
         "#",
         "# GENERATED by validation/generators/make_reference_areg.R -- do not edit",
         "# by hand; change the generator and re-run it instead.",
         paste0("# Reference: ", R.version.string, ", Hmisc ", as.character(packageVersion("Hmisc"))),
         "",
         "require anofox_statistics",
         "")

check <- function(out, title, query, conds) {
  for (s in seq(1, length(conds), by = 8)) {
    chunk <- conds[s:min(length(conds), s + 7)]
    out <- c(out, paste0("# ", title), paste0("query ", strrep("I", length(chunk))), "SELECT",
             paste0("    ", chunk, collapse = ",\n"), query, "----",
             paste(rep("true", length(chunk)), collapse = "\t"), "")
  }
  out
}

set.seed(20261106)
n <- 150
x1 <- round(rnorm(n), 3)
x2 <- round(runif(n), 3)
g <- sample(1:3, n, TRUE)
y <- round(exp(0.5 + 0.5 * x1 + sin(2 * x2) + c(0, 0.4, -0.3)[g] + rnorm(n, sd = 0.3)), 4)
X <- cbind(x1, x2, g)
rows <- sprintf("(%d, %s, %s, %s, %s)", seq_len(n), fmt(x1), fmt(x2), fmt(g), fmt(y))
out <- c(out, "statement ok", "CREATE TABLE d (id INTEGER, x1 DOUBLE, x2 DOUBLE, g DOUBLE, y DOUBLE);", "",
         "statement ok", "INSERT INTO d VALUES", paste0(paste(rows, collapse = ",\n"), ";"), "")

nd <- cbind(x1 = c(-1, 0, 0.5, 2.5), x2 = c(0.2, 0.5, 0.9, 0.1), g = c(1, 2, 3, 2))
nd_sql <- sprintf("[%s, %s, %s]", fmt(nd[, 1]), fmt(nd[, 2]), fmt(nd[, 3]))

fit_case <- function(out, title, call, f, tol, spline_y) {
  # A linear response: Hmisc reports ycoefficients = 1 (no intercept), the
  # extension (upstream) intercept-first [0, 1] -- the same transformation.
  if (!spline_y) f$ycoefficients <- c(0, f$ycoefficients)
  conds <- c(sprintf("len(m.x_coefficients) = %d", length(f$xcoefficients)),
             sprintf("len(m.y_coefficients) = %d", length(f$ycoefficients)),
             sprintf("m.x_df = [%s]", paste(f$xdf, collapse = ", ")),
             sprintf("m.y_df = %d", f$ydf),
             sprintf("m.n_observations = %d", n),
             close("m.r_squared", f$rsquared, tol))
  for (j in seq_along(f$xcoefficients)) {
    conds <- c(conds, close(sprintf("m.x_coefficients[%d]", j), f$xcoefficients[j], tol))
  }
  for (j in seq_along(f$ycoefficients)) {
    conds <- c(conds, close(sprintf("m.y_coefficients[%d]", j), f$ycoefficients[j], tol))
  }
  # xparms is named by predictor; a linear predictor has none (and no entry)
  for (k in seq_len(ncol(X))) {
    v <- suppressWarnings(as.numeric(f$xparms[[colnames(X)[k]]]))
    conds <- c(conds, sprintf("len(m.x_parameters[%d]) = %d", k, length(v)))
    for (j in seq_along(v)) {
      conds <- c(conds, close(sprintf("m.x_parameters[%d][%d]", k, j), v[j], "1e-12"))
    }
  }
  if (spline_y) {
    for (j in seq_along(f$yparms)) {
      conds <- c(conds, close(sprintf("m.y_parameters[%d]", j), f$yparms[j], "1e-12"))
    }
    conds <- c(conds, close("m.mad", f$mad, tol), close("m.med", f$med, tol))
  }
  lp <- predict(f, nd)
  fitted <- predict(f, nd, type = "fitted")
  for (r in seq_len(nrow(nd))) {
    conds <- c(conds, close(sprintf("areg_predict(m, %s)", nd_sql[r]), lp[r], tol),
               close(sprintf("areg_predict(m, %s, {'type': 'fitted'})", nd_sql[r]), fitted[r], tol))
  }
  yy <- c(min(y), 1, median(y), 5, max(y))
  ty <- f$ytrans(yy, coef = f$ycoefficients)
  for (j in seq_along(yy)) {
    conds <- c(conds, close(sprintf("areg_transform(m, %s)", fmt(yy[j])), ty[j], tol))
  }
  tt <- c(f$linear.predictors[c(1, 50)], -0.5, 0.4)
  inv <- f$yinv(tt)
  for (j in seq_along(tt)) {
    conds <- c(conds, close(sprintf("areg_inverse(m, %s)", fmt(tt[j])), inv[j], tol))
  }
  check(out, title, sprintf("FROM (SELECT %s AS m FROM d)", call), conds)
}

# smooth y, smooth x1 and x2, categorical g (canonical correlation)
f <- areg(X, y, xtype = c("s", "s", "c"), nk = 4)
out <- fit_case(out, "areg(x, y, xtype = c('s', 's', 'c'), nk = 4)",
                "areg_fit_agg(y, [x1, x2, g], {'x_types': ['s', 's', 'c']})", f, "1e-8", TRUE)

# linear y: ordinary least squares on the predictor bases; nk = 5
fl <- areg(X, y, xtype = c("s", "l", "c"), ytype = "l", nk = 5)
out <- fit_case(out, "areg(x, y, xtype = c('s', 'l', 'c'), ytype = 'l', nk = 5)",
                "areg_fit_agg(y, [x1, x2, g], {'x_types': ['s', 'l', 'c'], 'y_type': 'l', 'nk': 5})", fl, "1e-8",
                FALSE)

writeLines(out, "test/sql/reference/areg_reference.test")
cat("wrote test/sql/reference/areg_reference.test\n")
