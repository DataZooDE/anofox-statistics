# Reference values for ordinal regression (#313): ordinal_fit_agg / ordinal_predict
# against rms::orm and MASS::polr, continuation_ratio_fit_agg against
# rms::cr.setup + lrm. Writes test/sql/reference/ordinal_reference.test.
#
#   Rscript validation/generators/make_reference_ordinal.R
#
# Requires rms, MASS and numDeriv.
#
# Parameterisation: the extension reports rms::orm's intercepts alpha_j of
# P(Y >= y_{j+1}) = F(alpha_j + x'beta); MASS::polr's cut-points are
# zeta_j = -alpha_j with the same slopes. The proportional-odds score test has
# no packaged R implementation; as upstream anofox-regression's own validation,
# it is U' I^-1 U of the partial proportional-odds log-likelihood at the orm
# estimate, with the score U and the information I by numDeriv. The Wald z and
# p-values are coef / sqrt(diag(vcov)) and 2 * pnorm(-|z|). Predicted quantiles
# with confidence limits are rms::Quantile.orm(q, X =, conf.int = 0.95, method =).

suppressPackageStartupMessages({
  library(rms)
  library(MASS)
  library(numDeriv)
})

out <- "test/sql/reference/ordinal_reference.test"
num <- function(v) sprintf("%.15g", v)
close <- function(expr, ref, tol) sprintf("abs((%s) - (%s)) <= %s * (1 + abs(%s))", expr, num(ref), tol, num(ref))

L <- character()
w <- function(...) L <<- c(L, paste0(...))

check <- function(title, from, conds) {
  for (s in seq(1, length(conds), by = 6)) {
    chunk <- conds[s:min(length(conds), s + 5)]
    w("# ", title)
    w("query ", strrep("I", length(chunk)))
    w("SELECT")
    w(paste0("    ", chunk, collapse = ",\n"))
    w(from)
    w("----")
    w(paste(rep("true", length(chunk)), collapse = "\t"))
    w("")
  }
}

# Fixed dataset: four ordered levels with non-consecutive values (1, 2, 3, 5)
# from a proportional-odds model, case weights and an offset.
set.seed(313)
n <- 140
x1 <- round(rnorm(n), 3)
x2 <- rbinom(n, 1, 0.4)
off <- round(runif(n, -0.3, 0.3), 3)
lin <- 0.9 * x1 - 0.7 * x2
cat_ <- cut(lin + rlogis(n), c(-Inf, -1, 0, 1, Inf), labels = FALSE)
lv <- c(1, 2, 3, 5)
y <- lv[cat_]
wt <- round(runif(n, 0.5, 2), 2)
d <- data.frame(id = seq_len(n), y = y, x1 = x1, x2 = x2, off = off, wt = wt)
X <- cbind(x1, x2)
k <- 4
m <- k - 1

w("# name: test/sql/reference/ordinal_reference.test")
w("# description: ordinal_fit_agg / ordinal_predict / continuation_ratio_fit_agg (#313) vs rms::orm, MASS::polr, rms::cr.setup + lrm")
w("# group: [reference]")
w("#")
w("# GENERATED by validation/generators/make_reference_ordinal.R -- do not edit by hand.")
w("# Reference: rms ", as.character(packageVersion("rms")), ", MASS ", as.character(packageVersion("MASS")),
  ", numDeriv ", as.character(packageVersion("numDeriv")), ".")
w("# intercepts are orm's alpha_j of P(Y >= y_{j+1}); polr's zeta_j = -alpha_j.")
w("")
w("require anofox_statistics")
w("")
w("statement ok")
w("CREATE TABLE d (id INTEGER, y DOUBLE, x1 DOUBLE, x2 DOUBLE, off DOUBLE, wt DOUBLE);")
w("")
w("statement ok")
w("INSERT INTO d VALUES")
w(paste(sprintf("(%d, %s, %s, %s, %s, %s)", d$id, num(d$y), num(d$x1), num(d$x2), num(d$off), num(d$wt)),
        collapse = ",\n"), ";")
w("")

ids <- c(1, 17, 58, 99, 140)

# Score test of proportional odds for all slopes (partial PO alternative).
po_score <- function(f, family, wts = rep(1, n)) {
  cdf <- switch(family, logistic = plogis, probit = pnorm)
  a <- coef(f)[1:m]
  b <- coef(f)[-(1:m)]
  p <- ncol(X)
  ll <- function(par) {
    al <- par[1:m]
    bt <- matrix(par[m + seq_len(m * p)], nrow = p)
    cum <- sapply(1:m, function(j) cdf(al[j] + X %*% bt[, j]))
    cum <- cbind(1, cum, 0)
    sum(wts * log(cum[cbind(1:n, cat_)] - cum[cbind(1:n, cat_ + 1)]))
  }
  par0 <- c(a, rep(b, m))
  g <- grad(ll, par0)
  H <- hessian(ll, par0)
  as.numeric(t(g) %*% solve(-H, g))
}

fit_checks <- function(title, sql, f, family, po = NULL, extra = character()) {
  from <- sprintf("FROM (SELECT %s AS m FROM d) t;", sql)
  cf <- coef(f)
  V <- vcov(f, intercepts = "all")
  se <- sqrt(diag(V))
  conds <- character()
  for (j in 1:m) {
    conds <- c(conds, close(sprintf("m.intercepts[%d]", j), cf[j], "1e-6"),
               close(sprintf("m.intercept_std_errors[%d]", j), se[j], "1e-5"))
  }
  for (j in seq_len(length(cf) - m)) {
    z <- cf[m + j] / se[m + j]
    conds <- c(conds, close(sprintf("m.coefficients[%d]", j), cf[m + j], "1e-6"),
               close(sprintf("m.std_errors[%d]", j), se[m + j], "1e-5"),
               close(sprintf("m.z_values[%d]", j), z, "1e-5"),
               close(sprintf("m.p_values[%d]", j), 2 * pnorm(-abs(z)), "1e-5"))
  }
  conds <- c(conds,
             # with an offset orm's deviance is (null, intercepts + offset, model)
             close("m.log_likelihood", -f$deviance[length(f$deviance)] / 2, "1e-8"),
             close("m.null_log_likelihood", -f$deviance[length(f$deviance) - 1] / 2, "1e-8"),
             close("m.lr_chisq", f$stats[["Model L.R."]], "1e-6"),
             close("m.aic", AIC(f), "1e-8"),
             "m.converged", sprintf("m.link = '%s'", family), "m.levels = [1.0, 2.0, 3.0, 5.0]",
             sprintf("m.n_observations = %d", n), extra)
  if (!is.null(po)) {
    conds <- c(conds, close("m.po_test_statistic", po, "1e-5"), sprintf("m.po_test_df = %d", (m - 1) * ncol(X)),
               close("m.po_test_p_value", pchisq(po, (m - 1) * ncol(X), lower.tail = FALSE), "1e-5"))
  }
  check(sprintf("ordinal_fit_agg %s vs rms::orm", title), from, conds)
}

pred_checks <- function(title, sql, f, newdata, x_sql) {
  from <- sprintf("FROM (SELECT %s AS m FROM d) t;", sql)
  pr <- predict(f, newdata, type = "fitted.ind")
  ex <- predict(f, newdata, type = "fitted")
  conds <- character()
  for (r in seq_along(ids)) {
    i <- ids[r]
    q <- function(type, idx) sprintf("(SELECT ordinal_predict(t.m, %s, {'type': '%s'})[%d] FROM d WHERE id = %d)",
                                     x_sql, type, idx, i)
    for (j in 1:k) conds <- c(conds, close(q("prob", j), pr[r, j], "1e-6"))
    for (j in 1:m) conds <- c(conds, close(q("exceedance", j), ex[r, j], "1e-6"))
    conds <- c(conds, close(sprintf("(SELECT predict(t.m, %s, {'type': 'mean'}) FROM d WHERE id = %d)", x_sql, i),
                            sum(lv * pr[r, ]), "1e-6"),
               sprintf("(SELECT ordinal_predict(t.m, %s) FROM d WHERE id = %d) = %s", x_sql, i,
                       num(lv[which.max(pr[r, ])])))
  }
  check(sprintf("ordinal_predict %s vs predict.orm (fitted.ind, fitted)", title), from, conds)
}

ctl <- list(eps = 1e-10, gradtol = 1e-10, maxit = 200)
orm_fit <- function(formula, ...) orm(formula, data = d, x = TRUE, y = TRUE, eps = 1e-10, maxit = 200, ...)

# 1. logistic (proportional odds), with the PO score test and polr
f <- orm_fit(y ~ x1 + x2)
fit_checks("logistic", "ordinal_fit_agg(y, [x1, x2])", f, "logistic", po = po_score(f, "logistic"))
pred_checks("logistic", "ordinal_fit_agg(y, [x1, x2])", f, d[ids, ], "[x1, x2]")

pf <- polr(factor(y) ~ x1 + x2, data = d, Hess = TRUE, control = list(reltol = 1e-14, maxit = 1000))
pse <- sqrt(diag(vcov(pf)))
conds <- character()
for (j in 1:m) conds <- c(conds, close(sprintf("-m.intercepts[%d]", j), pf$zeta[j], "1e-5"),
                          close(sprintf("m.intercept_std_errors[%d]", j), pse[2 + j], "1e-4"))
for (j in 1:2) conds <- c(conds, close(sprintf("m.coefficients[%d]", j), coef(pf)[j], "1e-5"),
                          close(sprintf("m.std_errors[%d]", j), pse[j], "1e-4"))
conds <- c(conds, close("m.log_likelihood", as.numeric(logLik(pf)), "1e-7"))
check("ordinal_fit_agg logistic vs MASS::polr (zeta = -alpha)", "FROM (SELECT ordinal_fit_agg(y, [x1, x2]) AS m FROM d) t;", conds)
pc <- as.numeric(as.character(predict(pf, d[ids, ], type = "class")))
conds <- sprintf("(SELECT predict(t.m, [x1, x2]) FROM d WHERE id = %d) = %s", ids, num(pc))
check("ordinal_predict class vs predict.polr(type = 'class')", "FROM (SELECT ordinal_fit_agg(y, [x1, x2]) AS m FROM d) t;", conds)

# 2. the other links (probit with the PO score test)
for (fam in c("probit", "loglog", "cloglog", "cauchit")) {
  f <- orm_fit(y ~ x1 + x2, family = fam)
  sql <- sprintf("ordinal_fit_agg(y, [x1, x2], {'link': '%s'})", fam)
  fit_checks(fam, sql, f, fam, po = if (fam == "probit") po_score(f, "probit") else NULL)
  pred_checks(fam, sql, f, d[ids, ], "[x1, x2]")
}

# 3. case weights (orm and polr agree)
f <- orm_fit(y ~ x1 + x2, weights = wt)
fit_checks("case weights", "ordinal_fit_agg(y, [x1, x2], wt, {'po_test': true})", f, "logistic",
           po = po_score(f, "logistic", wt))
pfw <- polr(factor(y) ~ x1 + x2, data = d, weights = wt, Hess = TRUE, control = list(reltol = 1e-14, maxit = 1000))
conds <- c(close("m.coefficients[1]", coef(pfw)[1], "1e-5"), close("m.coefficients[2]", coef(pfw)[2], "1e-5"),
           close("-m.intercepts[2]", pfw$zeta[2], "1e-5"), close("m.log_likelihood", as.numeric(logLik(pfw)), "1e-7"))
check("ordinal_fit_agg case weights vs MASS::polr(weights)", "FROM (SELECT ordinal_fit_agg(y, [x1, x2], wt, NULL) AS m FROM d) t;", conds)

# 4. offset: the offset column is x[2] (removed from the slopes); prediction adds it
f <- orm_fit(y ~ x1 + offset(off) + x2)
fit_checks("offset", "ordinal_fit_agg(y, [x1, off, x2], {'offset': 2})", f, "logistic",
           extra = c("m.offset_column = 2", "m.n_features = 2"))
# predict.orm ignores an offset in newdata; the extension adds it (as predict.glm), so the
# reference is F(alpha_j + x'beta + offset) from orm's estimates.
cf <- coef(f)
cum <- cbind(1, sapply(1:m, function(j) plogis(cf[j] + cf[["x1"]] * x1[ids] + cf[["x2"]] * x2[ids] + off[ids])), 0)
pr <- cum[, 1:k] - cum[, 2:(k + 1)]
conds <- character()
for (r in seq_along(ids)) for (j in 1:k) {
  conds <- c(conds, close(sprintf("(SELECT ordinal_predict(t.m, [x1, off, x2], {'type': 'prob'})[%d] FROM d WHERE id = %d)",
                                  j, ids[r]), pr[r, j], "1e-6"))
}
check("ordinal_predict offset vs orm estimates, F(alpha_j + x'beta + offset)",
      "FROM (SELECT ordinal_fit_agg(y, [x1, off, x2], {'offset': 2}) AS m FROM d) t;", conds)

# 5. penalty: orm(penalty = 3); the reported log-likelihood is unpenalized, the
# penalized one is -deviance / 2, and lr_df the effective d.f. of the slopes.
f <- orm_fit(y ~ x1 + x2, penalty = 3)
cf <- coef(f)
from <- "FROM (SELECT ordinal_fit_agg(y, [x1, x2], {'penalty': 3}) AS m FROM d) t;"
conds <- c(close("m.coefficients[1]", cf[m + 1], "1e-6"), close("m.coefficients[2]", cf[m + 2], "1e-6"),
           close("m.intercepts[1]", cf[1], "1e-6"), close("m.intercepts[3]", cf[3], "1e-6"),
           close("m.std_errors[1]", sqrt(diag(vcov(f)))[["x1"]], "1e-5"),
           close("m.penalized_log_likelihood", -f$deviance[2] / 2, "1e-8"),
           close("m.lr_df", sum(f$effective.df.diagonal[-(1:m)]), "1e-6"), "m.penalty = 3")
check("ordinal_fit_agg penalty vs rms::orm(penalty = 3)", from, conds)

# 6. continuation ratio: lrm on cr.setup data (equal slopes; x1 cohort-specific; weights)
s <- cr.setup(y)
dd <- data.frame(y = s$y, cohort = s$cohort, x1 = x1[s$subs], x2 = x2[s$subs])
cr_cases <- list(
  list(title = "equal slopes", sql = "continuation_ratio_fit_agg(y, [x1, x2])",
       f = lrm(y ~ cohort + x1 + x2, data = dd, tol = 1e-14, maxit = 100), cs = FALSE),
  list(title = "x1 cohort-specific", sql = "continuation_ratio_fit_agg(y, [x1, x2], {'cohort_specific': [1]})",
       f = lrm(y ~ cohort + x1 + x2 + cohort:x1, data = dd, tol = 1e-14, maxit = 100), cs = TRUE),
  list(title = "case weights", sql = "continuation_ratio_fit_agg(y, [x1, x2], wt, NULL)",
       f = suppressWarnings(lrm(y ~ cohort + x1 + x2, data = dd, weights = wt[s$subs], tol = 1e-14, maxit = 100)),
       cs = FALSE)
)
for (cs in cr_cases) {
  f <- cs$f
  cf <- coef(f)
  se <- sqrt(diag(vcov(f)))
  from <- sprintf("FROM (SELECT %s AS m FROM d) t;", cs$sql)
  conds <- character()
  for (j in seq_along(cf)) {
    conds <- c(conds, close(sprintf("m.coefficients[%d]", j), cf[j], "1e-6"),
               close(sprintf("m.std_errors[%d]", j), se[j], "1e-5"))
  }
  ll <- -f$deviance[2] / 2
  conds <- c(conds, close("m.log_likelihood", ll, "1e-8"), close("m.aic", -2 * ll + 2 * length(cf), "1e-8"),
             sprintf("m.n_records = %d", nrow(dd)), "m.converged", "m.levels = [1.0, 2.0, 3.0, 5.0]")
  check(sprintf("continuation_ratio_fit_agg %s vs rms::cr.setup + lrm", cs$title), from, conds)
  # P(Y = y_j | x): h_j = plogis(lp of cohort j), P_j = h_j prod_{c<j} (1 - h_c)
  conds <- character()
  for (i in ids) {
    nd <- data.frame(cohort = factor(levels(dd$cohort), levels = levels(dd$cohort)), x1 = x1[i], x2 = x2[i])
    h <- plogis(predict(f, nd))
    p <- c(h, 1) * c(1, cumprod(1 - h))
    for (j in 1:k) {
      conds <- c(conds, close(sprintf("(SELECT ordinal_predict(t.m, [x1, x2], {'type': 'prob'})[%d] FROM d WHERE id = %d)",
                                      j, i), p[j], "1e-6"))
    }
    conds <- c(conds, close(sprintf("(SELECT predict(t.m, [x1, x2], {'type': 'mean'}) FROM d WHERE id = %d)", i),
                            sum(lv * p), "1e-6"))
  }
  check(sprintf("ordinal_predict continuation ratio %s vs predict.lrm on cr.setup cohorts", cs$title), from, conds)
}

# 6. predicted quantiles with pointwise confidence limits (type 'quantile') vs rms::Quantile.orm(conf.int = ):
#    the model is rebuilt from the stored intercepts, slopes and information.
quant_checks <- function(title, sql, f, newdata, x_sql, data_ids, fam) {
  from <- sprintf("FROM (SELECT %s AS m FROM %s) t;", sql, if (is.null(data_ids)) "d" else "dc")
  qu <- Quantile(f)
  conds <- character()
  for (q in c(0.5, 0.9)) for (meth in c("interpolated", "discrete")) {
    z <- qu(q, X = newdata, conf.int = 0.95, method = meth)
    lim <- attr(z, "limits")
    for (r in seq_len(nrow(newdata))) {
      e <- sprintf("ordinal_predict(t.m, %s, {'type': 'quantile', 'q': %s, 'method': '%s'})",
                   x_sql[r], num(q), meth)
      conds <- c(conds, close(sprintf("(%s).yhat", e), z[r], "1e-6"),
                 close(sprintf("(%s).yhat_lower", e), lim$lower[r], "1e-5"),
                 close(sprintf("(%s).yhat_upper", e), lim$upper[r], "1e-5"))
    }
  }
  check(sprintf("ordinal_predict type 'quantile' %s vs rms::Quantile.orm(conf.int = 0.95)", title), from, conds)
}
nd <- as.matrix(d[ids[1:3], c("x1", "x2")])
nd_sql <- sprintf("[%s, %s]", num(nd[, 1]), num(nd[, 2]))
for (fam in c("logistic", "probit")) {
  f <- orm_fit(y ~ x1 + x2, family = fam)
  sql <- sprintf("ordinal_fit_agg(y, [x1, x2], {'link': '%s'})", fam)
  quant_checks(fam, sql, f, nd, nd_sql, NULL, fam)
}
