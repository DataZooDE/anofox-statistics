dc <- data.frame(yc = yc, x1 = x1, x2 = x2)
fc <- orm(yc ~ x1 + x2, data = dc, x = TRUE, y = TRUE, eps = 1e-10, maxit = 200)
quant_checks("continuous response", "ordinal_fit_agg(yc, [x1, x2])", fc, nd, nd_sql, TRUE, "logistic")

