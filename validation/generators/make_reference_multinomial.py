#!/usr/bin/env python3
"""scikit-learn references for test/sql/reference/multinomial_sklearn.test (#314).

Usage (from the repository root):
    uv run --no-project --with scikit-learn python3 validation/generators/make_reference_multinomial.py

multinomial_fit_agg minimises scikit-learn's LogisticRegression objective

    sum_i s_i l_i(W, b) + (1 / C) * (l1_ratio ||W||_1 + (1 - l1_ratio) / 2 ||W||_2^2)

(lambda = 1 / C, intercepts unpenalized). With K >= 3 classes l is the
softmax cross-entropy with one coefficient row per class (sklearn's
symmetric parameterization, coef_ of shape (K, p)); with two classes a single
row, the log-odds of the second class (coef_ of shape (1, p)).

The references are solved to a tight tolerance ('lbfgs' for ridge, 'saga' for
the L1 / elastic-net penalties) so they are the optimum rather than a solver
stopping point. Checked: coef_, intercept_, predict_proba, predict, score
(accuracy) and the weighted log-likelihood sum_i s_i log p_i(y_i), for ridge,
lasso and elastic-net fits, sample weights, no intercept, two classes and
integer labels. The unpenalized fit is checked against R's nnet::multinom by
make_reference_multinomial.R.
"""
import os
import warnings

import numpy as np
import sklearn
from sklearn.linear_model import LogisticRegression

OUT = os.path.join("test", "sql", "reference", "multinomial_sklearn.test")

# Fixed dataset (drawn once, rounded so the SQL literals are exact): three
# features, three classes drawn from a softmax model (not separable).
rng = np.random.default_rng(314)
N = 90
X = np.round(rng.normal(size=(N, 3)), 3)
B = np.array([[1.2, -0.7, 0.0], [-0.4, 0.9, 0.3], [-0.8, -0.2, -0.3]])
eta = X @ B.T + np.array([0.2, 0.1, -0.3])
P = np.exp(eta - eta.max(axis=1, keepdims=True))
P /= P.sum(axis=1, keepdims=True)
CODE = np.array([rng.choice(3, p=P[i]) for i in range(N)])
NAMES = np.array(["high", "low", "mid"])  # sorted, as the extension orders the classes
LABEL = NAMES[CODE]
W = np.round(rng.uniform(0.5, 2.0, size=N), 2)
# Two-class subset: the rows whose class is 'low' or 'mid'.
BIN = CODE != 0

lines = []


def emit(s=""):
    lines.append(s)


def close(expr, value, tol):
    return f"abs(({expr}) - ({value!r})) <= {tol} * (1 + abs({value!r}))"


def check(title, query, conditions):
    for start in range(0, len(conditions), 6):
        chunk = conditions[start:start + 6]
        emit(f"# {title}")
        emit("query " + "I" * len(chunk))
        emit("SELECT")
        emit(",\n".join("    " + c for c in chunk))
        emit(query)
        emit("----")
        emit("\t".join(["true"] * len(chunk)))
        emit()


def fit(x, y, c, l1_ratio, fit_intercept=True, weights=None):
    solver = "lbfgs" if l1_ratio == 0.0 else "saga"
    kw = dict(C=c, l1_ratio=l1_ratio, fit_intercept=fit_intercept, solver=solver, tol=1e-13, max_iter=10**6)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        try:
            m = LogisticRegression(**kw)
        except TypeError:  # older sklearn needs penalty
            m = LogisticRegression(penalty="elasticnet" if l1_ratio > 0 else "l2", **kw)
        return m.fit(x, y, sample_weight=weights)


emit("# name: test/sql/reference/multinomial_sklearn.test")
emit("# description: multinomial_fit_agg / multinomial_predict (#314) against scikit-learn LogisticRegression")
emit("# group: [reference]")
emit("#")
emit("# GENERATED by validation/generators/make_reference_multinomial.py -- do not edit")
emit("# by hand; change the generator and re-run it instead.")
emit(f"# Reference: scikit-learn {sklearn.__version__}, numpy {np.__version__}")
emit()
emit("require anofox_statistics")
emit()
emit("statement ok")
emit("CREATE TABLE d (id INTEGER, y VARCHAR, yi BIGINT, x1 DOUBLE, x2 DOUBLE, x3 DOUBLE, w DOUBLE);")
emit()
emit("statement ok")
emit("INSERT INTO d VALUES")
emit(",\n".join(
    f"({i + 1}, '{LABEL[i]}', {int(CODE[i]) * 10 - 5}, {float(X[i, 0])!r}, {float(X[i, 1])!r}, "
    f"{float(X[i, 2])!r}, {float(W[i])!r})" for i in range(N)) + ";")
emit()

ROWS = (0, 7, 33, 61, 89)


def model_checks(title, m, x, y, model_sql, tol, weights=None, int_labels=False):
    k_rows = m.coef_.shape[0]
    conds = []
    for k in range(k_rows):
        conds += [close(f"m.coefficients[{k + 1}][{j + 1}]", float(m.coef_[k, j]), tol) for j in range(x.shape[1])]
        conds.append(close(f"m.intercepts[{k + 1}]", float(m.intercept_[k]), tol))
    proba = m.predict_proba(x)
    s = np.ones(len(y)) if weights is None else weights
    loglik = float(np.sum(s * np.log(proba[np.arange(len(y)), np.searchsorted(m.classes_, y)])))
    conds += [close("m.log_likelihood", loglik, tol), close("m.accuracy", float(m.score(x, y)), "1e-12"),
              f"m.n_classes = {len(m.classes_)}", f"len(m.coefficients) = {k_rows}"]
    if int_labels:
        conds.append(f"m.classes = {[int(c) for c in m.classes_]}")
    else:
        conds.append("m.classes = [" + ", ".join(f"'{c}'" for c in m.classes_) + "]")
    check(f"{title}: coef_, intercept_, log-likelihood, score", f"FROM ({model_sql}) t;", conds)
    return proba


def predict_checks(title, m, x, model_sql, tol, rows=ROWS, cols="[x1, x2, x3]"):
    proba = m.predict_proba(x)
    pred = m.predict(x)
    conds = []
    for i in rows:
        for k in range(proba.shape[1]):
            conds.append(close(f"(SELECT multinomial_predict(t.m, {cols}, {{'type': 'prob'}})[{k + 1}] FROM d "
                               f"WHERE id = {i + 1})", float(proba[i, k]), tol))
    check(f"{title}: predict_proba", f"FROM ({model_sql}) t;", conds)
    def lit(v):
        return f"'{v}'" if isinstance(v, str) else str(int(v))
    conds = [f"(SELECT predict(t.m, {cols}) FROM d WHERE id = {i + 1}) = {lit(pred[i])}" for i in rows]
    check(f"{title}: predict", f"FROM ({model_sql}) t;", conds)


XS = "[x1, x2, x3]"

# ---- ridge (sklearn defaults C = 1, l1_ratio = 0) -------------------------------
m = fit(X, LABEL, 1.0, 0.0)
sql = f"SELECT multinomial_fit_agg(y, {XS}) AS m FROM d"
model_checks("multinomial_fit_agg default (C = 1, ridge)", m, X, LABEL, sql, "1e-6")
predict_checks("multinomial_fit_agg default", m, X, sql, "1e-6")

# Integer labels: the same fit, the classes as BIGINT.
mi = fit(X, CODE * 10 - 5, 1.0, 0.0)
sql = f"SELECT multinomial_fit_agg(yi, {XS}) AS m FROM d"
model_checks("multinomial_fit_agg BIGINT labels", mi, X, CODE * 10 - 5, sql, "1e-6", int_labels=True)
predict_checks("multinomial_fit_agg BIGINT labels", mi, X, sql, "1e-6")

# C = 0.2 as lambda = 5.
m = fit(X, LABEL, 0.2, 0.0)
sql = f"SELECT multinomial_fit_agg(y, {XS}, {{'lambda': 5}}) AS m FROM d"
model_checks("multinomial_fit_agg lambda = 5 (C = 0.2)", m, X, LABEL, sql, "1e-6")

# ---- lasso and elastic net (saga) --------------------------------------------------
for c, l1 in [(0.1, 1.0), (0.5, 0.5)]:
    m = fit(X, LABEL, c, l1)
    sql = f"SELECT multinomial_fit_agg(y, {XS}, {{'C': {c}, 'l1_ratio': {l1}}}) AS m FROM d"
    model_checks(f"multinomial_fit_agg C = {c}, l1_ratio = {l1}", m, X, LABEL, sql, "1e-5")
    zeros = [(k, j) for k in range(3) for j in range(3) if m.coef_[k, j] == 0.0]
    if zeros:
        check(f"multinomial_fit_agg C = {c}, l1_ratio = {l1}: coefficients sklearn sets to exactly 0",
              f"FROM ({sql}) t;", [f"t.m.coefficients[{k + 1}][{j + 1}] = 0" for k, j in zeros])
    predict_checks(f"multinomial_fit_agg C = {c}, l1_ratio = {l1}", m, X, sql, "1e-5")

# ---- sample weights ----------------------------------------------------------------
m = fit(X, LABEL, 2.0, 0.0, weights=W)
sql = f"SELECT multinomial_fit_agg(y, {XS}, w, {{'C': 2}}) AS m FROM d"
model_checks("multinomial_fit_agg sample weights, C = 2", m, X, LABEL, sql, "1e-6", weights=W)
predict_checks("multinomial_fit_agg sample weights", m, X, sql, "1e-6")
m = fit(X, LABEL, 1.0, 0.5, weights=W)
sql = f"SELECT multinomial_fit_agg(y, {XS}, w, {{'l1_ratio': 0.5}}) AS m FROM d"
model_checks("multinomial_fit_agg sample weights, elastic net l1_ratio = 0.5", m, X, LABEL, sql, "1e-5",
             weights=W)

# ---- no intercept ------------------------------------------------------------------
m = fit(X, LABEL, 1.0, 0.0, fit_intercept=False)
sql = f"SELECT multinomial_fit_agg(y, {XS}, {{'fit_intercept': false}}) AS m FROM d"
model_checks("multinomial_fit_agg fit_intercept = false", m, X, LABEL, sql, "1e-6")

# ---- two classes: one coefficient row (the log-odds of 'mid' against 'low') ---------
m = fit(X[BIN], LABEL[BIN], 1.0, 0.0)
sql = f"SELECT multinomial_fit_agg(y, {XS}) AS m FROM d WHERE y <> 'high'"
model_checks("multinomial_fit_agg two classes", m, X[BIN], LABEL[BIN], sql, "1e-6")
ids = np.flatnonzero(BIN)
proba = m.predict_proba(X)
conds = []
for i in ids[:4]:
    conds += [close(f"(SELECT multinomial_predict(t.m, {XS}, {{'type': 'prob'}})[{k + 1}] FROM d WHERE id = {i + 1})",
                    float(proba[i, k]), "1e-6") for k in range(2)]
check("multinomial_fit_agg two classes: predict_proba", f"FROM ({sql}) t;", conds)
m = fit(X[BIN], LABEL[BIN], 0.3, 1.0)
sql = f"SELECT multinomial_fit_agg(y, {XS}, {{'C': 0.3, 'l1_ratio': 1}}) AS m FROM d WHERE y <> 'high'"
model_checks("multinomial_fit_agg two classes, lasso C = 0.3", m, X[BIN], LABEL[BIN], sql, "1e-5")

with open(OUT, "w") as f:
    f.write("\n".join(lines).rstrip("\n") + "\n")
print(f"wrote {OUT}")
