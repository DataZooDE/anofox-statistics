#!/usr/bin/env python3
"""scikit-learn references for test/sql/reference/option_passthroughs_sklearn.test (#305).

Usage (from the repository root):
    uv run --no-project --with scikit-learn python3 validation/generators/make_reference_option_passthroughs.py

Checks two option pass-throughs against scikit-learn:

* quantile_fit_agg / quantile_fit_predict_agg {'alpha': a}: the L1-penalized
  quantile regression of sklearn.linear_model.QuantileRegressor(quantile=tau,
  alpha=a, solver="highs"), objective (1/n) sum rho_tau(r) + a * ||beta||_1
  with the intercept unpenalized.
* huber_fit_agg / huber_fit_predict_agg {'scale_method': 'joint'}: the joint
  coefficient / scale estimate of sklearn.linear_model.HuberRegressor
  (coef_, intercept_, scale_, outliers_), solved here to a tight tolerance so
  the reference is the optimum rather than an L-BFGS-B stopping point.
"""
import os

import numpy as np
import sklearn
from sklearn.linear_model import HuberRegressor, QuantileRegressor

OUT = os.path.join("test", "sql", "reference", "option_passthroughs_sklearn.test")

# Fixed dataset (drawn once, rounded so the SQL literals are exact): three
# features, heavy-tailed noise and a few gross outliers.
rng = np.random.default_rng(305)
N = 40
X = np.round(rng.normal(size=(N, 3)), 3)
noise = rng.standard_t(3, N)
Y = np.round(2.0 + X @ np.array([1.5, -0.8, 0.05]) + 0.5 * noise, 3)
Y[[3, 17, 29]] += np.array([9.0, -7.5, 11.0])
Y = np.round(Y, 3)

lines = []


def emit(s=""):
    lines.append(s)


def close(expr, value, tol):
    return f"abs(({expr}) - ({value!r})) <= {tol} * (1 + abs({value!r}))"


def check(title, query, conditions):
    for start in range(0, len(conditions), 6):
        chunk = conditions[start:start + 6]
        emit(f"# {title}")
        emit("query " + "I" * len(chunk))
        emit("SELECT")
        emit(",\n".join("    " + c for c in chunk))
        emit(query)
        emit("----")
        emit("\t".join(["true"] * len(chunk)))
        emit()


emit("# name: test/sql/reference/option_passthroughs_sklearn.test")
emit("# description: quantile L1 alpha and Huber joint scale (#305) against scikit-learn "
     "QuantileRegressor / HuberRegressor")
emit("# group: [reference]")
emit("#")
emit("# GENERATED by validation/generators/make_reference_option_passthroughs.py -- do not edit")
emit("# by hand; change the generator and re-run it instead.")
emit(f"# Reference: scikit-learn {sklearn.__version__}, numpy {np.__version__}")
emit()
emit("require anofox_statistics")
emit()
emit("statement ok")
emit("CREATE TABLE d (id INTEGER, y DOUBLE, x1 DOUBLE, x2 DOUBLE, x3 DOUBLE);")
emit()
emit("statement ok")
emit("INSERT INTO d VALUES")
emit(",\n".join(f"({i + 1}, {float(Y[i])!r}, {float(X[i, 0])!r}, {float(X[i, 1])!r}, {float(X[i, 2])!r})" for i in range(N)) + ";")
emit()

# ---- quantile regression with an L1 penalty ----------------------------------
for tau, alpha in [(0.5, 0.0), (0.5, 0.05), (0.5, 0.2), (0.8, 0.1)]:
    m = QuantileRegressor(quantile=tau, alpha=alpha, fit_intercept=True, solver="highs").fit(X, Y)
    conds = [close("m.intercept", float(m.intercept_), "1e-6")]
    conds += [close(f"m.coefficients[{j + 1}]", float(m.coef_[j]), "1e-6") for j in range(3)]
    check(f"quantile_fit_agg tau = {tau}, alpha = {alpha}: QuantileRegressor coef_ / intercept_",
          f"FROM (SELECT quantile_fit_agg(y, [x1, x2, x3], {{'tau': {tau}, 'alpha': {alpha}}}) AS m FROM d);",
          conds)
    if alpha == 0.2:
        # The penalty removes slopes exactly (a vertex of the LP).
        zeros = [j for j in range(3) if m.coef_[j] == 0.0]
        if zeros:
            check(f"quantile_fit_agg alpha = {alpha}: slopes sklearn sets to exactly 0",
                  f"FROM (SELECT quantile_fit_agg(y, [x1, x2, x3], {{'tau': {tau}, 'alpha': {alpha}}}) AS m FROM d);",
                  [f"abs(m.coefficients[{j + 1}]) <= 1e-9" for j in zeros])
    if alpha == 0.05:
        pred = m.predict(X)
        conds = [close(f"list_extract(p, {i + 1}).yhat", float(pred[i]), "1e-6") for i in (0, 9, 19, 39)]
        check(f"quantile_fit_predict_agg tau = {tau}, alpha = {alpha}: QuantileRegressor.predict",
              f"FROM (SELECT quantile_fit_predict_agg(y, [x1, x2, x3], {{'tau': {tau}, 'alpha': {alpha}}} "
              f"ORDER BY id) AS p FROM d);",
              conds)

# ---- Huber regression with the joint scale -----------------------------------
# sklearn's L-BFGS-B stops a little short of the optimum when the penalty is
# large (alpha = 0.1 here: ~5e-6 relative, at an objective 4e-8 above the
# minimum upstream's Newton iterations reach), so that case is compared at 1e-4.
for eps, alpha, tol in [(1.35, 0.0001, "1e-6"), (1.5, 0.1, "1e-4")]:
    m = HuberRegressor(epsilon=eps, alpha=alpha, fit_intercept=True, max_iter=100000, tol=1e-12).fit(X, Y)
    opts = f"{{'scale_method': 'joint', 'epsilon': {eps}, 'alpha': {alpha}, 'tolerance': 1e-12}}"
    conds = [close("m.intercept", float(m.intercept_), tol)]
    conds += [close(f"m.coefficients[{j + 1}]", float(m.coef_[j]), tol) for j in range(3)]
    conds += [close("m.scale", float(m.scale_), tol), f"m.n_outliers = {int(m.outliers_.sum())}"]
    check(f"huber_fit_agg scale_method = 'joint', epsilon = {eps}, alpha = {alpha}: HuberRegressor "
          "coef_ / intercept_ / scale_ / outliers_",
          f"FROM (SELECT huber_fit_agg(y, [x1, x2, x3], {opts}) AS m FROM d);",
          conds)
    if alpha == 0.0001:
        pred = m.predict(X)
        conds = [close(f"list_extract(p, {i + 1}).yhat", float(pred[i]), "1e-6") for i in (0, 9, 19, 39)]
        check("huber_fit_predict_agg scale_method = 'joint': HuberRegressor.predict",
              f"FROM (SELECT huber_fit_predict_agg(y, [x1, x2, x3], {opts} ORDER BY id) AS p FROM d);",
              conds)
        check("huber_fit (scalar) scale_method = 'joint': HuberRegressor coef_",
              f"FROM (SELECT huber_fit(list(y ORDER BY id), [list(x1 ORDER BY id), list(x2 ORDER BY id), list(x3 ORDER BY id)], {opts}) AS m FROM d);",
              [close(f"m.coefficients[{j + 1}]", float(m.coef_[j]), "1e-6") for j in range(3)])

with open(OUT, "w") as f:
    f.write("\n".join(lines).rstrip("\n") + "\n")
print(f"wrote {OUT}")
