# =============================================================================
# 1. lr_test(model_full, model_reduced)
# =============================================================================
lrt <- function(f0, f1) {
  a <- anova(f0, f1, test = "LRT")
  disp <- summary(f1)$dispersion
  c(stat = a$Deviance[2] / disp, df = a$Df[2], p = a$`Pr(>Chi)`[2])
}
p0 <- glm(cnt ~ z1, family = poisson, control = ctl)
p1 <- glm(cnt ~ z1 + z2 + z3, family = poisson, control = ctl)
r <- lrt(p0, p1)
L <- c(L, lr_checks("poisson: anova(glm(cnt ~ z1), glm(cnt ~ z1 + z2 + z3), test = 'LRT')",
  lr_src("poisson_fit_agg", "cnt", "[z1, z2, z3]", "[z1]"), r[1], r[2], r[3]))

b0 <- glm(bin ~ z1, family = binomial, control = ctl)
b1 <- glm(bin ~ z1 + z2 + z3, family = binomial, control = ctl)
r <- lrt(b0, b1)
L <- c(L, lr_checks("logistic: anova(glm(bin ~ z1, binomial), glm(bin ~ z1 + z2 + z3, binomial), test = 'LRT')",
  lr_src("logistic_fit_agg", "bin", "[z1, z2, z3]", "[z1]"), r[1], r[2], r[3]))
lt <- lrtest(b0, b1)
L <- c(L, lr_checks("logistic: lmtest::lrtest gives the same chi-square",
  lr_src("logistic_fit_agg", "bin", "[z1, z2, z3]", "[z1]"), lt$Chisq[2], lt$Df[2], lt$`Pr(>Chisq)`[2]))

pb0 <- glm(bin ~ z1, family = binomial(link = "probit"), control = ctl)
pb1 <- glm(bin ~ z1 + z2, family = binomial(link = "probit"), control = ctl)
r <- lrt(pb0, pb1)
L <- c(L, lr_checks("binomial probit: anova(..., test = 'LRT')",
  lr_src("binomial_fit_agg", "bin", "[z1, z2]", "[z1]", "'binomial_link': 'probit'"), r[1], r[2], r[3]))

g0 <- glm(gam ~ z1, family = Gamma(link = "log"), control = ctl)
g1 <- glm(gam ~ z1 + z2 + z3, family = Gamma(link = "log"), control = ctl)
r <- lrt(g0, g1)
L <- c(L,
  "# Gamma: anova.glm divides the deviance difference by the full model's Pearson",
  "# dispersion (summary(g1)$dispersion), as upstream lr_test does.",
  lr_checks("gamma: anova(glm(gam ~ z1, Gamma(log)), glm(gam ~ z1 + z2 + z3, Gamma(log)), test = 'LRT')",
    lr_src("gamma_fit_agg", "gam", "[z1, z2, z3]", "[z1]"), r[1], r[2], r[3]),
  checks("gamma: the dispersion used is summary(full)$dispersion",
    lr_src("gamma_fit_agg", "gam", "[z1, z2, z3]", "[z1]"), "r.dispersion", summary(g1)$dispersion, 1e-6))

n0 <- glm.nb(nb ~ z1, control = ctl)
n1 <- glm.nb(nb ~ z1 + z2 + z3, control = ctl)
lt <- lrtest(n0, n1)
L <- c(L,
  "# Negative Binomial: theta differs between the fits, so the test uses -2 log L",
  "# (lmtest::lrtest(glm.nb, glm.nb) = anova.negbin).",
  lr_checks("negbinom: lmtest::lrtest(glm.nb(nb ~ z1), glm.nb(nb ~ z1 + z2 + z3))",
    lr_src("negbinom_fit_agg", "nb", "[z1, z2, z3]", "[z1]"), lt$Chisq[2], lt$Df[2], lt$`Pr(>Chisq)`[2], 1e-5))

o0 <- lm(gam ~ z1); o1 <- lm(gam ~ z1 + z2 + z3)
