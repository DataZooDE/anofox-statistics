#
#   Rscript validation/generators/make_reference_likelihood.R   # from repo root
#
# Requires: MASS, lmtest, statmod, survival. The data are the literal d2 columns of
# make_reference_regression.R plus two deterministic columns (z3, expo).
# =============================================================================
