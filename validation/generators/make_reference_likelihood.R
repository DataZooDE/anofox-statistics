#
# Generates test/sql/reference/likelihood_reference.test (#310): lr_test,
# glm_score_test_agg and the profile_ci option of the GLM fit aggregates against
#
#   lr_test             anova(reduced, full, test = "LRT") for GLMs (the deviance
#                       difference, divided by the full model's dispersion for
#                       Gamma), lmtest::lrtest for lm and MASS::glm.nb
#   lr_test(model)      the model LR chi-square against the null model
#   glm_score_test_agg  anova(reduced, full, test = "Rao"), z statistics of
