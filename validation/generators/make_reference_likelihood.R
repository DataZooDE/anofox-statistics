L <- c(L, sc_checks("poisson, intercept-only reduced model: anova(glm(cnt ~ 1), glm(cnt ~ z1 + z2), test = 'Rao')",
  sc_src("cnt", "[]", "[z1, z2]", "'family': 'poisson'"), rao(pi0, pi1)))
po0 <- glm(cnt ~ z1 + offset(lexpo), family = poisson, control = ctl)
