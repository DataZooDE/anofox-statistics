nf1 <- glm(nb ~ z1 + z2 + z3, family = negative.binomial(th), control = ctl)
L <- c(L,
  sprintf("# negbinom: theta of the reduced glm.nb fit (%.10f), dispersion 1.", th),
  sc_checks("negbinom: anova(glm(nb ~ z1, negative.binomial(theta)), ... + z2 + z3, test = 'Rao', dispersion = 1)",
    sc_src("nb", "[z1]", "[z2, z3]", "'family': 'negbinom'"), rao(nf0, nf1, dispersion = 1), 1e-5),
  checks("negbinom: theta estimated from the reduced fit equals glm.nb's",
    sc_src("nb", "[z1]", "[z2, z3]", "'family': 'negbinom'"), "r.theta", th, 1e-5))

# =============================================================================
# 4. profile_ci on the GLM fit aggregates
# =============================================================================
ci_checks <- function(comment, agg, y, x, extra, fit, tol = 1e-5) {
  ci <- suppressMessages(confint(fit))
  k <- nrow(ci) - 1
  o <- sub("}$", paste0(", 'profile_ci': true", if (extra == "") "" else paste0(", ", extra), "}"), opt)
  src <- sprintf("(SELECT %s(%s, %s, %s) AS r FROM d) s", agg, y, x, o)
  checks(comment, src,
    c("r.intercept_conf_low", "r.intercept_conf_high",
      sprintf("r.conf_low[%d]", 1:k), sprintf("r.conf_high[%d]", 1:k)),
    c(ci[1, 1], ci[1, 2], ci[-1, 1], ci[-1, 2]), tol)
}
L <- c(L, ci_checks("poisson: confint(glm(cnt ~ z1 + z2, poisson))", "poisson_fit_agg", "cnt", "[z1, z2]", "", pi1))
L <- c(L, ci_checks("logistic: confint(glm(bin ~ z1 + z2 + z3, binomial))", "logistic_fit_agg", "bin", "[z1, z2, z3]", "", b1))
L <- c(L, ci_checks("binomial probit: confint(glm(bin ~ z1 + z2, binomial(probit)))", "binomial_fit_agg", "bin",
  "[z1, z2]", "'binomial_link': 'probit'", pb1))
L <- c(L, ci_checks("gamma: confint(glm(gam ~ z1 + z2 + z3, Gamma(log)))", "gamma_fit_agg", "gam", "[z1, z2, z3]", "", g1))
L <- c(L, ci_checks("poisson with offset: confint(glm(cnt ~ z1 + z2 + offset(lexpo), poisson))", "poisson_fit_agg", "cnt",
  "[z1, z2, lexpo]", "'offset': 3", po1))
ci <- suppressMessages(confint(glm(cnt ~ z1 + z2, family = poisson, control = ctl), level = 0.9))
L <- c(L, checks("poisson at level 0.9: confint(..., level = 0.9)",
  sprintf("(SELECT poisson_fit_agg(cnt, [z1, z2], {'tolerance': 1e-12, 'max_iterations': 100, 'profile_ci': true, 'confidence_level': 0.9}) AS r FROM d) s"),
  c("r.intercept_conf_low", "r.intercept_conf_high", "r.conf_low[1]", "r.conf_high[2]", "r.conf_level"),
  c(ci[1, 1], ci[1, 2], ci[2, 1], ci[3, 2], 0.9), 1e-5))
n2 <- glm.nb(nb ~ z1 + z2, control = ctl)
L <- c(L,
  "# negbinom: confint(glm.nb) profiles at the fitted theta (dispersion 1).",
  ci_checks("negbinom: confint(glm.nb(nb ~ z1 + z2))", "negbinom_fit_agg", "nb", "[z1, z2]", "", n2, 1e-4))

writeLines(L, file.path(out_dir, "likelihood_reference.test"))
cat("wrote", file.path(out_dir, "likelihood_reference.test"), "\n")
