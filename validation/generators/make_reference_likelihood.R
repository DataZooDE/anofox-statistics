  "(SELECT lr_test(aft_fit_agg(gam, [z1, z2, z3], bin, {'dist': 'weibull'}), aft_fit_agg(gam, [z1], bin, {'dist': 'weibull'})) AS r FROM d) s",
  lt$Chisq[2], lt$Df[2], lt$`Pr(>Chisq)`[2], 1e-5))

# =============================================================================
# 2. lr_test(model): against the null model
# =============================================================================
mlr <- function(f) {
  stat <- (f$null.deviance - f$deviance) / summary(f)$dispersion
  df <- f$df.null - f$df.residual
  c(stat, df, pchisq(stat, df, lower.tail = FALSE))
}
r <- mlr(p1)
L <- c(L, lr_checks("poisson model LR: null.deviance - deviance on 3 df",
  sprintf("(SELECT lr_test(poisson_fit_agg(cnt, [z1, z2, z3], %s)) AS r FROM d) s", opt), r[1], r[2], r[3]))
r <- mlr(b1)
L <- c(L, lr_checks("logistic model LR: null.deviance - deviance on 3 df",
  sprintf("(SELECT lr_test(logistic_fit_agg(bin, [z1, z2, z3], %s)) AS r FROM d) s", opt), r[1], r[2], r[3]))

stat <- 2 * diff(a1$loglik)
L <- c(L, lr_checks("aft weibull model LR: 2 * diff(survreg$loglik) on 3 df (print.survreg's Chisq)",
  "(SELECT lr_test(aft_fit_agg(gam, [z1, z2, z3], bin, {'dist': 'weibull'})) AS r FROM d) s",
  stat, 3, pchisq(stat, 3, lower.tail = FALSE), 1e-5))

# =============================================================================
# 3. glm_score_test_agg
# =============================================================================
rao <- function(f0, f1, dispersion = NULL) {
  a <- if (is.null(dispersion)) anova(f0, f1, test = "Rao") else anova(f0, f1, test = "Rao", dispersion = dispersion)
  # anova prints the unscaled score; its p-value uses Rao / dispersion (stat.anova).
  scale <- if (is.null(dispersion)) summary(f1)$dispersion else dispersion
  c(a$Rao[2] / scale, a$Df[2], a$`Pr(>Chi)`[2])
}
sc_src <- function(y, red, add, extra) {
  sprintf("(SELECT glm_score_test_agg(%s, %s, %s, {%s}) AS r FROM d) s", y, red, add, extra)
}
sc_checks <- function(comment, src, r, tol = 1e-6) {
  checks(comment, src, c("r.statistic", "r.df1", "r.p_value"), r, tol)
}
