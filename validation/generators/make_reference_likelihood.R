# ----------------------------------------------------------------- helpers ---
num <- function(v) ifelse(is.na(v), "NULL", sprintf("%.17g", v))
values_sql <- function(df) {
  rows <- apply(df, 1, function(r) paste0("(", paste(r, collapse = ", "), ")"))
  paste(rows, collapse = ",\n")
}
checks <- function(comment, from, exprs, refs, tol) {
  stopifnot(length(exprs) == length(refs))
  out <- character()
  idx <- seq_along(exprs)
  for (chunk in split(idx, ceiling(idx / 6))) {
    cols <- vapply(chunk, function(i) {
      sprintf("abs((%s) - (%s)) <= %g * (1 + abs(%s))", exprs[i], num(refs[i]), tol, num(refs[i]))
    }, "")
    out <- c(out,
      paste0("# ", comment),
      paste0("query ", strrep("I", length(chunk))),
      paste0("SELECT\n    ", paste(cols, collapse = ",\n    ")),
      paste0("FROM ", from, ";"),
      "----",
      paste(rep("true", length(chunk)), collapse = "\t"),
      "")
  }
  out
}
ctl <- glm.control(epsilon = 1e-14, maxit = 100)
opt <- "{'tolerance': 1e-12, 'max_iterations': 100}"
lr_src <- function(agg, y, full, reduced, extra = "") {
  o <- if (extra == "") opt else sub("}$", paste0(", ", extra, "}"), opt)
  sprintf("(SELECT lr_test(%s(%s, %s, %s), %s(%s, %s, %s)) AS r FROM d) s",
          agg, y, full, o, agg, y, reduced, o)
}
lr_checks <- function(comment, src, stat, df, p, tol = 1e-6) {
  checks(comment, src, c("r.statistic", "r.df1", "r.p_value"), c(stat, df, p), tol)
}

