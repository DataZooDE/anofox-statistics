sv_sql <- c("statement ok",
  "CREATE TABLE sv (time DOUBLE, rt DOUBLE, ev INTEGER, a1 DOUBLE, arm VARCHAR, g3 INTEGER);", "",
  "statement ok",
  paste0("INSERT INTO sv VALUES\n", values_sql(data.frame(time, rt, ev, a1, arm, grp3)), ";"), "")
L <- header("survival_curves.test",
            "#156 Kaplan-Meier, log-rank and AFT survival curves against survival::survfit/survdiff/survreg")
