km_checks <- function(label, sf, src, tol) {
  m <- length(sf$time)
  out <- exact(sprintf("%s: one row per distinct time", label), sprintf("SELECT len(r) FROM %s;", src), m)
  out <- c(out, checks(sprintf("%s: time, n.risk, n.event, n.censor", label), src,
    c(sprintf("r[%d].time", 1:m), sprintf("r[%d].n_risk", 1:m), sprintf("r[%d].n_event", 1:m),
      sprintf("r[%d].n_censor", 1:m)),
    c(sf$time, sf$n.risk, sf$n.event, sf$n.censor), 0))
  out <- c(out, checks(sprintf("%s: surv", label), src, sprintf("r[%d].surv", 1:m), sf$surv, tol))
  out <- c(out, checks(sprintf("%s: lower, upper", label), src,
    c(sprintf("r[%d].conf_low", 1:m), sprintf("r[%d].conf_high", 1:m)), c(sf$lower, sf$upper), tol))
  # summary(survfit)$std.err is the Greenwood SE of surv, at event times only.
  ss <- summary(sf)
  k <- match(ss$time, sf$time)
  out <- c(out, checks(sprintf("%s: summary(survfit)$std.err (event times)", label), src,
    sprintf("r[%d].std_err", k), ss$std.err, tol))
  out
}
sf <- survfit(Surv(rt, ev) ~ 1)
L <- c(L, km_checks("survfit(Surv(rt, ev) ~ 1) [conf.type = 'log']", sf,
                    "(SELECT kaplan_meier_agg(rt, ev) AS r FROM sv) s", 1e-10))
sf <- survfit(Surv(rt, ev) ~ 1, conf.type = "log-log", conf.int = 0.9)
L <- c(L, km_checks("survfit(Surv(rt, ev) ~ 1, conf.type = 'log-log', conf.int = 0.9)", sf,
                    "(SELECT kaplan_meier_agg(rt, ev, 0.9, 'log-log') AS r FROM sv) s", 1e-10))
sf <- survfit(Surv(rt, ev) ~ 1, conf.type = "plain")
L <- c(L, km_checks("survfit(Surv(rt, ev) ~ 1, conf.type = 'plain'), BOOLEAN event", sf,
                    "(SELECT kaplan_meier_agg(rt, ev = 1, 0.95, 'plain') AS r FROM sv) s", 1e-10))
sf <- survfit(Surv(time, ev) ~ 1)
L <- c(L, km_checks("survfit(Surv(time, ev) ~ 1) [untied times]", sf,
                    "(SELECT kaplan_meier_agg(time, ev) AS r FROM sv) s", 1e-10))

# kaplan_meier_by: the strata of survfit(Surv(rt, ev) ~ arm), curve schema.
sfs <- survfit(Surv(rt, ev) ~ armf)
st <- rep(c("a", "b"), sfs$strata)
L <- c(L, exact("kaplan_meier_by: one row per (stratum, time)",
  "SELECT count(*), count(DISTINCT series), min(curve_type), max(curve_type) FROM kaplan_meier_by('sv', arm, rt, ev);",
  c(length(sfs$time), 2, "km", "km")))
for (s in c("a", "b")) {
  k <- which(st == s)
  src <- sprintf("(SELECT list(struct_pack(x, y, y_low, y_high, n_censor, weight) ORDER BY x) AS r FROM kaplan_meier_by('sv', arm, rt, ev) WHERE series = '%s') s", s)
  m <- length(k)
  L <- c(L, checks(sprintf("survfit(Surv(rt, ev) ~ arm), stratum %s: time, n.censor, n.risk", s), src,
    c(sprintf("r[%d].x", 1:m), sprintf("r[%d].n_censor", 1:m), sprintf("r[%d].weight", 1:m)),
    c(sfs$time[k], sfs$n.censor[k], sfs$n.risk[k]), 0))
  L <- c(L, checks(sprintf("survfit(Surv(rt, ev) ~ arm), stratum %s: surv, lower, upper", s), src,
    c(sprintf("r[%d].y", 1:m), sprintf("r[%d].y_low", 1:m), sprintf("r[%d].y_high", 1:m)),
    c(sfs$surv[k], sfs$lower[k], sfs$upper[k]), 1e-10))
}

# Log-rank tests.
for (spec in list(list("log_rank_test_agg(rt, ev, arm)", survdiff(Surv(rt, ev) ~ armf), "survdiff(Surv(rt, ev) ~ arm)"),
                  list("log_rank_test_agg(time, ev, g3)", survdiff(Surv(time, ev) ~ grp3), "survdiff(Surv(time, ev) ~ g3)"),
                  list("log_rank_test_agg(rt, ev = 1, g3::VARCHAR)", survdiff(Surv(rt, ev) ~ grp3), "survdiff(Surv(rt, ev) ~ g3), BOOLEAN event, VARCHAR group"))) {
  sd <- spec[[2]]
  df <- length(sd$n) - 1
  src <- sprintf("(SELECT %s AS r FROM sv) s", spec[[1]])
  L <- c(L, checks(spec[[3]], src, c("r.statistic", "r.df1", "r.p_value", "r.n"),
                   c(sd$chisq, df, pchisq(sd$chisq, df, lower.tail = FALSE), sum(sd$n)), 1e-10))
}
L <- c(L, exact("log_rank_test_agg method", "SELECT log_rank_test_agg(rt, ev, arm).method FROM sv;", "Log-rank test"))

# aft_survival: S(t | x) = 1 - psurvreg(t, lp, scale, dist) of survreg fits.
times <- c(0.5, 1, 2.5, 4, 6, 9, 15)
for (dist in c("weibull", "lognormal", "loglogistic", "exponential")) {
  fa <- survreg(Surv(time, ev) ~ a1, dist = dist, control = survreg.control(rel.tolerance = 1e-12, maxiter = 100))
  for (xv in c(0.3, 1.7)) {
    lp <- sum(coef(fa) * c(1, xv))
    s <- 1 - psurvreg(times, lp, fa$scale, dist)
    src <- sprintf(paste0("(SELECT aft_survival(m, [%s], [%s]) AS r FROM ",
      "(SELECT aft_fit_agg(time, [a1], ev, {'dist': '%s'}) AS m FROM sv)) s"), xv,
      paste(times, collapse = ", "), dist)
    L <- c(L, checks(sprintf("%s, a1 = %s: 1 - psurvreg(t, lp, scale, '%s')", dist, xv, dist), src,
      c(sprintf("r[%d].surv", seq_along(times)), sprintf("r[%d].time", seq_along(times))), c(s, times), 1e-6))
  }
}
write_test("survival_curves.test", L)
