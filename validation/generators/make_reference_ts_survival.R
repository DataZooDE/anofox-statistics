#!/usr/bin/env Rscript
# =============================================================================
# make_reference_ts_survival.R
#
# Generates the time-series diagnostics (#155) and survival curve (#156)
# reference sqllogictests under test/sql/reference/:
#
#   timeseries_diagnostics.test  acf_agg, pacf_agg, ljung_box_agg, box_pierce_agg,
#                                durbin_watson_agg, breusch_pagan_agg, white_test_agg
#                                <- stats::acf / pacf / Box.test, lmtest::dwtest / bptest
#   survival_curves.test         kaplan_meier_agg, kaplan_meier_by, log_rank_test_agg,
#                                aft_survival
#                                <- survival::survfit / survdiff / survreg + psurvreg
#
#   Rscript validation/generators/make_reference_ts_survival.R      # from repo root
#
# Requires: survival, lmtest. The datasets are literal constants (drawn once with
# set.seed(155) / the AFT data of make_reference_regression.R and rounded).
# =============================================================================
suppressPackageStartupMessages({ library(survival); library(lmtest) })

out_dir <- "test/sql/reference"

num <- function(v) ifelse(is.na(v), "NULL", sprintf("%.17g", v))
values_sql <- function(df) {
  rows <- apply(df, 1, function(r) paste0("(", paste(r, collapse = ", "), ")"))
  paste(rows, collapse = ",\n")
}
# Boolean checks, six per query: |a - b| <= tol * (1 + |b|); an NA reference
# asserts that the extension returns NULL.
checks <- function(comment, from, exprs, refs, tol) {
  stopifnot(length(exprs) == length(refs))
  out <- character()
  idx <- seq_along(exprs)
  for (chunk in split(idx, ceiling(idx / 6))) {
    cols <- vapply(chunk, function(i) {
      if (is.na(refs[i])) sprintf("(%s) IS NULL", exprs[i])
      else sprintf("abs((%s) - (%s)) <= %g * (1 + abs(%s))", exprs[i], num(refs[i]), tol, num(refs[i]))
    }, "")
    out <- c(out,
      paste0("# ", comment),
      paste0("query ", strrep("I", length(chunk))),
      paste0("SELECT\n    ", paste(cols, collapse = ",\n    ")),
      paste0("FROM ", from, ";"),
      "----",
      paste(rep("true", length(chunk)), collapse = "\t"),
      "")
  }
  out
}
header <- function(name, desc) {
  c(sprintf("# name: test/sql/reference/%s", name),
    sprintf("# description: %s", desc),
    "# group: [reference]",
    "#",
    "# GENERATED by validation/generators/make_reference_ts_survival.R -- do not edit",
    "# by hand; change the generator and re-run it instead.",
    sprintf("# Reference: %s, survival %s, lmtest %s", R.version.string,
            packageVersion("survival"), packageVersion("lmtest")),
    "",
    "require anofox_statistics",
    "")
}
write_test <- function(name, lines) {
  writeLines(lines, file.path(out_dir, name))
  cat("wrote", file.path(out_dir, name), "\n")
}
exact <- function(comment, sql, expected) {
  c(paste0("# ", comment), paste0("query ", strrep("I", length(expected))), sql, "----",
    paste(expected, collapse = "\t"), "")
}

# =============================================================================
# 1. Time-series diagnostics (#155)
# =============================================================================
# y = 1 + 0.5 x1 - 0.3 x2 + AR(1) errors whose spread grows with x1.
x1 <- c( 2.9, 9.4, 1.6, 4.4, 4.5, 7.3, 7.6, 5.4, 5.8, 3.3, 1, 8.3, 7.4, 9.1, 3.6, 3.7, 0.2, 2.5, 5.2, 3.9, 6.9, 0.9, 0.9, 9.3, 6.4, 3, 5.5, 2.9, 5.9, 7.2, 1.7, 2.6, 6.5, 8.6, 6.6, 6.7, 1.5, 5.3, 4.4, 4.7 )
x2 <- c( 1.2, 0.1, 3.3, 2.5, 4.1, 0.9, 0.7, 3.6, 2.8, 1.4, 1.7, 4.7, 2.1, 0.8, 4.2, 3, 4.6, 0.6, 3.9, 1.7, 2.6, 0.4, 3.5, 4.5, 2.2, 4.1, 1.5, 0.1, 3.4, 2, 4.5, 3.8, 0.8, 1.8, 3.2, 1.1, 2.8, 4.3, 0.5, 2.3 )
u <- c( 0.15, -0.71, 0.58, -0.25, 1.1, 0.42, -1.3, 0.94, -0.37, 0.21, -0.88, 1.47, -0.05, 0.66, -1.12, 0.33, -0.49, 0.8, -0.27, 1.02, -0.64, 0.12, -0.93, 0.55, 0.39, -1.21, 0.71, -0.16, 0.48, -0.82, 1.24, -0.43, 0.09, -0.58, 0.87, 0.26, -1.05, 0.63, -0.31, 0.44 )
n <- length(u)
err <- numeric(n); err[1] <- u[1]
for (i in 2:n) err[i] <- 0.6 * err[i - 1] + u[i]
y <- round(1 + 0.5 * x1 - 0.3 * x2 + err * (0.4 + 0.15 * x1), 3)
fit <- lm(y ~ x1 + x2)
e <- unname(residuals(fit))
tt <- seq_len(n)

ts_sql <- c("statement ok",
  "CREATE TABLE ts (t INTEGER, e DOUBLE, x1 DOUBLE, x2 DOUBLE);", "",
  "# Rows are inserted in reverse time order: the aggregates must follow ORDER BY t.",
  "statement ok",
  paste0("INSERT INTO ts VALUES\n", values_sql(data.frame(tt, num(e), x1, x2)[n:1, ]), ";"), "")
L <- header("timeseries_diagnostics.test",
            "#155 time-series residual diagnostics against stats::acf/pacf/Box.test and lmtest::dwtest/bptest")
L <- c(L, ts_sql,
  "# e are the residuals of lm(y ~ x1 + x2) (written with 17 significant digits).", "")

a <- drop(acf(e, lag.max = 8, plot = FALSE)$acf)
bound <- qnorm(0.975) / sqrt(n)
src <- "(SELECT acf_agg(e, 8 ORDER BY t) AS r FROM ts) s"
L <- c(L, exact("acf_agg returns lags 0..max_lag", "SELECT len(r), r[1].lag, r[9].lag FROM (SELECT acf_agg(e, 8 ORDER BY t) AS r FROM ts) s;", c(9, 0, 8)))
L <- c(L, checks("acf(e, lag.max = 8)$acf", src, sprintf("r[%d].acf", 1:9), a, 1e-10))
L <- c(L, checks("white-noise band qnorm(0.975) / sqrt(n)", src, c("r[2].conf_high", "r[2].conf_low"), c(bound, -bound), 1e-12))
ad <- acf(e, plot = FALSE)
L <- c(L, exact(sprintf("default lag.max = floor(10 log10 n) = %d", max(ad$lag)),
  "SELECT len(acf_agg(e ORDER BY t)) - 1, len(pacf_agg(e ORDER BY t)) FROM ts;",
  c(max(ad$lag), max(ad$lag))))
p <- drop(pacf(e, lag.max = 8, plot = FALSE)$acf)
src <- "(SELECT pacf_agg(e, 8 ORDER BY t) AS r FROM ts) s"
L <- c(L, exact("pacf_agg returns lags 1..max_lag", "SELECT len(r), r[1].lag, r[8].lag FROM (SELECT pacf_agg(e, 8 ORDER BY t) AS r FROM ts) s;", c(8, 1, 8)))
L <- c(L, checks("pacf(e, lag.max = 8)$acf", src, sprintf("r[%d].pacf", 1:8), p, 1e-10))

for (spec in list(list("ljung_box_agg", "Ljung-Box", 5, 2), list("ljung_box_agg", "Ljung-Box", 1, 0),
                  list("box_pierce_agg", "Box-Pierce", 5, 2), list("box_pierce_agg", "Box-Pierce", 10, 0))) {
  bt <- Box.test(e, lag = spec[[3]], type = spec[[2]], fitdf = spec[[4]])
  call <- if (spec[[3]] == 1) sprintf("%s(e ORDER BY t)", spec[[1]]) else
    sprintf("%s(e, %d, %d ORDER BY t)", spec[[1]], spec[[3]], spec[[4]])
  src <- sprintf("(SELECT %s AS r FROM ts) s", call)
  L <- c(L, checks(sprintf("Box.test(e, lag = %d, type = '%s', fitdf = %d)", spec[[3]], spec[[2]], spec[[4]]),
                   src, c("r.statistic", "r.df1", "r.p_value", "r.n"),
                   c(bt$statistic, bt$parameter, bt$p.value, n), 1e-10))
  L <- c(L, exact(sprintf("%s method string and lag/fitdf", spec[[1]]),
    sprintf("SELECT r.method, r.lag, r.fitdf FROM %s;", src), c(bt$method, spec[[3]], spec[[4]])))
}

dw <- dwtest(fit)
src <- "(SELECT durbin_watson_agg(e ORDER BY t) AS r FROM ts) s"
L <- c(L, checks("lmtest::dwtest(lm(y ~ x1 + x2))$statistic (p_value: not available upstream)", src,
                 c("r.statistic", "r.p_value", "r.n"), c(dw$statistic, NA, n), 1e-10))

bp <- bptest(fit)
bp0 <- bptest(fit, studentize = FALSE)
wt <- bptest(fit, ~ x1 * x2 + I(x1^2) + I(x2^2))
for (spec in list(list("breusch_pagan_agg(e, [x1, x2])", bp, "bptest(fit)"),
                  list("breusch_pagan_agg(e, [x1, x2], false)", bp0, "bptest(fit, studentize = FALSE)"),
                  list("white_test_agg(e, [x1, x2])", wt, "bptest(fit, ~ x1 * x2 + I(x1^2) + I(x2^2))"))) {
  src <- sprintf("(SELECT %s AS r FROM ts) s", spec[[1]])
  L <- c(L, checks(spec[[3]], src, c("r.statistic", "r.df1", "r.p_value"),
                   c(spec[[2]]$statistic, spec[[2]]$parameter, spec[[2]]$p.value), 1e-8))
}
L <- c(L, exact("method strings", paste0(
  "SELECT breusch_pagan_agg(e, [x1, x2]).method, breusch_pagan_agg(e, [x1, x2], false).method, ",
  "white_test_agg(e, [x1, x2]).method FROM ts;"),
  c(bp$method, "Breusch-Pagan test", "White test")))
write_test("timeseries_diagnostics.test", L)

