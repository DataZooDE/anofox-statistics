#!/usr/bin/env Rscript
# =============================================================================
# make_reference_cox.R
#
# Generates test/sql/reference/survival_cox.test: cox_fit_agg, cox_zph_agg,
# cox_survival, cox_augment_by and cox_tidy_by (#312) against
#
#   survival::coxph      coefficients, se, z, p, exp(confint), loglik, LR / Wald /
#                        score tests, concordance, AIC / BIC; Efron and Breslow ties,
#                        case weights, offset, strata, counting-process (start, stop]
#                        data, ridge(theta, scale = FALSE), robust / cluster variance
#   rms::cph             R2 (pseudo_r_squared)
#   survival::cox.zph    per-term and global tests, transforms km / rank / identity
#   survfit.coxph        S(t | newdata) at given times (summary(..., times))
#   residuals.coxph      martingale, deviance, score, dfbeta, dfbetas, schoenfeld,
#                        scaledsch; predict(type = "lp", reference = "zero")
#
#   Rscript validation/generators/make_reference_cox.R      # from repo root
#
# Data: survival::lung (complete cases of age, sex, ph.ecog; status 2 = death)
# and survival::heart (Stanford heart transplant, counting-process form).
# =============================================================================
suppressPackageStartupMessages({ library(survival); library(rms) })

out_dir <- "test/sql/reference"
num <- function(v) ifelse(is.na(v), "NULL", sprintf("%.17g", v))
values_sql <- function(df) {
  rows <- apply(df, 1, function(r) paste0("(", paste(num(as.numeric(r)), collapse = ", "), ")"))
  paste(rows, collapse = ",\n")
}
checks <- function(comment, from, exprs, refs, tol) {
  stopifnot(length(exprs) == length(refs))
  out <- character()
  idx <- seq_along(exprs)
  for (chunk in split(idx, ceiling(idx / 6))) {
    cols <- vapply(chunk, function(i) {
      if (is.na(refs[i])) sprintf("(%s) IS NULL", exprs[i])
      else sprintf("abs((%s) - (%s)) <= %g * (1 + abs(%s))", exprs[i], num(refs[i]), tol, num(refs[i]))
    }, "")
    out <- c(out, paste0("# ", comment), paste0("query ", strrep("I", length(chunk))),
             paste0("SELECT\n    ", paste(cols, collapse = ",\n    ")), paste0("FROM ", from, ";"), "----",
             paste(rep("true", length(chunk)), collapse = "\t"), "")
  }
  out
}
lines <- c(
  "# name: test/sql/reference/survival_cox.test",
  "# description: cox_fit_agg / cox_zph_agg / cox_survival / cox_augment_by against survival::coxph, cox.zph, survfit, residuals (#312)",
  "# group: [reference]",
  "#",
  "# GENERATED by validation/generators/make_reference_cox.R -- do not edit",
  "# by hand; change the generator and re-run it instead.",
  sprintf("# Reference: %s, survival %s, rms %s", R.version.string, packageVersion("survival"),
          packageVersion("rms")),
  "",
  "require anofox_statistics",
  "")

# ---------------------------------------------------------------------------
# Data
# ---------------------------------------------------------------------------
lung2 <- lung[!is.na(lung$ph.ecog), c("time", "status", "age", "sex", "ph.ecog")]
lung2$ev <- as.numeric(lung2$status == 2)
lung2$rid <- seq_len(nrow(lung2))
lung2$w <- 1 + (lung2$rid %% 3)          # integer case weights
lung2$wf <- 1 + (lung2$rid %% 3) / 2     # fractional: coxph then defaults to the robust variance
lung2$off <- 0.01 * lung2$age
rownames(lung2) <- lung2$rid
lungdf <- lung2[, c("rid", "time", "ev", "age", "sex", "ph.ecog", "w", "wf", "off")]
names(lungdf)[6] <- "ecog"
lines <- c(lines, "statement ok",
  "CREATE TABLE lung (rid INTEGER, time DOUBLE, ev DOUBLE, age DOUBLE, sex DOUBLE, ecog DOUBLE, w DOUBLE, wf DOUBLE, off DOUBLE);",
  "", "statement ok", "INSERT INTO lung VALUES", paste0(values_sql(lungdf), ";"), "")

hrt <- heart
hrt$rid <- seq_len(nrow(hrt))
rownames(hrt) <- hrt$rid
heartdf <- hrt[, c("rid", "start", "stop", "event", "age", "year", "surgery", "id")]
lines <- c(lines, "statement ok",
  "CREATE TABLE heart (rid INTEGER, start DOUBLE, stop DOUBLE, event DOUBLE, age DOUBLE, year DOUBLE, surgery DOUBLE, id DOUBLE);",
  "", "statement ok", "INSERT INTO heart VALUES", paste0(values_sql(heartdf), ";"), "")

# ---------------------------------------------------------------------------
# Fit checks
# ---------------------------------------------------------------------------
fit_checks <- function(label, fit, call, robust = FALSE, cph_fit = NULL) {
  s <- summary(fit)
  p <- length(coef(fit))
  cf <- s$coefficients
  ci <- exp(confint(fit))
  ref <- c(setNames(unname(coef(fit)), sprintf("m.coefficients[%d]", 1:p)),
           setNames(sqrt(diag(fit$var)), sprintf("m.std_errors[%d]", 1:p)),
           setNames(unname(cf[, "z"]), sprintf("m.z_values[%d]", 1:p)),
           setNames(unname(cf[, ncol(cf)]), sprintf("m.p_values[%d]", 1:p)),
           setNames(unname(exp(coef(fit))), sprintf("m.hazard_ratios[%d]", 1:p)),
           setNames(unname(ci[, 1]), sprintf("m.hr_conf_low[%d]", 1:p)),
           setNames(unname(ci[, 2]), sprintf("m.hr_conf_high[%d]", 1:p)),
           m.null_log_likelihood = fit$loglik[1], m.log_likelihood = fit$loglik[2],
           m.lr_statistic = s$logtest[["test"]], m.lr_p_value = s$logtest[["pvalue"]],
           m.score_statistic = unname(fit$score), m.concordance = unname(fit$concordance["concordance"]),
           m.n_events = fit$nevent, m.aic = AIC(fit), m.bic = BIC(fit))
  if (robust) {
    # summary(coxph) then reports the robust Wald test; the extension keeps the
    # model-based one and reports the model-based standard errors as naive_std_errors.
    ref <- c(ref, setNames(sqrt(diag(fit$naive.var)), sprintf("m.naive_std_errors[%d]", 1:p)))
  } else {
    ref <- c(ref, m.wald_statistic = unname(fit$wald.test), m.wald_p_value = s$waldtest[["pvalue"]])
  }
  if (!is.null(cph_fit)) ref <- c(ref, m.pseudo_r_squared = unname(cph_fit$stats["R2"]))
  checks(label, sprintf("(SELECT %s AS m FROM %s)", call$expr, call$table), names(ref), unname(ref), 1e-6)
}

# 1. lung, Efron (default)
f1 <- coxph(Surv(time, ev) ~ age + sex + ph.ecog, data = lung2)
c1 <- cph(Surv(time, ev) ~ age + sex + ph.ecog, data = lung2)
lines <- c(lines, fit_checks("coxph(Surv(time, ev) ~ age + sex + ph.ecog, lung): Efron", f1,
  list(expr = "cox_fit_agg(time, [age, sex, ecog], ev)", table = "lung"), cph_fit = c1))

# 2. Breslow ties
f2 <- coxph(Surv(time, ev) ~ age + sex + ph.ecog, data = lung2, ties = "breslow")
c2 <- cph(Surv(time, ev) ~ age + sex + ph.ecog, data = lung2, method = "breslow")
lines <- c(lines, fit_checks("ties = 'breslow'", f2,
  list(expr = "cox_fit_agg(time, [age, sex, ecog], ev, {'ties': 'breslow'})", table = "lung"), cph_fit = c2))

# 3. case weights
f3 <- coxph(Surv(time, ev) ~ age + sex + ph.ecog, data = lung2, weights = w)
lines <- c(lines, fit_checks("weights = w", f3,
  list(expr = "cox_fit_agg(time, [age, sex, ecog], ev, w)", table = "lung")))
# fractional weights: coxph switches to the robust variance by itself; here it is asked for
f3b <- coxph(Surv(time, ev) ~ age + sex + ph.ecog, data = lung2, weights = wf)
stopifnot(!is.null(f3b$naive.var))
lines <- c(lines, fit_checks("weights = wf (fractional; coxph's default robust variance = {'robust': true})", f3b,
  list(expr = "cox_fit_agg(time, [age, sex, ecog], ev, wf, {'robust': true})", table = "lung"), robust = TRUE))

# 4. offset (x position 4)
f4 <- coxph(Surv(time, ev) ~ sex + ph.ecog + offset(off), data = lung2)
lines <- c(lines, fit_checks("offset(off): x position 3", f4,
  list(expr = "cox_fit_agg(time, [sex, ecog, off], ev, {'offset': 3})", table = "lung")))

# 5. strata(sex)
f5 <- coxph(Surv(time, ev) ~ age + ph.ecog + strata(sex), data = lung2)
lines <- c(lines, fit_checks("strata(sex): x position 2", f5,
  list(expr = "cox_fit_agg(time, [age, sex, ecog], ev, {'strata': 2})", table = "lung")))

# 6. ridge(theta = 2, scale = FALSE): coefficients, se and loglik
f6 <- coxph(Surv(time, ev) ~ ridge(age, ph.ecog, theta = 2, scale = FALSE), data = lung2)
from6 <- "(SELECT cox_fit_agg(time, [age, ecog], ev, {'ridge': 2}) AS m FROM lung)"
lines <- c(lines, checks("ridge(age, ph.ecog, theta = 2, scale = FALSE)", from6,
  c("m.coefficients[1]", "m.coefficients[2]", "m.std_errors[1]", "m.std_errors[2]", "m.log_likelihood",
    "m.aic"),
  c(unname(coef(f6)), sqrt(diag(f6$var)), f6$loglik[2], NA), 1e-6))

# 7. robust = TRUE
f7 <- coxph(Surv(time, ev) ~ age + sex + ph.ecog, data = lung2, robust = TRUE)
lines <- c(lines, fit_checks("robust = TRUE", f7,
  list(expr = "cox_fit_agg(time, [age, sex, ecog], ev, {'robust': true})", table = "lung"), robust = TRUE))

# 8. counting process (start, stop] + cluster(id)
f8 <- coxph(Surv(start, stop, event) ~ age + year + surgery, data = hrt)
lines <- c(lines, fit_checks("Surv(start, stop, event) ~ age + year + surgery, heart: entry at x position 4", f8,
  list(expr = "cox_fit_agg(stop, [age, year, surgery, start], event, {'entry': 4})", table = "heart")))
f9 <- coxph(Surv(start, stop, event) ~ age + year + surgery + cluster(id), data = hrt)
lines <- c(lines, fit_checks("... + cluster(id): cluster at x position 5", f9,
  list(expr = "cox_fit_agg(stop, [age, year, surgery, start, id], event, {'entry': 4, 'cluster': 5})",
       table = "heart"), robust = TRUE))

# ---------------------------------------------------------------------------
# cox.zph
# ---------------------------------------------------------------------------
zph_checks <- function(label, fit, call, transform) {
  z <- cox.zph(fit, transform = transform, terms = FALSE)$table
  k <- nrow(z)
  from <- sprintf("(SELECT %s AS z FROM %s)", call$expr, call$table)
  checks(label, from,
         c(sprintf("z[%d].statistic", 1:k), sprintf("z[%d].df", 1:k), sprintf("z[%d].p_value", 1:k)),
         c(z[, "chisq"], z[, "df"], z[, "p"]), 1e-6)
}
lines <- c(lines, zph_checks("cox.zph(fit, transform = 'km')", f1,
  list(expr = "cox_zph_agg(time, [age, sex, ecog], ev)", table = "lung"), "km"))
lines <- c(lines, zph_checks("cox.zph(fit, transform = 'rank')", f1,
  list(expr = "cox_zph_agg(time, [age, sex, ecog], ev, {'transform': 'rank'})", table = "lung"), "rank"))
lines <- c(lines, zph_checks("cox.zph(fit, transform = 'identity'), Breslow", f2,
  list(expr = "cox_zph_agg(time, [age, sex, ecog], ev, {'ties': 'breslow', 'transform': 'identity'})",
       table = "lung"), "identity"))
lines <- c(lines, zph_checks("cox.zph(fit, transform = 'log'), strata", f5,
  list(expr = "cox_zph_agg(time, [age, sex, ecog], ev, {'strata': 2, 'transform': 'log'})", table = "lung"), "log"))
lines <- c(lines, "# The last row is the global test",
  "query II", "SELECT z[4].term, z[1].term FROM (SELECT cox_zph_agg(time, [age, sex, ecog], ev) AS z FROM lung);",
  "----", "GLOBAL\tx1", "")

