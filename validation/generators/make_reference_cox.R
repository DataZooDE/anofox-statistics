times <- c(30, 180, 365, 500, 1000)
surv_checks <- function(label, fit, newdata, call, sx = NULL) {
  sf <- summary(survfit(fit, newdata = newdata), times = times, extend = TRUE)
  from <- sprintf("(SELECT unnest(cox_survival(m, %s, [%s]%s)) AS s FROM (SELECT %s AS m FROM %s))",
                  call$x, paste(times, collapse = ", "), if (is.null(sx)) "" else paste0(", ", sx),
                  call$expr, call$table)
  checks(label, sprintf("(SELECT list(s.surv ORDER BY s.time) AS v FROM %s)", from),
         sprintf("v[%d]", seq_along(times)), as.numeric(sf$surv), 1e-6)
}
lines <- c(lines, surv_checks("survfit(f1, newdata = (age 60, sex 1, ph.ecog 1))", f1,
  data.frame(age = 60, sex = 1, ph.ecog = 1),
  list(x = "[60.0, 1.0, 1.0]", expr = "cox_fit_agg(time, [age, sex, ecog], ev)", table = "lung")))
lines <- c(lines, surv_checks("survfit(f2, newdata = (age 70, sex 2, ph.ecog 2)), Breslow", f2,
  data.frame(age = 70, sex = 2, ph.ecog = 2),
  list(x = "[70.0, 2.0, 2.0]", expr = "cox_fit_agg(time, [age, sex, ecog], ev, {'ties': 'breslow'})",
       table = "lung")))
sf5 <- survfit(f5, newdata = data.frame(age = 60, ph.ecog = 1))
for (st in 1:2) {
  ss <- summary(sf5[st], times = times, extend = TRUE)
  from <- sprintf(paste0("(SELECT list(s.surv ORDER BY s.time) AS v FROM (SELECT unnest(cox_survival(m, [60.0, 1.0], [%s], %d)) AS s ",
                         "FROM (SELECT cox_fit_agg(time, [age, sex, ecog], ev, {'strata': 2}) AS m FROM lung)))"),
                  paste(times, collapse = ", "), st)
  lines <- c(lines, checks(sprintf("survfit(f5, newdata)[stratum sex = %d]", st), from,
                           sprintf("v[%d]", seq_along(times)), as.numeric(ss$surv), 1e-6))
}

# ---------------------------------------------------------------------------
# Residuals: cox_augment_by / cox_augment_agg against residuals.coxph, row by row
# ---------------------------------------------------------------------------
# residuals(type = "schoenfeld") has one row per event, ordered by stratum, time
# and (within tied times) data order; its rownames are the times.
resid_table <- function(name, fit, time, event, strata) {
  n <- length(time)
  p <- length(coef(fit))
  ev_rows <- which(event == 1)
  ev_rows <- ev_rows[order(strata[ev_rows], time[ev_rows], ev_rows)]
  r_s <- as.matrix(residuals(fit, type = "schoenfeld"))
  stopifnot(nrow(r_s) == length(ev_rows), all(as.numeric(rownames(r_s)) == time[ev_rows]))
  sch <- matrix(NA, n, p); sch[ev_rows, ] <- r_s
  ssch <- matrix(NA, n, p); ssch[ev_rows, ] <- as.matrix(residuals(fit, type = "scaledsch"))
  sc <- residuals(fit, type = "score")
  dfb <- residuals(fit, type = "dfbeta")
  dfbs <- residuals(fit, type = "dfbetas")
  df <- data.frame(rid = seq_len(n), lp = predict(fit, type = "lp", reference = "zero"),
                   mart = residuals(fit, type = "martingale"), dev = residuals(fit, type = "deviance"),
                   sc1 = sc[, 1], sc2 = sc[, 2], dfb1 = dfb[, 1], dfb2 = dfb[, 2], dfbs1 = dfbs[, 1],
                   dfbs2 = dfbs[, 2], sch1 = sch[, 1], sch2 = sch[, 2], ssch1 = ssch[, 1], ssch2 = ssch[, 2])
  c("statement ok",
    sprintf(paste0("CREATE TABLE %s (rid INTEGER, lp DOUBLE, mart DOUBLE, dev DOUBLE, sc1 DOUBLE, sc2 DOUBLE, ",
                   "dfb1 DOUBLE, dfb2 DOUBLE, dfbs1 DOUBLE, dfbs2 DOUBLE, sch1 DOUBLE, sch2 DOUBLE, ssch1 DOUBLE, ",
                   "ssch2 DOUBLE);"), name),
    "", "statement ok", sprintf("INSERT INTO %s VALUES", name), paste0(values_sql(df), ";"), "")
}
# `src` yields rid, fitted, residual, deviance_residual, score_residuals, dfbeta, dfbetas,
# schoenfeld_residuals, scaled_schoenfeld_residuals.
resid_query <- function(label, ref, src) {
  d <- function(a, b) sprintf("abs(%s - %s)", a, b)
  c(paste0("# ", label),
    "query IIIIIII",
    paste0("SELECT max(", d("a.fitted", "r.lp"), ") < 1e-6, max(", d("a.residual", "r.mart"), ") < 1e-6,\n",
           "    max(", d("a.deviance_residual", "r.dev"), ") < 1e-6,\n",
           "    max(greatest(", d("a.score_residuals[1]", "r.sc1"), ", ", d("a.score_residuals[2]", "r.sc2"), ")) < 1e-6,\n",
           "    max(greatest(", d("a.dfbeta[1]", "r.dfb1"), ", ", d("a.dfbeta[2]", "r.dfb2"), ", ",
           d("a.dfbetas[1]", "r.dfbs1"), ", ", d("a.dfbetas[2]", "r.dfbs2"), ")) < 1e-6,\n",
           "    max(greatest(", d("a.schoenfeld_residuals[1]", "r.sch1"), ", ", d("a.schoenfeld_residuals[2]", "r.sch2"),
           ", ", d("a.scaled_schoenfeld_residuals[1]", "r.ssch1"), ", ",
           d("a.scaled_schoenfeld_residuals[2]", "r.ssch2"), ")) < 1e-6,\n",
           "    bool_and((a.schoenfeld_residuals IS NULL) = (r.sch1 IS NULL))"),
    sprintf("FROM %s a JOIN %s r USING (rid);", src, ref),
    "----", paste(rep("true", 7), collapse = "\t"), "")
}
lines <- c(lines, "statement ok", "CREATE VIEW lung_g AS SELECT *, 0 AS g FROM lung;", "",
           "statement ok",
           "CREATE VIEW heart_g AS SELECT *, (year > 3)::DOUBLE AS yr3, 0 AS g FROM heart;", "")
g1 <- coxph(Surv(time, ev) ~ age + ph.ecog, data = lung2)
lines <- c(lines, resid_table("res_efron", g1, lung2$time, lung2$ev, rep(0, nrow(lung2))),
  resid_query("residuals(coxph(Surv(time, ev) ~ age + ph.ecog)), Efron: cox_augment_by", "res_efron",
              "cox_augment_by('lung_g', g, time, [age, ecog], ev)"))
g2 <- coxph(Surv(time, ev) ~ age + ph.ecog, data = lung2, ties = "breslow", weights = w)
agg <- paste0("cox_augment_agg(time, [age, ecog], ev, w, {'ties': 'breslow'}) OVER (ORDER BY rid ROWS BETWEEN ",
              "UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING)")
lines <- c(lines, resid_table("res_breslow_w", g2, lung2$time, lung2$ev, rep(0, nrow(lung2))),
  resid_query("residuals(...), Breslow ties, case weights: cox_augment_agg over the table", "res_breslow_w",
              paste0("(SELECT rid, x.linear_predictor AS fitted, x.martingale_residual AS residual, ",
                     "x.deviance_residual, x.score_residuals, x.dfbeta, x.dfbetas, x.schoenfeld_residuals, ",
                     "x.scaled_schoenfeld_residuals FROM (SELECT rid, (", agg, ")[row_number() OVER (ORDER BY rid)] AS x ",
                     "FROM lung))")))
g3 <- coxph(Surv(start, stop, event) ~ age + surgery + strata(year > 3), data = hrt)
lines <- c(lines, resid_table("res_heart", g3, hrt$stop, hrt$event, as.numeric(hrt$year > 3)),
  resid_query("residuals(coxph(Surv(start, stop, event) ~ age + surgery + strata(year > 3), heart))", "res_heart",
              "cox_augment_by('heart_g', g, stop, [age, surgery, start, yr3], event, options := {'entry': 3, 'strata': 4})"))

# tidy: estimate / std_error / conf_low of the log hazard ratios
lines <- c(lines, checks("cox_tidy_by: log hazard ratios with inference",
  "(SELECT list(estimate ORDER BY term) AS e, list(std_error ORDER BY term) AS s, list(conf_low ORDER BY term) AS l FROM cox_tidy_by('lung', 1, time, [age, sex, ecog], ev))",
  c("e[1]", "e[2]", "e[3]", "s[1]", "s[2]", "s[3]", "l[1]", "l[3]"),
  c(unname(coef(f1)), sqrt(diag(f1$var)), unname(confint(f1)[1, 1]), unname(confint(f1)[3, 1])), 1e-6))

writeLines(lines, file.path(out_dir, "survival_cox.test"))
cat("wrote", file.path(out_dir, "survival_cox.test"), "\n")
