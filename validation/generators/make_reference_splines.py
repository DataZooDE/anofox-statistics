#!/usr/bin/env python3
"""scikit-learn references for test/sql/reference/splines_sklearn.test (#317).

Usage (from the repository root):
    uv run --no-project --with scikit-learn python3 validation/generators/make_reference_splines.py

bspline(x, knots, degree, {'extrapolation': e, 'include_bias': b}) against
sklearn.preprocessing.SplineTransformer(knots=<array>, degree=degree,
extrapolation=e, include_bias=b) for one feature, inside and outside the base
knots, and bspline_knots_agg(x, n, {'knots': 'uniform' | 'quantile'}) against
the knots SplineTransformer(n_knots=n, knots=...) places on the data
(bsplines_[0].t without the added boundary knots).
"""
import os

import numpy as np
import sklearn
from sklearn.preprocessing import SplineTransformer

OUT = os.path.join("test", "sql", "reference", "splines_sklearn.test")


def fmt(v):
    return repr(float(v))


def lst(v):
    return "[" + ", ".join(fmt(x) for x in v) + "]"


lines = []
emit = lines.append

emit("# name: test/sql/reference/splines_sklearn.test")
emit("# description: #317 bspline / bspline_knots_agg vs scikit-learn SplineTransformer")
emit("# group: [reference]")
emit("#")
emit(f"# Generated by validation/generators/make_reference_splines.py (scikit-learn {sklearn.__version__},")
emit(f"# numpy {np.__version__}). Do not edit by hand.")
emit("")
emit("require anofox_statistics")
emit("")
emit("statement ok")
emit(
    "CREATE MACRO max_abs_diff(a, b) AS CASE WHEN len(a) = len(b) THEN coalesce(list_max(list_transform("
    "range(1, len(a) + 1), lambda i: abs(a[i] - b[i]))), 0) ELSE 1e300 END;"
)
emit("")

grid = np.array([-3.0, -0.5, 0.0, 0.7, 2.5, 4.1, 5.0, 7.75, 9.9, 10.0, 11.2, 14.0])
inside = grid[(grid >= 0) & (grid <= 10)]
cases = [
    ([0.0, 2.5, 5.0, 7.5, 10.0], 3),
    ([0.0, 1.0, 4.0, 6.0, 10.0], 2),
    ([0.0, 3.0, 10.0], 1),
    ([0.0, 2.0, 5.0, 9.0, 10.0], 3),
]
for knots, degree in cases:
    for extrapolation in ["constant", "linear", "continue", "periodic", "error"]:
        if extrapolation == "periodic" and degree >= len(knots):
            continue
        for bias in [True, False]:
            st = SplineTransformer(
                knots=np.array(knots).reshape(-1, 1),
                degree=degree,
                extrapolation=extrapolation,
                include_bias=bias,
            )
            xs = inside if extrapolation == "error" else grid
            st.fit(np.array(knots).reshape(-1, 1))
            B = st.transform(xs.reshape(-1, 1))
            rows = ", ".join(f"({fmt(x)}, {lst(B[i])})" for i, x in enumerate(xs))
            opts = f"{{'extrapolation': '{extrapolation}', 'include_bias': {str(bias).lower()}}}"
            emit(
                f"# SplineTransformer(knots={knots}, degree={degree}, extrapolation='{extrapolation}', "
                f"include_bias={bias})"
            )
            emit("query I")
            emit(f"SELECT count(*) FROM (VALUES {rows}) t(x, e)")
            emit(f"WHERE NOT max_abs_diff(bspline(x, {lst(knots)}, {degree}, {opts}), e) <= 1e-10;")
            emit("----")
            emit("0")
            emit("")

# Knots placed on data.
rng = np.random.default_rng(317)
data = np.round(rng.gamma(2.0, 3.0, 90), 2)
emit("statement ok")
emit(f"CREATE TABLE gdata AS SELECT unnest({lst(data)}::DOUBLE[]) AS x;")
emit("")
for n_knots in [3, 5, 8]:
    for placement in ["uniform", "quantile"]:
        degree = 3
        st = SplineTransformer(n_knots=n_knots, knots=placement, degree=degree).fit(data.reshape(-1, 1))
        t = st.bsplines_[0].t[degree:-degree]
        emit(f"# SplineTransformer(n_knots={n_knots}, knots='{placement}').bsplines_[0].t[3:-3]")
        emit("query I")
        emit(
            f"SELECT max_abs_diff(bspline_knots_agg(x, {n_knots}, {{'knots': '{placement}'}}), {lst(t)}) < 1e-10 "
            "FROM gdata;"
        )
        emit("----")
        emit("true")
        emit("")
        # The basis on the data-placed knots equals the transformer's output.
        xs = np.array([data.min(), 1.0, 4.4, 9.0, data.max(), data.max() + 2.0])
        B = st.transform(xs.reshape(-1, 1))
        rows = ", ".join(f"({fmt(x)}, {lst(B[i])})" for i, x in enumerate(xs))
        emit(f"# SplineTransformer(n_knots={n_knots}, knots='{placement}').fit(data).transform(x)")
        emit("query I")
        emit(f"WITH k AS (SELECT bspline_knots_agg(x, {n_knots}, {{'knots': '{placement}'}}) AS knots FROM gdata)")
        emit(f"SELECT count(*) FROM (VALUES {rows}) t(x, e), k WHERE NOT max_abs_diff(bspline(x, k.knots), e) <= 1e-10;")
        emit("----")
        emit("0")
        emit("")

with open(OUT, "w") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", OUT)
