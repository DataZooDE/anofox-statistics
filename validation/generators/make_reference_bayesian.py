#!/usr/bin/env python3
"""scikit-learn references for test/sql/reference/regression_bayesian.test (#61).

Usage (from the repository root):
    uv run --no-project --with scikit-learn python3 validation/generators/make_reference_bayesian.py

Writes the .test file. bayesian_ridge_fit_agg / ard_fit_agg are checked against
sklearn.linear_model.BayesianRidge / ARDRegression (coef_, intercept_, alpha_,
lambda_, sqrt(diag(sigma_)), n_iter_, scores_ with compute_score=True), and the
*_fit_predict_agg bands against predict(X, return_std=True) with normal
quantiles. Requires scikit-learn >= 1.8 (earlier releases did not center X in
return_std).
"""
import os

import numpy as np
import sklearn
from scipy.stats import norm
from sklearn.linear_model import ARDRegression, BayesianRidge

OUT = os.path.join("test", "sql", "reference", "regression_bayesian.test")
TOL = "1e-07"

# Fixed datasets (drawn once, rounded so the SQL literals are exact).
rng = np.random.default_rng(61)
N = 30
X = np.round(rng.normal(size=(N, 4)), 3)
Y = np.round(1.5 + X @ np.array([2.0, -1.0, 0.5, 0.0]) + rng.normal(0.0, 0.3, N), 3)
# ARD: x4 is pure noise and x3 has a tiny effect.
Y_ARD = np.round(0.5 + X @ np.array([1.5, 0.0, -2.0, 0.0]) + rng.normal(0.0, 0.2, N), 3)

lines = []


def emit(s=""):
    lines.append(s)


def close(expr, value):
    return f"abs(({expr}) - ({value!r})) <= {TOL} * (1 + abs({value!r}))"


def check(title, query, conditions):
    emit(f"# {title}")
    emit("query " + "I" * len(conditions))
    emit("SELECT")
    emit(",\n".join("    " + c for c in conditions))
    emit(query)
    emit("----")
    emit("\t".join(["true"] * len(conditions)))
    emit()


def posterior_sd(model, p):
    sd = np.zeros(p)
    kept = model.lambda_ < model.threshold_lambda if hasattr(model, "threshold_lambda") else np.ones(p, bool)
    sd[kept] = np.sqrt(np.diag(model.sigma_))
    return sd


def fit_checks(name, fn, model, y_col, opts, p):
    sd = posterior_sd(model, p)
    conds = [close("m.intercept", float(model.intercept_)) if model.fit_intercept else "m.intercept = 0"]
    conds += [close(f"m.coefficients[{j + 1}]", float(model.coef_[j])) for j in range(p)]
    conds += [close("m.noise_precision", float(model.alpha_))]
    if isinstance(model, ARDRegression):
        conds += [close(f"m.weight_precisions[{j + 1}]", float(model.lambda_[j]))
                  for j in range(p) if model.lambda_[j] < model.threshold_lambda]
    else:
        conds += [close("m.weight_precision", float(model.lambda_)),
                  close("m.log_marginal_likelihood", float(model.scores_[-1]))]
    conds += [close(f"m.posterior_sd[{j + 1}]", float(sd[j])) for j in range(p)]
    conds += [f"m.iterations = {int(model.n_iter_)}"]
    x_list = "[" + ", ".join(f"x{j + 1}" for j in range(p)) + "]"
    query = f"FROM (SELECT {fn}({y_col}, {x_list}{opts}) AS m FROM d)"
    check(name, query, conds)


def predict_checks(name, fn, model, y_col, opts, p, level):
    mean, std = model.predict(X[:, :p], return_std=True)
    z = norm.ppf(0.5 + level / 2)
    conds = []
    for i in (0, 7, 19, 29):
        conds += [close(f"p[{i + 1}].yhat", float(mean[i])),
                  close(f"p[{i + 1}].yhat_lower", float(mean[i] - z * std[i])),
                  close(f"p[{i + 1}].yhat_upper", float(mean[i] + z * std[i]))]
    x_list = "[" + ", ".join(f"x{j + 1}" for j in range(p)) + "]"
    query = f"FROM (SELECT {fn}({y_col}, {x_list}, {{'confidence_level': {level}{opts}}} ORDER BY id) AS p FROM d)"
    check(name, query, conds)


emit("# name: test/sql/reference/regression_bayesian.test")
emit("# description: Bayesian Ridge and ARD regression against scikit-learn BayesianRidge / ARDRegression (#61)")
emit("# group: [reference]")
emit("#")
emit("# GENERATED by validation/generators/make_reference_bayesian.py -- do not edit")
emit("# by hand; change the generator and re-run it instead.")
emit(f"# Reference: scikit-learn {sklearn.__version__}, numpy {np.__version__}")
emit()
emit("require anofox_statistics")
emit()
emit("statement ok")
emit("CREATE TABLE d (id INTEGER, y DOUBLE, y_ard DOUBLE, x1 DOUBLE, x2 DOUBLE, x3 DOUBLE, x4 DOUBLE);")
emit()
emit("statement ok")
emit("INSERT INTO d VALUES")
emit(",\n".join(f"({i + 1}, {float(Y[i])!r}, {float(Y_ARD[i])!r}, " + ", ".join(repr(float(v)) for v in X[i]) + ")"
                for i in range(N)) + ";")
emit()

br = BayesianRidge(compute_score=True).fit(X, Y)
fit_checks("bayesian_ridge_fit_agg: sklearn BayesianRidge() defaults", "bayesian_ridge_fit_agg", br, "y", "", 4)
predict_checks("bayesian_ridge_fit_predict_agg: predict(return_std=True), 95% normal band",
               "bayesian_ridge_fit_predict_agg", br, "y", "", 4, 0.95)

br_ni = BayesianRidge(compute_score=True, fit_intercept=False).fit(X[:, :3], Y)
fit_checks("bayesian_ridge_fit_agg: fit_intercept = false", "bayesian_ridge_fit_agg", br_ni, "y",
           ", {'fit_intercept': false}", 3)

br_prior = BayesianRidge(compute_score=True, alpha_1=2.0, alpha_2=0.5, lambda_1=1.0, lambda_2=3.0,
                         tol=1e-6, max_iter=500).fit(X, Y)
fit_checks("bayesian_ridge_fit_agg: informative gamma priors, tol = 1e-6", "bayesian_ridge_fit_agg", br_prior, "y",
           ", {'alpha_1': 2.0, 'alpha_2': 0.5, 'lambda_1': 1.0, 'lambda_2': 3.0, 'tolerance': 1e-6, "
           "'max_iterations': 500}", 4)

ard = ARDRegression(compute_score=True).fit(X, Y_ARD)
fit_checks(f"ard_fit_agg: sklearn ARDRegression() defaults (kept: {[int(j) + 1 for j in np.where(ard.lambda_ < 1e4)[0]]})",
           "ard_fit_agg", ard, "y_ard", "", 4)
predict_checks("ard_fit_predict_agg: predict(return_std=True), 90% normal band", "ard_fit_predict_agg", ard,
               "y_ard", "", 4, 0.9)

ard_t = ARDRegression(compute_score=True, threshold_lambda=50.0).fit(X, Y_ARD)
fit_checks(f"ard_fit_agg: threshold_lambda = 50 (kept: {[int(j) + 1 for j in np.where(ard_t.lambda_ < 50)[0]]})",
           "ard_fit_agg", ard_t, "y_ard", ", {'threshold_lambda': 50}", 4)

with open(OUT, "w") as f:
    f.write("\n".join(lines).rstrip() + "\n")
print(f"wrote {OUT}")
