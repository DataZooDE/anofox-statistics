#!/usr/bin/env python3
"""scikit-learn references for test/sql/reference/regression_passive_aggressive.test (#63).

Usage (from the repository root):
    uv run --no-project --with scikit-learn python3 validation/generators/make_reference_passive_aggressive.py

Writes the .test file. passive_aggressive_fit_agg(... ORDER BY t) is checked
against sklearn.linear_model.PassiveAggressiveRegressor with shuffle=False:
partial_fit (one online pass, the default) for PA-I and PA-II, and fit with
max_iter / tol for multi-pass fits. passive_aggressive_fit_predict(...) OVER a
cumulative frame is checked against partial_fit on every prefix.
"""
import os
import warnings

import numpy as np
import sklearn
from sklearn.linear_model import PassiveAggressiveRegressor

warnings.simplefilter("ignore", FutureWarning)  # deprecated in 1.8, still the reference

OUT = os.path.join("test", "sql", "reference", "regression_passive_aggressive.test")
TOL = "1e-09"

rng = np.random.default_rng(63)
N = 40
X = np.round(rng.normal(size=(N, 2)), 3)
Y = np.round(0.5 + X @ np.array([1.2, -0.7]) + rng.normal(0.0, 0.3, N), 3)

lines = []


def emit(s=""):
    lines.append(s)


def close(expr, value):
    return f"abs(({expr}) - ({value!r})) <= {TOL} * (1 + abs({value!r}))"


def check(title, query, conditions):
    emit(f"# {title}")
    emit("query " + "I" * len(conditions))
    emit("SELECT")
    emit(",\n".join("    " + c for c in conditions))
    if query:
        emit(query)
    emit("----")
    emit("\t".join(["true"] * len(conditions)))
    emit()


def model(**kw):
    return PassiveAggressiveRegressor(shuffle=False, fit_intercept=True, average=False, **kw)


emit("# name: test/sql/reference/regression_passive_aggressive.test")
emit("# description: Passive-Aggressive regression against scikit-learn PassiveAggressiveRegressor (shuffle=False) (#63)")
emit("# group: [reference]")
emit("#")
emit("# GENERATED by validation/generators/make_reference_passive_aggressive.py -- do not edit")
emit("# by hand; change the generator and re-run it instead.")
emit(f"# Reference: scikit-learn {sklearn.__version__}, numpy {np.__version__}")
emit()
emit("require anofox_statistics")
emit()
emit("statement ok")
emit("CREATE TABLE d (t INTEGER, y DOUBLE, x1 DOUBLE, x2 DOUBLE);")
emit()
emit("statement ok")
emit("INSERT INTO d VALUES")
emit(",\n".join(f"({i + 1}, {float(Y[i])!r}, {float(X[i, 0])!r}, {float(X[i, 1])!r})" for i in range(N)) + ";")
emit()
# The table is inserted out of order so ORDER BY matters.
emit("statement ok")
emit("CREATE TABLE shuffled AS SELECT * FROM d ORDER BY (t * 17) % 41;")
emit()

cases = [
    ("PA-I, C = 1, epsilon = 0.1 (defaults)", {}, "", dict(C=1.0, epsilon=0.1, loss="epsilon_insensitive")),
    ("PA-I, C = 0.05, epsilon = 0", {"c": 0.05, "epsilon": 0}, "{'c': 0.05, 'epsilon': 0}",
     dict(C=0.05, epsilon=0.0, loss="epsilon_insensitive")),
    ("PA-II, C = 0.5, epsilon = 0.2", {}, "{'variant': 'pa2', 'C': 0.5, 'epsilon': 0.2}",
     dict(C=0.5, epsilon=0.2, loss="squared_epsilon_insensitive")),
]
for title, _, opts, kw in cases:
    m = model(**kw)
    m.partial_fit(X, Y)
    arg = f", {opts}" if opts else ""
    conds = [close("m.intercept", float(m.intercept_[0]))]
    conds += [close(f"m.coefficients[{j + 1}]", float(m.coef_[j])) for j in range(2)]
    conds += ["m.iterations = 1", "m.n_observations = 40"]
    check(f"passive_aggressive_fit_agg, one online pass = partial_fit: {title}",
          f"FROM (SELECT passive_aggressive_fit_agg(y, [x1, x2]{arg} ORDER BY t) AS m FROM shuffled)", conds)

# Multi-pass fit: sklearn fit(max_iter, tol) without shuffling.
m = model(C=1.0, epsilon=0.1, loss="epsilon_insensitive", max_iter=50, tol=1e-6)
m.fit(X, Y)
conds = [close("m.intercept", float(m.intercept_[0]))]
conds += [close(f"m.coefficients[{j + 1}]", float(m.coef_[j])) for j in range(2)]
conds += [f"m.iterations = {int(m.n_iter_)}"]
check("passive_aggressive_fit_agg, max_iterations = 50, tolerance = 1e-6 = fit(max_iter=50, tol=1e-6)",
      "FROM (SELECT passive_aggressive_fit_agg(y, [x1, x2], {'max_iterations': 50, 'tolerance': 1e-6} ORDER BY t) "
      "AS m FROM shuffled)", conds)

# Window over a cumulative frame: the prediction for row k from partial_fit on rows 1..k.
conds = []
for k in (1, 2, 10, 25, 40):
    mk = model(C=1.0, epsilon=0.1, loss="epsilon_insensitive")
    mk.partial_fit(X[:k], Y[:k])
    pred = float(mk.predict(X[k - 1:k])[0])
    conds.append(close(f"(SELECT p FROM w WHERE t = {k})", pred))
emit("statement ok")
emit("CREATE TABLE w AS SELECT t, (passive_aggressive_fit_predict(y, [x1, x2]) OVER (ORDER BY t ROWS BETWEEN "
     "UNBOUNDED PRECEDING AND CURRENT ROW)).yhat AS p FROM shuffled;")
emit()
check("passive_aggressive_fit_predict OVER a cumulative frame = partial_fit on the prefix, predicting its last row",
      "", conds)

# fit_predict_agg: final coefficients applied to every row.
m = model(C=1.0, epsilon=0.1, loss="epsilon_insensitive")
m.partial_fit(X[:30], Y[:30])
pred = m.predict(X)
conds = [close(f"p[{i + 1}].yhat", float(pred[i])) for i in (0, 29, 30, 39)]
conds += ["p[31].is_training = false", "p[30].is_training = true"]
check("passive_aggressive_fit_predict_agg: fit on rows 1-30 (y NULL after), predict all",
      "FROM (SELECT passive_aggressive_fit_predict_agg(CASE WHEN t <= 30 THEN y END, [x1, x2] ORDER BY t) AS p "
      "FROM shuffled)", conds)

with open(OUT, "w") as f:
    f.write("\n".join(lines).rstrip() + "\n")
print(f"wrote {OUT}")
