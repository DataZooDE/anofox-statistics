#!/usr/bin/env Rscript
# =============================================================================
# make_reference_survival_extras.R
#
# Generates test/sql/reference/survival_extras.test (#322):
#
#   aft_augment_agg / aft_augment_by  <- survival::survreg: predict(type = "lp"),
#       standardized residuals (log t - lp) / scale, Cox-Snell residuals
#       -log(1 - psurvreg(t, lp, scale, dist)) and the score contributions
#       residuals(fit, type = "matrix")[, c("dg", "ds")] * (1, x, 1), for the
#       weibull, lognormal, loglogistic and exponential distributions
#   kaplan_meier_agg(time, event, [columns,] options)
#       <- survival::survfit: case weights (integer: Greenwood; fractional:
#       robust by default), left truncation Surv(entry, time, event), cluster
#       (id =) robust standard errors, ctype = 2 (Fleming-Harrington),
#       conf.type, conf.int; summary(fit)$std.err, fit$cumhaz, fit$std.chaz
#   log_rank_test_agg(time, event, group, [columns,] options)
#       <- survival::survdiff(rho = ...), + strata(s)
#
#   Rscript validation/generators/make_reference_survival_extras.R   # from repo root
#
# Data: survival::lung (complete ph.ecog; status 2 = death) and
# survival::heart (Stanford heart transplant, counting-process form).
# =============================================================================
suppressPackageStartupMessages(library(survival))

out_dir <- "test/sql/reference"
num <- function(v) ifelse(is.na(v), "NULL", sprintf("%.17g", v))
values_sql <- function(df) {
  rows <- apply(df, 1, function(r) paste0("(", paste(num(as.numeric(r)), collapse = ", "), ")"))
  paste(rows, collapse = ",\n")
}
checks <- function(comment, from, exprs, refs, tol) {
  stopifnot(length(exprs) == length(refs))
  out <- character()
  idx <- seq_along(exprs)
  for (chunk in split(idx, ceiling(idx / 6))) {
    cols <- vapply(chunk, function(i) {
      if (is.na(refs[i])) sprintf("(%s) IS NULL", exprs[i])
      else sprintf("abs((%s) - (%s)) <= %g * (1 + abs(%s))", exprs[i], num(refs[i]), tol, num(refs[i]))
    }, "")
    out <- c(out, paste0("# ", comment), paste0("query ", strrep("I", length(chunk))),
             paste0("SELECT\n    ", paste(cols, collapse = ",\n    ")), paste0("FROM ", from, ";"), "----",
             paste(rep("true", length(chunk)), collapse = "\t"), "")
  }
  out
}
# A reference table plus one query that compares every row (max relative error).
table_check <- function(comment, name, df, sql, cols, tol) {
  types <- paste(sprintf("%s DOUBLE", names(df)), collapse = ", ")
  conds <- vapply(cols, function(c) {
    sprintf("bool_and(CASE WHEN r.%s IS NULL THEN a.%s IS NULL ELSE abs(a.%s - r.%s) <= %g * (1 + abs(r.%s)) END)",
            c, c, c, c, tol, c)
  }, "")
  c(sprintf("# %s", comment), "statement ok", sprintf("CREATE TABLE %s (%s);", name, types), "",
    "statement ok", sprintf("INSERT INTO %s VALUES", name), paste0(values_sql(df), ";"), "",
    paste0("query ", strrep("I", length(cols) + 1)),
    sprintf("SELECT count(*) = %d,\n    %s\nFROM (%s) a JOIN %s r USING (k);", nrow(df),
            paste(conds, collapse = ",\n    "), sql, name),
    "----", paste(rep("true", length(cols) + 1), collapse = "\t"), "")
}

lines <- c(
  "# name: test/sql/reference/survival_extras.test",
  "# description: aft_augment_agg / aft_augment_by, kaplan_meier_agg and log_rank_test_agg options against survival::survreg, survfit, survdiff (#322)",
  "# group: [reference]",
  "#",
  "# GENERATED by validation/generators/make_reference_survival_extras.R -- do not edit",
  "# by hand; change the generator and re-run it instead.",
  sprintf("# Reference: %s, survival %s", R.version.string, packageVersion("survival")),
  "",
  "require anofox_statistics",
  "")

# ---------------------------------------------------------------------------
# Data
# ---------------------------------------------------------------------------
lung2 <- lung[!is.na(lung$ph.ecog), c("time", "status", "age", "sex", "ph.ecog")]
lung2$ev <- as.numeric(lung2$status == 2)
lung2$rid <- seq_len(nrow(lung2))
lung2$w <- 1 + (lung2$rid %% 3)          # integer case weights
lung2$wf <- 1 + (lung2$rid %% 3) / 2     # fractional weights
rownames(lung2) <- lung2$rid
lungdf <- lung2[, c("rid", "time", "ev", "age", "sex", "ph.ecog", "w", "wf")]
lines <- c(lines, "statement ok",
  "CREATE TABLE lung (rid INTEGER, time DOUBLE, ev DOUBLE, age DOUBLE, sex DOUBLE, ecog DOUBLE, w DOUBLE, wf DOUBLE);",
  "", "statement ok", "INSERT INTO lung VALUES", paste0(values_sql(lungdf), ";"), "")

hrt <- heart
hrt$rid <- seq_len(nrow(hrt))
heartdf <- hrt[, c("rid", "start", "stop", "event", "transplant", "id")]
heartdf$transplant <- as.numeric(as.character(heartdf$transplant))
lines <- c(lines, "statement ok",
  "CREATE TABLE heart (rid INTEGER, start DOUBLE, stop DOUBLE, event DOUBLE, transplant DOUBLE, id DOUBLE);",
  "", "statement ok", "INSERT INTO heart VALUES", paste0(values_sql(heartdf), ";"), "")

# ---------------------------------------------------------------------------
# AFT residuals: aft_augment_by
# ---------------------------------------------------------------------------
X <- cbind(1, lung2$age, lung2$sex, lung2$ph.ecog)
for (dist in c("weibull", "lognormal", "loglogistic", "exponential")) {
  f <- survreg(Surv(time, ev) ~ age + sex + ph.ecog, data = lung2, dist = dist)
  lp <- predict(f, type = "lp")
  z <- (log(lung2$time) - lp) / f$scale
  cs <- -log(1 - psurvreg(lung2$time, lp, f$scale, dist))
  rr <- residuals(f, type = "matrix")
  score <- X * rr[, "dg"]
  ref <- data.frame(k = lung2$rid, fitted = lp, std_residual = z, residual = cs,
                    s1 = score[, 1], s2 = score[, 2], s3 = score[, 3], s4 = score[, 4])
  cols <- c("fitted", "std_residual", "residual", "s1", "s2", "s3", "s4")
  if (dist != "exponential") {
    ref$s5 <- rr[, "ds"]
    cols <- c(cols, "s5")
  }
  ncol_sc <- if (dist == "exponential") 4 else 5
  sql <- sprintf(paste0("SELECT rid AS k, fitted, std_residual, residual, %s FROM aft_augment_by('lung', 1, time, ",
                        "[age, sex, ecog], ev, options := {'distribution': '%s'})"),
                 paste(sprintf("score_contributions[%d] AS s%d", 1:ncol_sc, 1:ncol_sc), collapse = ", "), dist)
  lines <- c(lines, table_check(
    sprintf("survreg(Surv(time, ev) ~ age + sex + ph.ecog, dist = '%s'): lp, (log t - lp)/scale, -log S, score", dist),
    sprintf("ref_aft_%s", dist), ref, sql, cols, 1e-5))
}

# ---------------------------------------------------------------------------
# Kaplan-Meier with options
# ---------------------------------------------------------------------------
km_ref <- function(sf) {
  s <- summary(sf, censored = TRUE)
  data.frame(k = sf$time, surv = sf$surv, n_risk = sf$n.risk, n_event = sf$n.event,
             n_censor = sf$n.censor, std_err = s$std.err, conf_low = sf$lower, conf_high = sf$upper,
             cumhaz = sf$cumhaz, std_chaz = sf$std.chaz)
}
km_cols <- c("surv", "n_risk", "n_event", "n_censor", "std_err", "conf_low", "conf_high", "cumhaz", "std_chaz")
km_sql <- function(call, table) {
  sprintf(paste0("SELECT p.time AS k, p.surv, p.n_risk, p.n_event, p.n_censor, p.std_err, p.conf_low, p.conf_high, ",
                 "p.cumhaz, p.std_chaz FROM (SELECT unnest(%s) AS p FROM %s)"), call, table)
}
km_cases <- list(
  list("survfit(Surv(time, ev) ~ 1) (defaults through the options form)",
       survfit(Surv(time, ev) ~ 1, data = lung2), "kaplan_meier_agg(time, ev, {'conf_type': 'log'})", "lung"),
  list("survfit(..., ctype = 2, conf.type = 'log-log', conf.int = 0.9)",
       survfit(Surv(time, ev) ~ 1, data = lung2, ctype = 2, conf.type = "log-log", conf.int = 0.9),
       "kaplan_meier_agg(time, ev, {'hazard': 'fleming-harrington', 'conf_type': 'log-log', 'conf_level': 0.9})",
       "lung"),
  list("survfit(..., weights = w) (integer weights: Greenwood)",
       survfit(Surv(time, ev) ~ 1, data = lung2, weights = w),
       "kaplan_meier_agg(time, ev, [w], {'weight': 1})", "lung"),
  list("survfit(..., weights = wf) (fractional weights: robust by default)",
       survfit(Surv(time, ev) ~ 1, data = lung2, weights = wf),
       "kaplan_meier_agg(time, ev, [age, wf], {'weight': 2})", "lung"),
  # With ctype = 2 and robust = TRUE, survfit flags its (unchanged) infinitesimal-jackknife SE
  # of S as a log-scale SE (logse = TRUE), so summary()$std.err and the limits differ from the
  # ctype = 1 fit of the same curve; anofox-regression keeps the ctype = 1 values. Only the
  # cumulative hazard and its SE are compared for that combination.
  list("survfit(..., weights = w, robust = TRUE, ctype = 2): cumhaz and std.chaz",
       survfit(Surv(time, ev) ~ 1, data = lung2, weights = w, robust = TRUE, ctype = 2),
       "kaplan_meier_agg(time, ev, [w], {'weight': 1, 'robust': true, 'hazard': 'fleming-harrington'})", "lung",
       c("surv", "n_risk", "cumhaz", "std_chaz")),
  list("survfit(..., weights = w, robust = TRUE)",
       survfit(Surv(time, ev) ~ 1, data = lung2, weights = w, robust = TRUE),
       "kaplan_meier_agg(time, ev, [w], {'weight': 1, 'robust': true})", "lung"),
  list("survfit(..., robust = TRUE, conf.type = 'plain')",
       survfit(Surv(time, ev) ~ 1, data = lung2, robust = TRUE, conf.type = "plain"),
       "kaplan_meier_agg(time, ev, {'robust': true, 'conf_type': 'plain'})", "lung"),
  list("survfit(Surv(start, stop, event) ~ 1) (left truncation)",
       survfit(Surv(start, stop, event) ~ 1, data = heart),
       "kaplan_meier_agg(stop, event, [start], {'entry': 1})", "heart"),
  list("survfit(Surv(start, stop, event) ~ 1, cluster = id) (robust)",
       survfit(Surv(start, stop, event) ~ 1, data = heart, cluster = id),
       "kaplan_meier_agg(stop, event, [id, start], {'entry': 2, 'cluster': 1})", "heart"),
  list("survfit(Surv(start, stop, event) ~ 1, cluster = id, robust = FALSE, ctype = 2)",
       suppressWarnings(survfit(Surv(start, stop, event) ~ 1, data = heart, cluster = id, robust = FALSE, ctype = 2)),
       "kaplan_meier_agg(stop, event, [id, start], {'entry': 2, 'cluster': 1, 'robust': false, 'hazard': 'fleming-harrington'})",
       "heart"))
for (i in seq_along(km_cases)) {
  cs <- km_cases[[i]]
  cols <- if (length(cs) >= 5) cs[[5]] else km_cols
  lines <- c(lines, table_check(cs[[1]], sprintf("ref_km_%d", i), km_ref(cs[[2]]), km_sql(cs[[3]], cs[[4]]),
                                cols, 1e-9))
}

# ---------------------------------------------------------------------------
# survdiff: rho and strata
# ---------------------------------------------------------------------------
sd_check <- function(label, sd, call, table) {
  e <- if (is.matrix(sd$exp)) rowSums(sd$exp) else sd$exp
  df <- sum(e > 0) - 1
  ref <- c("r.statistic" = sd$chisq, "r.df1" = df,
           "r.p_value" = pchisq(sd$chisq, df, lower.tail = FALSE), "r.n" = sum(sd$n))
  stopifnot(abs(ref[["r.p_value"]] - pchisq(sd$chisq, length(sd$n) - 1, lower.tail = FALSE)) < 1e-12)
  checks(label, sprintf("(SELECT %s AS r FROM %s)", call, table), names(ref), unname(ref), 1e-9)
}
lines <- c(lines,
  sd_check("survdiff(Surv(time, ev) ~ sex, rho = 1) (Peto-Peto)",
           survdiff(Surv(time, ev) ~ sex, data = lung2, rho = 1),
           "log_rank_test_agg(time, ev, sex::BIGINT, {'rho': 1})", "lung"),
  sd_check("survdiff(Surv(time, ev) ~ ph.ecog, rho = 0.5) (3 groups)",
           survdiff(Surv(time, ev) ~ ph.ecog, data = lung2, rho = 0.5),
           "log_rank_test_agg(time, ev, ecog::BIGINT, {'rho': 0.5})", "lung"),
  sd_check("survdiff(Surv(time, ev) ~ sex + strata(ph.ecog))",
           survdiff(Surv(time, ev) ~ sex + strata(ph.ecog), data = lung2),
           "log_rank_test_agg(time, ev, sex::VARCHAR, [ecog], {'strata': 1})", "lung"),
  sd_check("survdiff(Surv(time, ev) ~ sex + strata(ph.ecog), rho = 1)",
           survdiff(Surv(time, ev) ~ sex + strata(ph.ecog), data = lung2, rho = 1),
           "log_rank_test_agg(time, ev, sex::VARCHAR, [age, ecog], {'strata': 2, 'rho': 1})", "lung"),
  sd_check("survdiff(Surv(time, ev) ~ sex) via the options form with rho = 0 (anofox-statistics path)",
           survdiff(Surv(time, ev) ~ sex, data = lung2),
           "log_rank_test_agg(time, ev, sex::BIGINT, {'rho': 0})", "lung"))

writeLines(lines, file.path(out_dir, "survival_extras.test"))
cat("wrote", file.path(out_dir, "survival_extras.test"), "\n")
