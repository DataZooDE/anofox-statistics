check <- function(comment, call, exprs, refs) {
  if (!all(is.finite(refs))) stop("non-finite reference in: ", comment)
  stopifnot(length(exprs) == length(refs))
  emit("# ", comment)
  emit("query ", strrep("I", length(exprs)))
  emit("SELECT")
  conds <- sprintf("    abs((%s) - (%s)) <= %s * (1 + abs(%s))", exprs, fmt(refs), tol, fmt(refs))
  emit(paste(conds, collapse = ",\n"))
  emit("FROM (SELECT ", call, " AS r FROM d) s;")
  emit("----")
  emit(paste(rep("true", length(exprs)), collapse = "\t"))
  emit("")
}

# Wald F test of all slopes with covariance V (lmtest::waldtest(fit, vcov = V, test = "F")
# with an intercept; the same formula by hand without one).
wald_f <- function(fit, V, intercept = TRUE) {
  if (intercept) {
    wt <- waldtest(fit, vcov = V, test = "F")
    return(c(wt$F[2], wt$`Pr(>F)`[2]))
  }
  b <- coef(fit)
  q <- length(b)
  f <- drop(t(b) %*% solve(V, b)) / q
  c(f, pf(f, q, df.residual(fit), lower.tail = FALSE))
}

# One block of checks: coefficient inference (coeftest / coefci with the residual
# degrees of freedom), the covariance entries, the F test and n_clusters.
block <- function(label, fit, V, call, intercept = TRUE, n_clusters) {
  ct <- coeftest(fit, vcov. = V)
  ci <- coefci(fit, vcov. = V, level = 0.95)
  k <- nrow(ct)
  off <- if (intercept) 1 else 0
  slopes <- (off + 1):k
  ex <- c(); rf <- c()
  for (j in seq_along(slopes)) {
    r <- slopes[j]
    ex <- c(ex, sprintf("r.std_errors[%d]", j), sprintf("r.t_values[%d]", j), sprintf("r.p_values[%d]", j),
            sprintf("r.conf_low[%d]", j), sprintf("r.conf_high[%d]", j))
    rf <- c(rf, ct[r, 2], ct[r, 3], ct[r, 4], ci[r, 1], ci[r, 2])
  }
  check(paste0(label, ": slope std_errors, t, p, CI = coeftest / coefci(fit, vcov = V)"), call, ex, rf)
  if (intercept) {
    check(paste0(label, ": intercept inference"), call,
          c("r.intercept_std_error", "r.intercept_statistic", "r.intercept_p_value",
            "r.intercept_conf_low", "r.intercept_conf_high"),
          c(ct[1, 2], ct[1, 3], ct[1, 4], ci[1, 1], ci[1, 2]))
  }
  vv <- as.vector(t(unclass(V)))
  check(paste0(label, ": vcov (row-major, intercept first) = V"), call,
        sprintf("r.vcov[%d]", seq_along(vv)), vv)
  f <- wald_f(fit, V, intercept)
  check(paste0(label, ": F test = waldtest(fit, vcov = V, test = 'F')"), call,
        c("r.f_statistic", "r.f_pvalue", "r.df_residual"), c(f, df.residual(fit)))
  emit("# ", label, ": clusters per dimension")
  emit("query T")
  emit("SELECT r.n_clusters::VARCHAR FROM (SELECT ", call, " AS r FROM d) s;")
  emit("----")
  emit("[", paste(n_clusters, collapse = ", "), "]")
  emit("")
}

ng <- function(...) sapply(list(...), function(v) length(unique(v)))

fit <- lm(y ~ x1 + x2, data = d)

# Default: vcovCL's default for lm, type HC1 with cadjust (Stata's CR1).
V <- vcovCL(fit, cluster = ~firm)
block("OLS, firm, default (HC1, cadjust)", fit, V, "ols_fit_agg(y, [x1, x2], firm, MAP {})",
      n_clusters = ng(d$firm))
emit("query T")
emit("SELECT r.vcov_type FROM (SELECT ols_fit_agg(y, [x1, x2], firm, MAP {}) AS r FROM d) s;")
emit("----")
emit("cluster_HC1")
emit("")

for (ty in c("HC0", "HC2", "HC3")) {
  V <- vcovCL(fit, cluster = ~firm, type = ty)
  block(paste0("OLS, firm, type ", ty), fit, V,
        sprintf("ols_fit_agg(y, [x1, x2], firm, {'hc_type': '%s'})", tolower(ty)), n_clusters = ng(d$firm))
}

# No correction: rms::robcov(ols(...), cluster) == vcovCL(type = "HC0", cadjust = FALSE).
V <- vcovCL(fit, cluster = ~firm, type = "HC0", cadjust = FALSE)
rfit <- robcov(ols(y ~ x1 + x2, data = d, x = TRUE, y = TRUE), cluster = d$firm)
stopifnot(max(abs(unclass(vcov(rfit)) - unclass(V))) < 1e-12)
block("OLS, firm, HC0 without cadjust (= rms::robcov)", fit, V,
      "ols_fit_agg(y, [x1, x2], firm, {'hc_type': 'hc0', 'cadjust': false})", n_clusters = ng(d$firm))

# Integer cluster ids (year).
V <- vcovCL(fit, cluster = ~yr)
block("OLS, yr (INTEGER ids), default", fit, V, "ols_fit_agg(y, [x1, x2], yr, MAP {})", n_clusters = ng(d$yr))

# Two-way clustering (Cameron, Gelbach & Miller): vcovCL(cluster = ~firm + yr).
V <- vcovCL(fit, cluster = ~firm + yr)
block("OLS, firm x yr two-way (LIST), default", fit, V,
      "ols_fit_agg(y, [x1, x2], [firm, yr::VARCHAR], MAP {})", n_clusters = ng(d$firm, d$yr))
V <- vcovCL(fit, cluster = ~firm + yr, type = "HC0", cadjust = FALSE)
block("OLS, firm x yr two-way (STRUCT), HC0 without cadjust", fit, V,
      "ols_fit_agg(y, [x1, x2], {'f': firm, 'y': yr}, {'hc_type': 'hc0', 'cadjust': false})",
      n_clusters = ng(d$firm, d$yr))

# No intercept.
fit0 <- lm(y ~ x1 + x2 - 1, data = d)
V <- vcovCL(fit0, cluster = ~firm)
block("OLS without intercept, firm, default", fit0, V,
      "ols_fit_agg(y, [x1, x2], firm, {'fit_intercept': false})", intercept = FALSE, n_clusters = ng(d$firm))

# Confidence level.
V <- vcovCL(fit, cluster = ~firm)
ci90 <- coefci(fit, vcov. = V, level = 0.9)
check("OLS, firm, confidence_level 0.9: coefci(level = 0.9)",
      "ols_fit_agg(y, [x1, x2], firm, {'confidence_level': 0.9})",
      c("r.conf_low[1]", "r.conf_high[1]", "r.conf_low[2]", "r.conf_high[2]",
        "r.intercept_conf_low", "r.intercept_conf_high"),
      c(ci90[2, 1], ci90[2, 2], ci90[3, 1], ci90[3, 2], ci90[1, 1], ci90[1, 2]))

# WLS.
wfit <- lm(y ~ x1 + x2, data = d, weights = w)
V <- vcovCL(wfit, cluster = ~firm)
block("WLS, firm, default (HC1, cadjust)", wfit, V, "wls_fit_agg(y, [x1, x2], w, firm, MAP {})",
      n_clusters = ng(d$firm))
V <- vcovCL(wfit, cluster = ~firm, type = "HC2")
block("WLS, firm, type HC2", wfit, V, "wls_fit_agg(y, [x1, x2], w, firm, {'hc_type': 'hc2'})",
      n_clusters = ng(d$firm))
V <- vcovCL(wfit, cluster = ~firm + yr)
block("WLS, firm x yr two-way, default", wfit, V, "wls_fit_agg(y, [x1, x2], w, [firm, yr::VARCHAR], MAP {})",
      n_clusters = ng(d$firm, d$yr))

# Point estimates are the sibling's (lm), unchanged by clustering.
check("coefficients and fit statistics are lm's", "ols_fit_agg(y, [x1, x2], firm, MAP {})",
      c("r.intercept", "r.coefficients[1]", "r.coefficients[2]", "r.r_squared", "r.residual_std_error"),
      c(coef(fit), summary(fit)$r.squared, summary(fit)$sigma))

writeLines(lines, out_file)
cat("wrote", out_file, "\n")
