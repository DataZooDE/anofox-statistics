# Reference values for the cluster-robust (sandwich) covariance of ols_fit_agg /
# wls_fit_agg (#309): R sandwich::vcovCL, lmtest::coeftest / coefci / waldtest
# and rms::robcov.
#
#   Rscript validation/generators/make_reference_cluster_vcov.R
#
# (Re)writes test/sql/reference/cluster_vcov.test. The dataset is a literal
# constant (no RNG), so the output does not depend on R's RNG implementation.
suppressMessages({
  library(sandwich)
  library(lmtest)
  library(rms)
})

out_file <- "test/sql/reference/cluster_vcov.test"
tol <- "1e-09"

n <- 30
i <- 0:(n - 1)
# Unbalanced firm x year cells (22 of 30 distinct) so that the two-way
# inclusion-exclusion covariance is positive definite.
firm <- c("a", "b", "c", "d", "e", "f")[((i * 6 + i %/% 4) %% 6) + 1]
yr <- 2000L + ((i * 3 + i %/% 7) %% 5)
x1 <- round(sin(i / 2.5) * 3 + (i %% 4), 2)
x2 <- round(cos(i / 3.7) * 2 + (i %% 3) / 2, 2)
firm_eff <- c(a = 0.8, b = -0.5, c = 0.3, d = -1.1, e = 0.6, f = 0.1)[firm]
yr_eff <- c(0.4, -0.2, 0.1, -0.5, 0.3)[yr - 1999L]
y <- round(1 + 0.7 * x1 - 0.4 * x2 + firm_eff + yr_eff + ((i * 11) %% 7 - 3) / 6, 2)
w <- round(0.5 + ((i * 5) %% 9) / 8, 3)
d <- data.frame(id = i + 1, y, x1, x2, w, firm, yr, stringsAsFactors = FALSE)

