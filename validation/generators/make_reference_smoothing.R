#!/usr/bin/env Rscript
# R references for test/sql/reference/lowess_reference.test and
# test/sql/reference/lm_dynamic_reference.test (#63).
#
#   Rscript validation/generators/make_reference_smoothing.R
#
# lowess_agg / lowess_by against stats::lowess, lm_dynamic_fit_agg against
# greybox::lmDynamic(bruteforce = TRUE) (normal distribution, explicit lowess f;
# greybox picks f by optimisation when it is not given).

suppressMessages(library(greybox))

TOL <- "1e-08"

fmt <- function(v) sprintf("%.17g", v)
close <- function(expr, value) {
  sprintf("abs((%s) - (%s)) <= %s * (1 + abs(%s))", expr, fmt(value), TOL, fmt(value))
}

check <- function(out, title, query, conds) {
  c(out,
    paste0("# ", title),
    paste0("query ", strrep("I", length(conds))),
    "SELECT",
    paste0("    ", conds, collapse = ",\n"),
    query,
    "----",
    paste(rep("true", length(conds)), collapse = "\t"),
    "")
}

header <- function(name, description) {
  c(paste0("# name: test/sql/reference/", name),
    paste0("# description: ", description),
    "# group: [reference]",
    "#",
    "# GENERATED by validation/generators/make_reference_smoothing.R -- do not edit",
    "# by hand; change the generator and re-run it instead.",
    paste0("# Reference: ", R.version.string, ", greybox ", as.character(packageVersion("greybox"))),
    "",
    "require anofox_statistics",
    "")
}

insert <- function(out, table, df) {
  rows <- apply(df, 1, function(r) paste0("(", paste(fmt(as.numeric(r)), collapse = ", "), ")"))
  c(out, "statement ok",
    paste0("CREATE TABLE ", table, " (", paste(names(df), "DOUBLE", collapse = ", "), ");"), "",
    "statement ok", paste0("INSERT INTO ", table, " VALUES"), paste0(paste(rows, collapse = ",\n"), ";"), "")
}

# -----------------------------------------------------------------------------
# LOWESS
# -----------------------------------------------------------------------------
set.seed(63)
n <- 50
s <- data.frame(t = 1:n, x = round(runif(n, 0, 10), 3))
s$y <- round(sin(s$x) + rnorm(n, sd = 0.3), 3)
s$y[c(7, 30)] <- s$y[c(7, 30)] + c(3, -2.5)    # outliers for the robustness passes
ties <- data.frame(t = 1:20, x = rep(c(1, 2, 2.5, 4, 4, 4, 7, 8, 8, 10), 2))
ties$y <- round(log(ties$x) + rnorm(20, sd = 0.2), 3)

lw <- header("lowess_reference.test", "lowess_agg / lowess_by against R stats::lowess (#63)")
lw <- insert(lw, "s", s)
lw <- insert(lw, "ties", ties)

lowess_case <- function(out, title, table, call, fit, idx) {
  conds <- c(sprintf("len(c) = %d", length(fit$x)))
  for (k in idx) {
    conds <- c(conds, close(sprintf("c[%d].x", k), fit$x[k]), close(sprintf("c[%d].yhat", k), fit$y[k]))
  }
  check(out, title, sprintf("FROM (SELECT %s AS c FROM %s)", call, table), conds)
}

f <- lowess(s$x, s$y)
lw <- lowess_case(lw, "lowess_agg(y, x): R defaults (f = 2/3, iter = 3) on unsorted x with outliers", "s",
                  "lowess_agg(y, x)", f, c(1, 2, 13, 25, 26, 38, 50))
f <- lowess(s$x, s$y, f = 0.2, iter = 0)
lw <- lowess_case(lw, "lowess_agg(y, x, 0.2, 0): small span, no robustness iterations", "s",
                  "lowess_agg(y, x, 0.2, 0)", f, c(1, 9, 17, 33, 41, 50))
f <- lowess(s$x, s$y, f = 0.3, iter = 5)
lw <- lowess_case(lw, "lowess_agg(y, x, 0.3, 5)", "s", "lowess_agg(y, x, 0.3, 5)", f, c(1, 20, 50))
f <- lowess(ties$x, ties$y, f = 0.6)
lw <- lowess_case(lw, "lowess_agg(y, x, 0.6): tied x values", "ties", "lowess_agg(y, x, 0.6)", f, 1:20)

# lowess_by: the same curve per group, in the contract's curve schema
f <- lowess(s$x, s$y, f = 0.4)
conds <- c("count(*) = 50", "bool_and(curve_type = 'lowess' AND model_id = 'lowess')")
for (k in c(1, 25, 50)) {
  conds <- c(conds, close(sprintf("list(y ORDER BY x)[%d]", k), f$y[k]))
}
lw <- check(lw, "lowess_by(..., frac := 0.4): one curve point per row, x increasing",
            "FROM lowess_by('s', 1, x, y, frac := 0.4)", conds)
writeLines(lw, "test/sql/reference/lowess_reference.test")

# -----------------------------------------------------------------------------
# lmDynamic
# -----------------------------------------------------------------------------
set.seed(1)
n <- 40
d <- data.frame(t = 1:n, x1 = round(rnorm(n), 3), x2 = round(rnorm(n), 3), x3 = round(runif(n), 3))
d$y <- round(1 + ifelse(d$t > 20, 1.5, 0.3) * d$x1 + 0.4 * d$x2 + rnorm(n, sd = 0.8), 3)

ld <- header("lm_dynamic_reference.test",
             "lm_dynamic_fit_agg against greybox::lmDynamic(bruteforce = TRUE), normal distribution (#63)")
ld <- insert(ld, "d", d)
ld <- c(ld, "statement ok", "CREATE TABLE shuffled AS SELECT * FROM d ORDER BY (t * 13) % 41;", "")

dyn_case <- function(out, title, data, ic, f, options, xs) {
  fit <- suppressWarnings(lmDynamic(data, ic = ic, bruteforce = TRUE, lowess = !is.null(f), f = f))
  cd <- fit$coefficientsDynamic
  conds <- c(close("m.intercept", fit$coefficients[1]))
  for (j in seq_along(xs)) conds <- c(conds, close(sprintf("m.coefficients[%d]", j), fit$coefficients[j + 1]))
  conds <- c(conds, close("m.log_likelihood", as.numeric(logLik(fit))),
             sprintf("m.n_models = %d", ncol(fit$weights)))
  for (t in c(1, 10, 21, 40)) {
    conds <- c(conds, close(sprintf("m.dynamic_intercept[%d]", t), cd[t, 1]))
    for (j in seq_along(xs)) {
      conds <- c(conds, close(sprintf("m.dynamic_coefficients[%d][%d]", t, j), cd[t, j + 1]))
    }
  }
  call <- sprintf("lm_dynamic_fit_agg(y, [%s], %s ORDER BY t)", paste(xs, collapse = ", "), options)
  check(out, title, sprintf("FROM (SELECT %s AS m FROM shuffled)", call), conds)
}

ld <- dyn_case(ld, "AICc, no smoothing: lmDynamic(ic = 'AICc', lowess = FALSE)",
               d[, c("y", "x1", "x2")], "AICc", NULL, "{'ic': 'aicc', 'span': 0}", c("x1", "x2"))
ld <- dyn_case(ld, "AIC, lowess f = 0.5", d[, c("y", "x1", "x2")], "AIC", 0.5, "{'ic': 'aic', 'span': 0.5}",
               c("x1", "x2"))
ld <- dyn_case(ld, "BIC, three regressors, lowess f = 0.3", d[, c("y", "x1", "x2", "x3")], "BIC", 0.3,
               "{'ic': 'bic', 'span': 0.3}", c("x1", "x2", "x3"))
writeLines(ld, "test/sql/reference/lm_dynamic_reference.test")
cat("wrote test/sql/reference/lowess_reference.test and lm_dynamic_reference.test\n")
