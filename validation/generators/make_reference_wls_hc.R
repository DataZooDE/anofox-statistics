# Reference values for the heteroskedasticity-consistent standard errors of
# wls_fit_agg(y, x, w, {'hc_type': ...}) without a cluster: R
# sandwich::vcovHC(lm(y ~ x1 + x2, weights = w), type = "HC0".."HC3") with
# lmtest::coeftest / coefci (t with the residual degrees of freedom). The F
# test stays the classical one of summary(lm(..., weights = w)).
#
#   Rscript validation/generators/make_reference_wls_hc.R
#
# (Re)writes test/sql/reference/wls_hc.test. The dataset is the literal one
# of make_reference_cluster_vcov.R (no RNG).
suppressMessages({
  library(sandwich)
  library(lmtest)
})

out_file <- "test/sql/reference/wls_hc.test"
tol <- "1e-09"

n <- 30
i <- 0:(n - 1)
x1 <- round(sin(i / 2.5) * 3 + (i %% 4), 2)
x2 <- round(cos(i / 3.7) * 2 + (i %% 3) / 2, 2)
y <- round(1 + 0.7 * x1 - 0.4 * x2 + (x1^2 / 6) * ((i * 11) %% 7 - 3) / 3, 2)
w <- round(0.5 + ((i * 5) %% 9) / 8, 3)
d <- data.frame(id = i + 1, y, x1, x2, w)

fmt <- function(v) formatC(v, digits = 17, format = "g")
lines <- character()
emit <- function(...) lines <<- c(lines, paste0(...))

emit("# name: test/sql/reference/wls_hc.test")
emit("# description: wls_fit_agg hc_type (no cluster) against R sandwich::vcovHC(lm(..., weights = w)) with lmtest::coeftest / coefci")
emit("# group: [reference]")
emit("#")
emit("# GENERATED by validation/generators/make_reference_wls_hc.R -- do not edit")
emit("# by hand; change the generator and re-run it instead.")
emit("# Reference: ", R.version.string, ", sandwich ", as.character(packageVersion("sandwich")),
     ", lmtest ", as.character(packageVersion("lmtest")))
emit("")
emit("require anofox_statistics")
emit("")
emit("statement ok")
emit("CREATE TABLE d (id INTEGER, y DOUBLE, x1 DOUBLE, x2 DOUBLE, w DOUBLE);")
emit("")
emit("statement ok")
emit("INSERT INTO d VALUES")
rows <- sprintf("(%d, %s, %s, %s, %s)", d$id, fmt(d$y), fmt(d$x1), fmt(d$x2), fmt(d$w))
emit(paste0(rows, c(rep(",", n - 1), ";"), collapse = "\n"))
emit("")

check <- function(comment, call, exprs, refs) {
  if (!all(is.finite(refs))) stop("non-finite reference in: ", comment)
  stopifnot(length(exprs) == length(refs))
  emit("# ", comment)
  emit("query ", strrep("I", length(exprs)))
  emit("SELECT")
  conds <- sprintf("    abs((%s) - (%s)) <= %s * (1 + abs(%s))", exprs, fmt(refs), tol, fmt(refs))
  emit(paste(conds, collapse = ",\n"))
  emit("FROM (SELECT ", call, " AS r FROM d) s;")
  emit("----")
  emit(paste(rep("true", length(exprs)), collapse = "\t"))
  emit("")
}

block <- function(label, fit, V, call, intercept = TRUE) {
  ct <- coeftest(fit, vcov. = V)
  ci <- coefci(fit, vcov. = V, level = 0.95)
  off <- if (intercept) 1 else 0
  slopes <- (off + 1):nrow(ct)
  ex <- c(); rf <- c()
  for (j in seq_along(slopes)) {
    r <- slopes[j]
    ex <- c(ex, sprintf("r.std_errors[%d]", j), sprintf("r.t_values[%d]", j), sprintf("r.p_values[%d]", j),
            sprintf("r.conf_low[%d]", j), sprintf("r.conf_high[%d]", j))
    rf <- c(rf, ct[r, 2], ct[r, 3], ct[r, 4], ci[r, 1], ci[r, 2])
  }
  check(paste0(label, ": slope std_errors, t, p, CI = coeftest / coefci(fit, vcov = vcovHC)"), call, ex, rf)
  if (intercept) {
    check(paste0(label, ": intercept inference"), call,
          c("r.intercept_std_error", "r.intercept_statistic", "r.intercept_p_value",
            "r.intercept_conf_low", "r.intercept_conf_high"),
          c(ct[1, 2], ct[1, 3], ct[1, 4], ci[1, 1], ci[1, 2]))
  }
  fs <- summary(fit)$fstatistic
  check(paste0(label, ": classical F test (summary(lm(..., weights = w)))"), call,
        c("r.f_statistic", "r.f_pvalue", "r.df_residual"),
        c(fs[["value"]], pf(fs[["value"]], fs[["numdf"]], fs[["dendf"]], lower.tail = FALSE), df.residual(fit)))
}

fit <- lm(y ~ x1 + x2, data = d, weights = w)
for (ty in c("HC0", "HC1", "HC2", "HC3")) {
  block(paste0("WLS, ", ty), fit, vcovHC(fit, type = ty),
        sprintf("wls_fit_agg(y, [x1, x2], w, {'hc_type': '%s', 'compute_inference': true})", tolower(ty)))
}

# The weights matter: the unweighted HC3 of the same coefficients' residuals
# (what the extension reported before) differs from vcovHC of the weighted fit.
stopifnot(abs(sqrt(diag(vcovHC(fit, type = "HC3")))[2] -
              sqrt(diag(vcovHC(lm(y ~ x1 + x2, data = d), type = "HC3")))[2]) > 1e-3)

fit0 <- lm(y ~ x1 + x2 - 1, data = d, weights = w)
block("WLS without intercept, HC3", fit0, vcovHC(fit0, type = "HC3"),
      "wls_fit_agg(y, [x1, x2], w, {'hc_type': 'hc3', 'fit_intercept': false, 'compute_inference': true})", intercept = FALSE)

# Unit weights: the same as ols_fit_agg with hc_type.
emit("# Unit weights: wls_fit_agg(hc_type) = ols_fit_agg(hc_type)")
emit("query IIII")
emit("SELECT")
emit(paste(sprintf(paste0("    list_distance((wls_fit_agg(y, [x1, x2], 1.0, {'hc_type': '%s', 'compute_inference': true})).std_errors, ",
                          "(ols_fit_agg(y, [x1, x2], {'hc_type': '%s', 'compute_inference': true})).std_errors) < 1e-9"),
                   c("hc0", "hc1", "hc2", "hc3"), c("hc0", "hc1", "hc2", "hc3")), collapse = ",\n"))
emit("FROM d;")
emit("----")
emit("true\ttrue\ttrue\ttrue")
emit("")

writeLines(lines, out_file)
cat("wrote", out_file, "\n")
