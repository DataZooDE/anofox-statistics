#!/usr/bin/env python3
"""NannyML 0.13.1 reference values for test/sql/reference/reconstruction_reference.test (#366, #367).

Usage:
  uv run --no-project --python 3.11 --with nannyml==0.13.1 --with statsmodels \
      python3 validation/generators/make_reference_reconstruction.py > test/sql/reference/reconstruction_reference.test

Data: NannyML's synthetic car-loan dataset (first 2000 reference and 2000
analysis rows, the numeric columns car_value, debt_to_income_ratio,
loan_length, driver_tenure), chunks of 400 rows.

- DataReconstructionDriftCalculator: per-chunk reconstruction error, sampling
  error, confidence band, thresholds and alert, for n_components = 0.65
  (default), 2, a non-default StandardDeviationThreshold, and with missing
  values (NannyML imputes the reference column means).
- Row reconstruction errors: StandardScaler + PCA(n_components = 0.65) of
  scikit-learn, as NannyML fits them.
- nannyml.thresholds: StandardDeviationThreshold, ConstantThreshold and
  calculate_threshold_values (value limits, override_using_none).
"""
import math

import numpy as np
import nannyml as nml
from sklearn.decomposition import PCA
from sklearn.preprocessing import StandardScaler

COLS = ["car_value", "debt_to_income_ratio", "loan_length", "driver_tenure"]
N, CHUNK = 2000, 400
TOL = "1e-9"

ref_all, ana_all, _ = nml.load_synthetic_car_loan_dataset()
ref = ref_all.iloc[:N].reset_index(drop=True)
ana = ana_all.iloc[:N].reset_index(drop=True)

out = []
emit = out.append


def lit(v):
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return "NULL"
    return repr(float(v))


def table(name, frame):
    emit("statement ok")
    emit(f"CREATE TABLE {name} (id INTEGER, chunk INTEGER, period VARCHAR, "
         f"{', '.join(c + ' DOUBLE' for c in COLS)})")
    emit("")
    emit("statement ok")
    emit(f"INSERT INTO {name} VALUES")
    lines = []
    for period, df in frame:
        for i, row in df[COLS].iterrows():
            lines.append(f"({i}, {i // CHUNK}, '{period}', " + ", ".join(lit(row[c]) for c in COLS) + ")")
    emit(",\n".join(lines) + ";")
    emit("")


def close(expr, value):
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return f"({expr} IS NULL)"
    return f"(abs({expr} - {lit(value)}) <= {TOL} * (1 + {abs(float(value))!r}))"


def dre_case(title, table_name, reference, analysis, n_components, threshold, sql_options, sql_threshold):
    kwargs = {"n_components": n_components}
    if threshold is not None:
        kwargs["threshold"] = threshold
    calc = nml.DataReconstructionDriftCalculator(column_names=COLS, chunk_size=CHUNK, **kwargs)
    calc.fit(reference)
    res = calc.calculate(analysis).to_df()
    emit(f"# {title}: NannyML picks {calc._pca.n_components_} components")
    emit("query IIIII")
    checks = []
    expected = []
    for period in ["reference", "analysis"]:
        p = res[res[("chunk", "period")] == period].reset_index(drop=True)
        for k in range(len(p)):
            g = lambda col: float(p.loc[k, ("reconstruction_error", col)])
            checks.append(
                f"WHEN chunk = {k} AND is_reference = {str(period == 'reference').lower()} THEN ["
                + ", ".join([
                    close("reconstruction_error", g("value")),
                    close("sampling_error", g("sampling_error")),
                    close("lower_confidence", g("lower_confidence_boundary")),
                    close("upper_confidence", g("upper_confidence_boundary")),
                    close("lower_threshold", g("lower_threshold")),
                    close("upper_threshold", g("upper_threshold")),
                ])
                + "]")
            alert = bool(p.loc[k, ("reconstruction_error", "alert")])
            expected.append(f"{k}\t{str(period == 'reference').lower()}\t{CHUNK}\ttrue\t{str(alert).lower()}")
    emit("SELECT chunk, is_reference, n, list_bool_and(c), alert FROM (")
    emit("    SELECT *, CASE " + "\n        ".join(checks) + " END AS c")
    args = f"'{table_name}', chunk, [{', '.join(COLS)}], period = 'reference'"
    if sql_options:
        args += f", options := {sql_options}"
    if sql_threshold:
        args += f", threshold := {sql_threshold}"
    emit(f"    FROM pca_reconstruction_drift_by({args}))")
    emit("----")
    out.extend(expected)
    emit("")
    return calc


emit("# name: test/sql/reference/reconstruction_reference.test")
emit("# description: pca_reconstruction_* and alert_band_agg / alert_band_by (#366, #367) vs NannyML 0.13.1")
emit("# group: [reference]")
emit("#")
emit("# GENERATED by validation/generators/make_reference_reconstruction.py -- do not edit by hand.")
emit("# Reference: nannyml.DataReconstructionDriftCalculator on the synthetic car-loan dataset (first 2000")
emit("# reference / analysis rows, chunks of 400), scikit-learn StandardScaler + PCA for row errors, and")
emit("# nannyml.thresholds (StandardDeviationThreshold, ConstantThreshold, calculate_threshold_values).")
emit(f"# Tolerance: |a - b| <= {TOL} * (1 + |b|).")
emit("")
emit("require anofox_statistics")
emit("")
table("car_loan", [("reference", ref), ("analysis", ana)])

dre_case("Default: n_components = 0.65, StandardDeviationThreshold(3, 3)", "car_loan", ref, ana, 0.65, None,
         None, None)
dre_case("Fixed n_components = 2", "car_loan", ref, ana, 2, None, "{'n_components': 2}", None)
dre_case("StandardDeviationThreshold(std_lower_multiplier = 1, std_upper_multiplier = 0.5)", "car_loan", ref, ana,
         0.65, nml.thresholds.StandardDeviationThreshold(1, 0.5), "{'variance': 0.65}",
         "{'lower': 1, 'upper': 0.5}")

# Missing values, imputed by the reference column means (SQL NULL).
ref_nan, ana_nan = ref.copy(), ana.copy()
ref_nan.loc[::37, "car_value"] = np.nan
ref_nan.loc[5::53, "driver_tenure"] = np.nan
ana_nan.loc[::11, "debt_to_income_ratio"] = np.nan
ana_nan.loc[3::17, "car_value"] = np.nan
# The same positions in SQL (pandas .loc[a::b] is id >= a AND (id - a) % b = 0).
emit("statement ok")
emit("CREATE TABLE car_loan_nan AS SELECT id, chunk, period,")
emit("    CASE WHEN period = 'reference' AND id % 37 = 0 THEN NULL"
     " WHEN period = 'analysis' AND id >= 3 AND (id - 3) % 17 = 0 THEN NULL ELSE car_value END AS car_value,")
emit("    CASE WHEN period = 'analysis' AND id % 11 = 0 THEN NULL ELSE debt_to_income_ratio END"
     " AS debt_to_income_ratio,")
emit("    loan_length,")
emit("    CASE WHEN period = 'reference' AND id >= 5 AND (id - 5) % 53 = 0 THEN NULL ELSE driver_tenure END"
     " AS driver_tenure")
emit("FROM car_loan")
emit("")
emit("query II")
emit("SELECT count(*) FILTER (WHERE car_value IS NULL), count(*) FILTER (WHERE driver_tenure IS NULL) FROM car_loan_nan")
emit("----")
emit(f"{int(ref_nan['car_value'].isna().sum() + ana_nan['car_value'].isna().sum())}\t"
     f"{int(ref_nan['driver_tenure'].isna().sum())}")
emit("")
dre_case("Missing values (mean imputation)", "car_loan_nan", ref_nan, ana_nan, 0.65, None, None, None)

# Row errors of the first analysis rows (NannyML's StandardScaler + PCA(0.65)).
sc = StandardScaler().fit(ref[COLS])
pca = PCA(n_components=0.65, random_state=16).fit(sc.transform(ref[COLS]))
z = sc.transform(ana[COLS].iloc[:10])
errors = np.linalg.norm(z - pca.inverse_transform(pca.transform(z)), axis=1)
emit("# Row reconstruction errors of the first 10 analysis rows")
emit("query II")
emit("WITH m AS (SELECT pca_reconstruction_fit_agg([" + ", ".join(COLS) + "]) AS model FROM car_loan "
     "WHERE period = 'reference')")
emit("SELECT id, " + "CASE " + " ".join(
    f"WHEN id = {i} THEN {close('pca_reconstruction_error(model, [' + ', '.join(COLS) + '])', e)}"
    for i, e in enumerate(errors)) + " END")
emit("FROM car_loan, m WHERE period = 'analysis' AND id < 10 ORDER BY id")
emit("----")
for i in range(10):
    emit(f"{i}\ttrue")
emit("")
emit("query III")
emit("SELECT (m).n_components, (m).n_features, (m).n_observations FROM (SELECT pca_reconstruction_fit_agg(["
     + ", ".join(COLS) + "]) AS m FROM car_loan WHERE period = 'reference')")
emit("----")
emit(f"{pca.n_components_}\t4\t{N}")
emit("")

# ------------------------------------------------------------ thresholds
vals = [0.91, 0.93, float("nan"), 0.92, 0.95, 0.90]
NAN_LIT = "'NaN'"
emit("statement ok")
emit("CREATE TABLE metric AS SELECT * FROM (VALUES " + ", ".join(
    f"({i}, {NAN_LIT if math.isnan(v) else repr(v)}::DOUBLE)" for i, v in enumerate(vals)) + ") t(chunk, value)")
emit("")


def band_case(title, sql_options, lower, upper):
    emit(f"# {title}")
    emit("query II")
    opts = f", {sql_options}" if sql_options else ""
    emit(f"SELECT {close('(b).lower_threshold', lower)}, {close('(b).upper_threshold', upper)} "
         f"FROM (SELECT alert_band_agg(value{opts}) AS b FROM metric)")
    emit("----")
    emit("true\ttrue")
    emit("")


def nan_none(x):
    return float("nan") if x is None else float(x)


arr = np.array(vals)
for lo, up, sql in [(3, 3, None), (2, None, "{'lower': 2, 'upper': NULL}"), (1.5, 0.5, "{'lower': 1.5, 'upper': 0.5}")]:
    t = nml.thresholds.StandardDeviationThreshold(lo, up)
    lower, upper = t.thresholds(arr)
    band_case(f"StandardDeviationThreshold({lo}, {up})", sql, nan_none(lower), nan_none(upper))
    lower, upper = nml.thresholds.calculate_threshold_values(
        t, arr, lower_threshold_value_limit=0.9, upper_threshold_value_limit=0.96)
    lim = "'lower_limit': 0.9, 'upper_limit': 0.96"
    sql_lim = "{" + (sql[1:-1] + ", " if sql else "") + lim + "}"
    band_case(f"StandardDeviationThreshold({lo}, {up}), limits [0.9, 0.96]", sql_lim, nan_none(lower),
              nan_none(upper))
    lower, upper = nml.thresholds.calculate_threshold_values(
        t, arr, lower_threshold_value_limit=0.9, upper_threshold_value_limit=0.96, override_using_none=True)
    sql_none = "{" + (sql[1:-1] + ", " if sql else "") + lim + ", 'override_with_none': true}"
    band_case(f"StandardDeviationThreshold({lo}, {up}), limits [0.9, 0.96], override_using_none", sql_none,
              nan_none(lower), nan_none(upper))

t = nml.thresholds.ConstantThreshold(lower=0.905, upper=0.94)
lower, upper = t.thresholds(arr)
band_case("ConstantThreshold(0.905, 0.94)", "{'method': 'constant', 'lower': 0.905, 'upper': 0.94}",
          nan_none(lower), nan_none(upper))
t = nml.thresholds.ConstantThreshold(lower=None, upper=0.94)
lower, upper = t.thresholds(arr)
band_case("ConstantThreshold(None, 0.94)", "{'method': 'fixed', 'upper': 0.94}", nan_none(lower), nan_none(upper))

# alert_band_by: NannyML's alert rule (value outside the band) on chunks 0-3 as reference.
t = nml.thresholds.StandardDeviationThreshold(1, 1)
ref_vals = arr[:4]
lower, upper = t.thresholds(ref_vals)
emit("# alert_band_by, reference chunks 0-3, StandardDeviationThreshold(1, 1)")
emit("query IIIII")
emit("SELECT chunk, is_reference, " + close("lower_threshold", nan_none(lower)) + ", "
     + close("upper_threshold", nan_none(upper)) + ", alert FROM alert_band_by('metric', chunk, value, chunk < 4, "
     "options := {'k': 1})")
emit("----")
order = [i for i in range(len(vals)) if i < 4] + [i for i in range(len(vals)) if i >= 4]
for i in order:
    v = vals[i]
    alert = (not math.isnan(v)) and ((lower is not None and v < lower) or (upper is not None and v > upper))
    emit(f"{i}\t{str(i < 4).lower()}\ttrue\ttrue\t{str(alert).lower()}")
emit("")

print("\n".join(out))
