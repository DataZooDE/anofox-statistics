fmt <- function(v) trimws(formatC(v, digits = 17, format = "g"))
lines <- character()
emit <- function(...) lines <<- c(lines, paste0(...))

close_to <- function(expr, ref, tol = 1e-9) {
  sprintf("abs((%s) - (%s)) <= %g * (1 + abs(%s))", expr, fmt(ref), tol, fmt(ref))
}

table_sql <- function(name, cols) {
  emit("statement ok")
  emit(sprintf("CREATE TABLE %s (t INTEGER, %s);", name,
               paste(sprintf("%s DOUBLE", names(cols)), collapse = ", ")))
  emit("")
  emit("# Rows are inserted in reverse time order: the aggregates must follow ORDER BY t.")
  emit("statement ok")
  emit(sprintf("INSERT INTO %s VALUES", name))
  n <- length(cols[[1]])
  rows <- vapply(rev(seq_len(n)), function(i) {
    sprintf("(%d, %s)", i, paste(vapply(cols, function(v) fmt(v[i]), ""), collapse = ", "))
  }, "")
  emit(paste(rows, collapse = ",\n"), ";")
  emit("")
}

spa_stats <- function(d) {
  n <- length(d[[1]])
  vapply(d, function(x) mean(x) * sqrt(n) / sqrt(var(x) / n), 0)
}

