# Reference values for principal component analysis (#303): pca_agg,
# pca_transform and pca_by. Writes test/sql/reference/pca_reference.test.
#
#   Rscript validation/generators/make_reference_pca.R
#
# Base R only (stats::prcomp, predict.prcomp, datasets::USArrests).
#
# Sign convention: prcomp's component signs come from LAPACK and are
# arbitrary. The extension (upstream anofox-statistics multivariate::pca)
# fixes each component's sign so that its loading of largest absolute value
# is positive (scikit-learn's svd_flip on the components). The generator
# applies the same flip to prcomp's rotation (and the scores) before writing
# the references, so the comparison does not depend on R's sign choice.
#
# Component count: upstream keeps min(n - 1, d) components; prcomp returns
# min(n, d), the extra one with sdev 0 when n <= d. The wide case below
# therefore compares the first n - 1 components.

out <- "test/sql/reference/pca_reference.test"
fmt <- function(v) paste(sprintf("%.15g", v), collapse = ", ")
lst <- function(v) paste0("[", fmt(v), "]")

flip <- function(p) {
  s <- apply(p$rotation, 2, function(v) sign(v[which.max(abs(v))]))
  p$rotation <- sweep(p$rotation, 2, s, `*`)
  p$x <- sweep(p$x, 2, s, `*`)
  p
}

# max over the elements of |a - b| / (1 + |b|) for list a and literal b
close_list <- function(expr, ref, tol = "1e-9") {
  sprintf("list_max(list_transform(range(1, %d), lambda _i: abs((%s)[_i] - (%s)[_i]) / (1 + abs((%s)[_i])))) < %s AND len(%s) = %d",
          length(ref) + 1, expr, lst(ref), lst(ref), tol, expr, length(ref))
}

L <- character()
w <- function(...) L <<- c(L, paste0(...))

w("# name: test/sql/reference/pca_reference.test")
w("# description: pca_agg / pca_transform / pca_by (#303) vs R prcomp")
w("# group: [reference]")
w("#")
w("# GENERATED by validation/generators/make_reference_pca.R -- do not edit by hand.")
w("# Reference: stats::prcomp(x, center = TRUE, scale. = FALSE / TRUE) and predict.prcomp.")
w("# prcomp's component signs are arbitrary; the references are flipped to the")
w("# extension's convention (each component's largest absolute loading positive).")
w("# Tolerance: |a - b| <= 1e-9 * (1 + |b|) per element.")
w("")
w("require anofox_statistics")
w("")

# --- USArrests: n = 50, d = 4 ----------------------------------------------
X <- as.matrix(USArrests)
w("statement ok")
w("CREATE TABLE usarrests AS SELECT * FROM (VALUES")
rows <- sprintf("    (%d, %s, %s, %s, %s)", seq_len(nrow(X)), X[, 1], X[, 2], X[, 3], X[, 4])
w(paste(rows, collapse = ",\n"))
w(") t(id, murder, assault, urbanpop, rape);")
w("")

p <- flip(prcomp(X, center = TRUE, scale. = FALSE))
prop <- p$sdev^2 / sum(p$sdev^2)
w("# Full fit: sdev, proportion of variance, center, counts.")
w("query IIIIII")
w("SELECT ", close_list("m.sdev", p$sdev), ",")
w("       ", close_list("m.proportion_of_variance", prop), ",")
w("       ", close_list("m.center", p$center), ",")
w("       m.n_components, m.n_features, m.n_observations")
w("FROM (SELECT pca_agg([murder, assault, urbanpop, rape]) AS m FROM usarrests);")
w("----")
w("true\ttrue\ttrue\t4\t4\t50")
w("")
w("# Loadings: loadings[j] is component j (prcomp's rotation[, j]).")
w("query IIII")
w("SELECT ", paste(sapply(1:4, function(j) close_list(sprintf("m.loadings[%d]", j), p$rotation[, j])),
                    collapse = ",\n       "))
w("FROM (SELECT pca_agg([murder, assault, urbanpop, rape]) AS m FROM usarrests);")
w("----")
w("true\ttrue\ttrue\ttrue")
w("")
w("# Sign-invariant check of the loadings (independent of the sign convention).")
w("query I")
ref_abs <- abs(p$rotation)
w("SELECT ", paste(sapply(1:4, function(j) close_list(sprintf("list_transform(m.loadings[%d], lambda _v: abs(_v))", j), ref_abs[, j])),
                    collapse = "\n   AND "))
w("FROM (SELECT pca_agg([murder, assault, urbanpop, rape]) AS m FROM usarrests);")
w("----")
w("true")
w("")

# Truncated to two components (prcomp(rank. = 2)): proportions stay shares of the total.
p2 <- flip(prcomp(X, center = TRUE, scale. = FALSE, rank. = 2))
w("# n_components = 2 (prcomp(rank. = 2)); proportions remain shares of the total variance.")
w("query IIIII")
w("SELECT ", close_list("m.sdev", p2$sdev[1:2]), ",")
w("       ", close_list("m.proportion_of_variance", prop[1:2]), ",")
w("       ", close_list("m.loadings[2]", p2$rotation[, 2]), ",")
w("       len(m.loadings), m.n_components")
w("FROM (SELECT pca_agg([murder, assault, urbanpop, rape], {'n_components': 2}) AS m FROM usarrests);")
w("----")
w("true\ttrue\ttrue\t2\t2")
w("")

# Scores of the fitted rows and of new rows (predict.prcomp).
newx <- rbind(c(10, 200, 60, 20), c(2.5, 90, 80, 12.25)); colnames(newx) <- colnames(X)
newsc <- predict(p, newdata = newx)
w("# pca_transform: scores of fitted rows (prcomp()$x) and new rows (predict.prcomp).")
w("query III")
w("SELECT ", close_list("pca_transform(m, [13.2, 236, 58, 21.2])", p$x[1, ]), ",")
w("       ", close_list("pca_transform(m, [10, 200, 60, 20])", newsc[1, ]), ",")
w("       ", close_list("pca_transform(m, [2.5, 90, 80, 12.25])", newsc[2, ]))
w("FROM (SELECT pca_agg([murder, assault, urbanpop, rape]) AS m FROM usarrests);")
w("----")
w("true\ttrue\ttrue")
w("")
w("# Two-component model: two scores.")
w("query I")
w("SELECT ", close_list("pca_transform(m, [10, 200, 60, 20])", newsc[1, 1:2]))
w("FROM (SELECT pca_agg([murder, assault, urbanpop, rape], {'n_components': 2}) AS m FROM usarrests);")
w("----")
w("true")
w("")

# pca_by: every row's scores, grouped.
w("# pca_by: every source row with its scores; all 50 rows of one group match prcomp()$x.")
w("statement ok")
w("CREATE TABLE usarrests_sc AS SELECT * FROM (VALUES")
w(paste(sprintf("    (%d, %s)", seq_len(nrow(X)), apply(p$x, 1, lst)), collapse = ",\n"))
w(") t(id, ref);")
w("")
w("statement ok")
w("CREATE VIEW usarrests_g AS SELECT 'US' AS region, * FROM usarrests;")
w("")
w("query II")
w("SELECT count(*), bool_and(list_max(list_transform(range(1, 5), lambda _i: abs(b.scores[_i] - s.ref[_i]) / (1 + abs(s.ref[_i])))) < 1e-9)")
w("FROM pca_by('usarrests_g', region, [murder, assault, urbanpop, rape]) b JOIN usarrests_sc s USING (id);")
w("----")
w("50\ttrue")
w("")

# --- wide: n = 4 rows, d = 6 variables (Gram-matrix path) -------------------
W <- rbind(c(1.0, 2.0, 0.5, 3.0, -1.0, 0.25),
           c(2.0, 0.5, 1.5, 2.5,  0.0, 1.00),
           c(0.5, 1.5, 2.5, 1.0,  1.0, 0.50),
           c(3.0, 1.0, 0.0, 0.5,  2.0, 1.75))
pw <- flip(prcomp(W, center = TRUE, scale. = FALSE))
kw <- nrow(W) - 1
propw <- pw$sdev^2 / sum(pw$sdev^2)
w("# Wide data (n = 4 < d = 6): min(n - 1, d) = 3 components; prcomp's 4th has sdev 0.")
w("statement ok")
w("CREATE TABLE wide AS SELECT * FROM (VALUES")
w(paste(sprintf("    (%d, %s)", 1:4, apply(W, 1, lst)), collapse = ",\n"))
w(") t(id, x);")
w("")
w("query IIIIII")
w("SELECT ", close_list("m.sdev", pw$sdev[1:kw]), ",")
w("       ", close_list("m.proportion_of_variance", propw[1:kw]), ",")
w("       ", close_list("m.loadings[1]", pw$rotation[, 1]), ",")
w("       ", close_list("m.loadings[3]", pw$rotation[, 3]), ",")
w("       ", close_list("pca_transform(m, x0)", pw$x[2, 1:kw]), ",")
w("       m.n_components")
w("FROM (SELECT pca_agg(x) AS m, (SELECT x FROM wide WHERE id = 2) AS x0 FROM wide);")
w("----")
w("true\ttrue\ttrue\ttrue\ttrue\t3")
w("")

# --- scaled: prcomp(scale. = TRUE), pca_agg(..., {'scale': true}) ------------
ps <- flip(prcomp(X, center = TRUE, scale. = TRUE))
props <- ps$sdev^2 / sum(ps$sdev^2)
newss <- predict(ps, newdata = newx)
w("# Scaled PCA: prcomp(scale. = TRUE) (the correlation-matrix PCA); the model stores the")
w("# column sds (prcomp()$scale) and pca_transform divides by them (predict.prcomp).")
w("query IIIIIII")
w("SELECT ", close_list("m.sdev", ps$sdev), ",")
w("       ", close_list("m.proportion_of_variance", props), ",")
w("       ", close_list("m.loadings[1]", ps$rotation[, 1]), ",")
w("       ", close_list("m.loadings[4]", ps$rotation[, 4]), ",")
w("       ", close_list("m.center", ps$center), ",")
w("       ", close_list("m.scale", ps$scale), ",")
w("       ", close_list("pca_transform(m, [10, 200, 60, 20])", newss[1, ]))
w("FROM (SELECT pca_agg([murder, assault, urbanpop, rape], {'scale': true}) AS m FROM usarrests);")
w("----")
w("true\ttrue\ttrue\ttrue\ttrue\ttrue\ttrue")
w("")
ps2 <- flip(prcomp(X, center = TRUE, scale. = TRUE, rank. = 2))
w("# Scaled, two components: scores of a fitted row (prcomp()$x) and of a new row.")
w("query II")
w("SELECT ", close_list("pca_transform(m, [13.2, 236, 58, 21.2])", ps2$x[1, ]), ",")
w("       ", close_list("pca_transform(m, [2.5, 90, 80, 12.25])", newss[2, 1:2]))
w("FROM (SELECT pca_agg([murder, assault, urbanpop, rape], {'scale': true, 'n_components': 2}) AS m FROM usarrests);")
w("----")
w("true\ttrue")
w("")
pws <- flip(prcomp(W, center = TRUE, scale. = TRUE))
w("# Scaled wide data (n = 4 < d = 6).")
w("query IIII")
w("SELECT ", close_list("m.sdev", pws$sdev[1:kw]), ",")
w("       ", close_list("m.loadings[2]", pws$rotation[, 2]), ",")
w("       ", close_list("m.scale", pws$scale), ",")
w("       ", close_list("pca_transform(m, x0)", pws$x[2, 1:kw]))
w("FROM (SELECT pca_agg(x, {'scale': true}) AS m, (SELECT x FROM wide WHERE id = 2) AS x0 FROM wide);")
w("----")
w("true\ttrue\ttrue\ttrue")
w("")
w("# A constant column cannot be scaled (prcomp: 'cannot rescale a constant/zero column').")
w("statement error")
w("SELECT pca_agg([murder, 1.0], {'scale': true}) FROM usarrests;")
w("----")
w("")

writeLines(L, out)
cat("wrote", out, "\n")
