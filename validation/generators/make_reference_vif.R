#!/usr/bin/env Rscript
# =============================================================================
# make_reference_vif.R
#
# Generates test/sql/reference/vif_reference.test (#307):
#
#   vif, vif_agg, gvif_agg   <- car::vif(lm(...))
#
#   Rscript validation/generators/make_reference_vif.R      # from repo root
#
# Requires: car. The dataset is a literal deterministic formula (no RNG): two
# correlated numeric predictors, a 3-level factor (region) and a 4-level factor
# (edu) whose levels depend on region, so the factor terms have df > 1 and a
# GVIF that differs from the per-column VIF. The design is coded with
# treatment-contrast dummies as R's model.matrix does.
# =============================================================================
suppressPackageStartupMessages(library(car))

out_dir <- "test/sql/reference"

num <- function(v) sprintf("%.17g", v)
checks <- function(comment, from, exprs, refs, tol) {
  stopifnot(length(exprs) == length(refs))
  out <- character()
  idx <- seq_along(exprs)
  for (chunk in split(idx, ceiling(idx / 6))) {
    cols <- vapply(chunk, function(i) {
      sprintf("abs((%s) - (%s)) <= %g * (1 + abs(%s))", exprs[i], num(refs[i]), tol, num(refs[i]))
    }, "")
    out <- c(out,
      paste0("# ", comment),
      paste0("query ", strrep("I", length(chunk))),
      paste0("SELECT\n    ", paste(cols, collapse = ",\n    ")),
      paste0("FROM ", from, ";"),
      "----",
      paste(rep("true", length(chunk)), collapse = "\t"),
      "")
  }
  out
}

i <- 0:39
age <- 20 + (i * 7) %% 41 + 0.25 * sin(i)
income <- round(1.5 * age + 10 * cos(i / 2) + (i %% 3), 4)
region <- factor(c("a", "b", "c")[(i %% 3) + 1])
edu <- factor(c("e1", "e2", "e3", "e4")[((i %/% 2) + (i %% 3)) %% 4 + 1])
y <- round(1 + 0.1 * age + 0.05 * income + as.integer(region) + 0.5 * as.integer(edu) + cos(i), 4)
mm <- model.matrix(~ age + income + region + edu)
d <- data.frame(id = i, age = age, income = income, rb = mm[, "regionb"], rc = mm[, "regionc"],
                e2 = mm[, "edue2"], e3 = mm[, "edue3"], e4 = mm[, "edue4"], y = y)

fit_num <- lm(y ~ age + income + rb + rc + e2 + e3 + e4, data = d)
v_num <- vif(fit_num)                              # every dummy as its own column
fit_fac <- lm(y ~ age + income + region + edu)
v_fac <- vif(fit_fac)                              # GVIF, Df, GVIF^(1/(2*Df))
fit_3 <- lm(y ~ age + income + rb, data = d)
v_3 <- vif(fit_3)

# Near-collinear: VIF > 1e4 (R^2 > 0.9999), finite in car::vif. Before #307
# the extension reported inf from R^2 >= 0.9999.
h1 <- 1:12
h2 <- round(h1 + 0.002 * sin(3 * h1), 6)
h3 <- round(cos(h1), 6)
v_hi <- vif(lm(sin(2 * h1) ~ h1 + h2 + h3))
vec <- function(v) paste0("[", paste(num(v), collapse = ", "), "]")

rows <- apply(d, 1, function(r) sprintf("(%d, %s)", as.integer(r[["id"]]),
                                        paste(num(r[-1]), collapse = ", ")))

out <- c(
  "# name: test/sql/reference/vif_reference.test",
  "# description: #307 vif, vif_agg and gvif_agg against car::vif",
  "# group: [reference]",
  "#",
  "# GENERATED by validation/generators/make_reference_vif.R -- do not edit",
  "# by hand; change the generator and re-run it instead.",
  sprintf("# Reference: %s, car %s", R.version.string, packageVersion("car")),
  "",
  "require anofox_statistics",
  "",
  "statement ok",
  "CREATE TABLE vd (id INTEGER, age DOUBLE, income DOUBLE, rb DOUBLE, rc DOUBLE, e2 DOUBLE, e3 DOUBLE, e4 DOUBLE, y DOUBLE);",
  "",
  "statement ok",
  paste0("INSERT INTO vd VALUES\n", paste(rows, collapse = ",\n"), ";"),
  "",
  "# vif_agg: one VIF per column, car::vif(lm(y ~ age + income + rb + rc + e2 + e3 + e4))",
  "statement ok",
  "CREATE TABLE v_agg AS SELECT vif_agg([age, income, rb, rc, e2, e3, e4]) AS v FROM vd;",
  "",
  checks("vif_agg vs car::vif (numeric columns)", "v_agg",
         sprintf("v[%d]", seq_along(v_num)), unname(v_num), 1e-8),
  "# vif (scalar) on the same feature-major matrix",
  "statement ok",
  paste0("CREATE TABLE v_sc AS SELECT vif([list(age ORDER BY id), list(income ORDER BY id), list(rb ORDER BY id), ",
         "list(rc ORDER BY id), list(e2 ORDER BY id), list(e3 ORDER BY id), list(e4 ORDER BY id)]) AS v FROM vd;"),
  "",
  checks("vif vs car::vif (numeric columns)", "v_sc",
         sprintf("v[%d]", seq_along(v_num)), unname(v_num), 1e-8),
  "# gvif_agg without terms: every column its own term, gvif = VIF, gvif_adj = sqrt(VIF)",
  "statement ok",
  "CREATE TABLE g_num AS SELECT gvif_agg([age, income, rb, rc, e2, e3, e4]) AS g FROM vd;",
  "",
  checks("gvif_agg (default terms) vs car::vif", "g_num",
         c(sprintf("g[%d].gvif", seq_along(v_num)), sprintf("g[%d].gvif_adj", seq_along(v_num))),
         c(unname(v_num), sqrt(unname(v_num))), 1e-8),
  "query TIII",
  "SELECT g[1].term, g[7].term, g[1].df, g[7].n_observations FROM g_num;",
  "----",
  "x1\tx7\t1\t40",
  "",
  "# gvif_agg with factor terms: car::vif(lm(y ~ age + income + region + edu))",
  "statement ok",
  paste0("CREATE TABLE g_fac AS SELECT gvif_agg([age, income, rb, rc, e2, e3, e4], ",
         "{'terms': ['age', 'income', 'region', 'region', 'edu', 'edu', 'edu']}) AS g FROM vd;"),
  "",
  "query TTTTIIII",
  "SELECT g[1].term, g[2].term, g[3].term, g[4].term, g[1].df, g[2].df, g[3].df, g[4].df FROM g_fac;",
  "----",
  sprintf("age\tincome\tregion\tedu\t%s", paste(v_fac[, "Df"], collapse = "\t")),
  "",
  checks("gvif_agg (factor terms) GVIF vs car::vif", "g_fac",
         sprintf("g[%d].gvif", 1:4), unname(v_fac[, "GVIF"]), 1e-8),
  checks("gvif_agg (factor terms) GVIF^(1/(2 Df)) vs car::vif", "g_fac",
         sprintf("g[%d].gvif_adj", 1:4), unname(v_fac[, "GVIF^(1/(2*Df))"]), 1e-8),
  "# Columns of a term need not be adjacent; integer labels work too (terms in first-appearance order)",
  "statement ok",
  paste0("CREATE TABLE g_mix AS SELECT gvif_agg([rb, age, e2, rc, income, e3, e4], ",
         "{'terms': [3, 1, 4, 3, 2, 4, 4]}) AS g FROM vd;"),
  "",
  "query TTTT",
  "SELECT g[1].term, g[2].term, g[3].term, g[4].term FROM g_mix;",
  "----",
  "3\t1\t4\t2",
  "",
  checks("gvif_agg (non-adjacent integer terms) vs car::vif", "g_mix",
         sprintf("g[%d].gvif", 1:4), unname(v_fac[c(3, 1, 4, 2), "GVIF"]), 1e-8),
  "# A smaller model: car::vif(lm(y ~ age + income + rb))",
  checks("vif_agg vs car::vif (3 columns)", "vd",
         sprintf("(vif_agg([age, income, rb]))[%d]", 1:3), unname(v_3), 1e-8),
  "# Near-collinear features: car::vif reports a large finite VIF (> 1e4)",
  checks("vif vs car::vif (near-collinear)",
         sprintf("(SELECT vif([%s, %s, %s]) AS v)", vec(h1), vec(h2), vec(h3)),
         sprintf("v[%d]", 1:3), unname(v_hi), 1e-6)
)

writeLines(out, file.path(out_dir, "vif_reference.test"))
cat("wrote", file.path(out_dir, "vif_reference.test"), "\n")
print(v_num); print(v_fac); print(v_3); print(v_hi)
