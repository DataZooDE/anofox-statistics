#!/usr/bin/env Rscript
# =============================================================================
# make_reference_option_passthroughs.R
#
# Generates test/sql/reference/option_passthroughs_r.test (issue #305): the
# option pass-throughs checked against R
#   poisson_fit_agg(y, x, w) / gamma_fit_agg / tweedie_fit_agg   glm(weights = w)
#                                   (Tweedie: statmod::tweedie(var.power, link.power = 0))
#   glmm_fit_agg {'n_agq': k}       lme4::glmer(nAGQ = k)
#   ridge_fit_agg {'conditioning'}  closed-form ridge with lambda_small when
#                                   kappa(X'X) <= cond_threshold (X centred), else alpha
#
#   Rscript validation/generators/make_reference_option_passthroughs.R   # from repo root
#
# Requires: statmod, lme4, tweedie (rtweedie, data only). The GLMM data is the d4 panel of
# test/sql/reference/glm_glmm.test (read from that file, so both stay in sync).
# The quantile L1 alpha and Huber joint scale are checked against scikit-learn by
# make_reference_option_passthroughs.py.
# =============================================================================
suppressPackageStartupMessages({
  library(statmod); library(lme4)
})

out_dir <- "test/sql/reference"
num <- function(v) ifelse(is.na(v), "NULL", sprintf("%.17g", v))
checks <- function(comment, from, exprs, refs, tol) {
  stopifnot(length(exprs) == length(refs))
  out <- character()
  idx <- seq_along(exprs)
  for (chunk in split(idx, ceiling(idx / 6))) {
    cols <- vapply(chunk, function(i)
      sprintf("abs((%s) - (%s)) <= %g * (1 + abs(%s))", exprs[i], num(refs[i]), tol, num(refs[i])), "")
    out <- c(out, paste0("# ", comment), paste0("query ", strrep("I", length(chunk))),
             paste0("SELECT\n    ", paste(cols, collapse = ",\n    ")), paste0("FROM ", from, ";"), "----",
             paste(rep("true", length(chunk)), collapse = "\t"), "")
  }
  out
}
lst <- function(field, idx) sprintf("r.%s[%d]", field, idx)

L <- c(
  "# name: test/sql/reference/option_passthroughs_r.test",
  "# description: option pass-throughs (#305): GLM prior weights vs glm(weights =), GLMM n_agq vs glmer(nAGQ =), ridge conditioning-aware lambda vs closed-form ridge",
  "# group: [reference]",
  "#",
  "# GENERATED by validation/generators/make_reference_option_passthroughs.R -- do not edit",
  "# by hand; change the generator and re-run it instead.",
  sprintf("# Reference: %s; statmod %s, lme4 %s", R.version.string, packageVersion("statmod"),
          packageVersion("lme4")),
  "",
  "require anofox_statistics",
  "")

# =============================================================================
# 1. GLM prior weights
# =============================================================================
set.seed(305)
n <- 36
z1 <- round(rnorm(n), 2)
z2 <- round(runif(n, -1, 1), 2)
w <- round(runif(n, 0.2, 3), 1)
expo <- round(runif(n, 0.5, 2), 2)
cnt <- rpois(n, exp(0.4 + 0.5 * z1 - 0.3 * z2) * expo)
gam <- round(rgamma(n, shape = 3, rate = 3 / exp(1 + 0.4 * z1 + 0.2 * z2)), 3)
tw <- round(tweedie::rtweedie(n, mu = exp(0.3 + 0.5 * z1), phi = 1.2, power = 1.5), 3)
lexpo <- log(expo)
L <- c(L, "statement ok",
  "CREATE TABLE gw (id INTEGER, cnt DOUBLE, gam DOUBLE, tw DOUBLE, z1 DOUBLE, z2 DOUBLE, w DOUBLE, lexpo DOUBLE);",
  "", "statement ok", "INSERT INTO gw VALUES",
  paste0(paste(sprintf("(%d, %s, %s, %s, %s, %s, %s, %s)", seq_len(n), num(cnt), num(gam), num(tw), num(z1),
                       num(z2), num(w), num(lexpo)), collapse = ",\n"), ";"), "")

ctl <- glm.control(epsilon = 1e-14, maxit = 100)
glm_block <- function(title, fit, call, pz, extra = NULL) {
  cc <- coef(summary(fit))
  disp <- if (is.null(extra$disp)) summary(fit)$dispersion else extra$disp
  aic <- if (is.null(extra$aic)) fit$aic else extra$aic
  src <- sprintf("(SELECT %s AS r FROM gw) s", call)
  c(checks(paste(title, "coefficients, deviance, null deviance, pseudo R^2, AIC, dispersion"), src,
      c("r.intercept", lst("coefficients", 1:2), "r.deviance", "r.null_deviance", "r.pseudo_r_squared",
        if (!is.na(aic)) "r.aic", "r.dispersion"),
      c(coef(fit), fit$deviance, fit$null.deviance, 1 - fit$deviance / fit$null.deviance,
        if (!is.na(aic)) aic, disp), 1e-6),
    checks(paste(title, "standard errors and", pz, "p-values (summary.glm)"), src,
      c("r.intercept_std_error", lst("std_errors", 1:2), "r.intercept_p_value", lst("p_values", 1:2)),
      c(cc[, 2], cc[, 4]), 1e-6))
}

fp <- glm(cnt ~ z1 + z2, family = poisson, weights = w, control = ctl)
fpo <- glm(cnt ~ z1 + z2 + offset(lexpo), family = poisson, weights = w, control = ctl)
fg <- glm(gam ~ z1 + z2, family = Gamma(link = "log"), weights = w, control = ctl)
ft <- glm(tw ~ z1 + z2, family = tweedie(var.power = 1.5, link.power = 0), weights = w, control = ctl)
L <- c(L,
  "# ---- Poisson with prior weights ----",
  "# poisson_fit_agg(y, x, w) is glm(y ~ x, family = poisson, weights = w): IRLS",
  "# weights, deviance, log-likelihood and Pearson terms multiplied by w.",
  glm_block("glm(cnt ~ z1 + z2, poisson, weights = w):", fp,
    "poisson_fit_agg(cnt, [z1, z2], w, {'compute_inference': true, 'tolerance': 1e-12})", "z"),
  checks("glm(cnt ~ z1 + z2 + offset(log(expo)), poisson, weights = w): coefficients, deviance, AIC",
    "(SELECT poisson_fit_agg(cnt, [z1, z2, lexpo], w, {'offset': 3, 'tolerance': 1e-12}) AS r FROM gw) s",
    c("r.intercept", lst("coefficients", 1:2), "r.deviance", "r.null_deviance", "r.aic"),
    c(coef(fpo), fpo$deviance, fpo$null.deviance, fpo$aic), 1e-6),
  "# ---- Gamma (log link) with prior weights ----",
  "# Dispersion = sum(w (y - mu)^2 / mu^2) / df (summary.glm); AIC is R's",
  "# Gamma()$aic with weights (dispersion = deviance / sum(w)). The weighted fit's",
  "# tests use t(df.residual) as summary.glm, the unweighted gamma_fit_agg uses z.",
  glm_block("glm(gam ~ z1 + z2, Gamma('log'), weights = w):", fg,
    "gamma_fit_agg(gam, [z1, z2], w, {'compute_inference': true, 'tolerance': 1e-12})", "t"),
  "# ---- Tweedie (power 1.5, log link) with prior weights ----",
  "# statmod::tweedie has no closed-form density for 1 < p < 2, so R's AIC is NA and",
  "# the weighted fit reports NULL log-likelihood / AIC / BIC (checked below).",
  glm_block("glm(tw ~ z1 + z2, tweedie(1.5, link.power = 0), weights = w):", ft,
    "tweedie_fit_agg(tw, [z1, z2], w, {'power': 1.5, 'compute_inference': true, 'tolerance': 1e-12})", "t"),
  "query I",
  "SELECT tweedie_fit_agg(tw, [z1, z2], w, {'power': 1.5}).aic IS NULL FROM gw;",
  "----", "true", "")

# Integer weights are frequency weights: the fit equals the fit on replicated rows.
L <- c(L,
  "# Integer weights equal replicated rows (the unweighted fit on the expanded data).",
  "query III",
  "WITH k AS (SELECT *, 1 + id % 3 AS f FROM gw),",
  "     rep AS (SELECT k.* FROM k, range(3) r(i) WHERE r.i < k.f),",
  "     a AS (SELECT poisson_fit_agg(cnt, [z1, z2], f, {'tolerance': 1e-12}) AS m FROM k),",
  "     b AS (SELECT poisson_fit_agg(cnt, [z1, z2], {'tolerance': 1e-12}) AS m FROM rep)",
  "SELECT abs(a.m.coefficients[1] - b.m.coefficients[1]) < 1e-9,",
  "       abs(a.m.intercept - b.m.intercept) < 1e-9,",
  "       abs(a.m.deviance - b.m.deviance) < 1e-8",
  "FROM a, b;",
  "----", "true\ttrue\ttrue", "")

# =============================================================================
# 2. GLMM n_agq
# =============================================================================
src <- readLines(file.path(out_dir, "glm_glmm.test"))
start <- grep("^CREATE TABLE d4", src)
ins <- grep("^INSERT INTO d4 VALUES", src)
end <- ins + which(grepl(";$", src[(ins + 1):length(src)]))[1]
L <- c(L, "statement ok", src[start], "", "statement ok", src[ins:end], "")
rows <- gsub("[();]", "", sub(",$", "", src[(ins + 1):end]))
d4 <- read.csv(text = rows, header = FALSE, quote = "'", strip.white = TRUE,
               col.names = c("g", "q1", "ly", "pc", "bb", "h", "nc", "lc"))
d4$g <- factor(d4$g)
stopifnot(nrow(d4) == 48)

opt <- list(xtol_abs = 1e-12, ftol_abs = 1e-14, xtol_rel = 1e-12, ftol_rel = 1e-14, maxeval = 1e5)
# calc.derivs = TRUE: for nAGQ >= 1 lme4's standard errors come from the
# finite-difference Hessian of the deviance in (theta, beta), as upstream's.
gctl <- glmerControl(optimizer = "nloptwrap", calc.derivs = TRUE, tolPwrss = 1e-12, optCtrl = opt)
L <- c(L,
  "# ---- GLMM integration: n_agq ----",
  "# {'n_agq': 1} is glmer's default Laplace fit (fixed effects optimised jointly",
  "# with theta); {'n_agq': k > 1} adaptive Gauss-Hermite quadrature with k nodes.",
  "# Standard errors from the Hessian of the deviance in (theta, beta), as lme4's",
  "# vcov with calc.derivs = TRUE. For n_agq > 1 lme4's Poisson logLik omits the",
  "# saturated-model term sum(log dpois(y, y)); the reference adds it back.",
  "# The default (n_agq = 0, glmer(nAGQ = 0)) is checked in glm_glmm.test.",
  "")
for (fam in c("poisson", "binomial")) {
  yv <- if (fam == "poisson") "pc" else "bb"
  for (k in c(1L, 5L)) {
    fm <- glmer(as.formula(sprintf("%s ~ q1 + (1 | g)", yv)), data = d4, family = fam, nAGQ = k, control = gctl)
    cc <- coef(summary(fm)); vg <- as.data.frame(VarCorr(fm))$vcov
    ll <- as.numeric(logLik(fm))
    # lme4's nAGQ > 1 deviance leaves out the saturated-model term
    # sum(log f(y | mu = y)) that its nAGQ <= 1 logLik includes (non-zero for
    # Poisson counts, zero for 0/1 outcomes); the extension reports the full
    # log-likelihood for every n_agq, so add the term back.
    if (k > 1 && fam == "poisson") ll <- ll + sum(dpois(d4$pc, d4$pc, log = TRUE))
    from <- sprintf("(SELECT glmm_fit_agg(%s, [q1], g, {'family': '%s', 'n_agq': %d, 'compute_inference': true}) AS r FROM d4) s",
                    yv, fam, k)
    L <- c(L, checks(sprintf("%s: glmer(%s ~ q1 + (1|g), nAGQ = %d): fixef, SEs, var_group, logLik", fam, yv, k), from,
      c("r.intercept", "r.coefficients[1]", "r.intercept_std_error", "r.std_errors[1]", "r.var_group",
        "r.log_likelihood"),
      c(cc[, 1], cc[, 2], vg, ll), 1e-4))
  }
}

# =============================================================================
# 3. Ridge conditioning-aware lambda
# =============================================================================
set.seed(3051)
m <- 30
a1 <- round(rnorm(m), 3)
a2 <- round(rnorm(m), 3)
a3 <- round(a1 + rnorm(m, sd = 0.01), 3) # nearly collinear with a1
ry <- round(1 + 2 * a1 - a2 + rnorm(m, sd = 0.5), 3)
L <- c(L, "statement ok", "CREATE TABLE rd (ry DOUBLE, a1 DOUBLE, a2 DOUBLE, a3 DOUBLE);", "",
  "statement ok", "INSERT INTO rd VALUES",
  paste0(paste(sprintf("(%s, %s, %s, %s)", num(ry), num(a1), num(a2), num(a3)), collapse = ",\n"), ";"), "")
ridge <- function(X, y, lambda) {
  Xc <- scale(X, scale = FALSE); yc <- y - mean(y)
  b <- solve(crossprod(Xc) + lambda * diag(ncol(X)), crossprod(Xc, yc))
  c(mean(y) - sum(colMeans(X) * b), b)
}
kap <- function(X) { s <- svd(scale(X, scale = FALSE))$d; (max(s) / min(s))^2 }
Xw <- cbind(a1, a2); Xi <- cbind(a1, a2, a3)
kw <- kap(Xw); ki <- kap(Xi)
stopifnot(kw <= 1000, ki > 1000)
L <- c(L,
  "# ---- Ridge conditioning-aware lambda ----",
  sprintf("# kappa(X'X) of the centred design: %.6g for [a1, a2] (well conditioned) and", kw),
  sprintf("# %.6g for [a1, a2, a3] (a3 ~ a1). With 'conditioning' the fit uses lambda_small", ki),
  "# (default 0.1, threshold 1000) on the first and alpha on the second.",
  checks("ridge_fit_agg {'alpha': 5, 'conditioning': true} on a well-conditioned design = ridge(lambda = 0.1)",
    "(SELECT ridge_fit_agg(ry, [a1, a2], {'alpha': 5, 'conditioning': true}) AS r FROM rd) s",
    c("r.intercept", lst("coefficients", 1:2)), ridge(Xw, ry, 0.1), 1e-8),
  checks("ridge_fit_agg {'alpha': 5, 'conditioning': true} on an ill-conditioned design = ridge(lambda = 5)",
    "(SELECT ridge_fit_agg(ry, [a1, a2, a3], {'alpha': 5, 'conditioning': true}) AS r FROM rd) s",
    c("r.intercept", lst("coefficients", 1:3)), ridge(Xi, ry, 5), 1e-8),
  checks("ridge_fit_agg {'alpha': 5, 'lambda_small': 0.5, 'cond_threshold': 1e7}: both designs below the threshold",
    "(SELECT ridge_fit_agg(ry, [a1, a2, a3], {'alpha': 5, 'lambda_small': 0.5, 'cond_threshold': 1e7}) AS r FROM rd) s",
    c("r.intercept", lst("coefficients", 1:3)), ridge(Xi, ry, 0.5), 1e-8),
  checks("ridge_fit_agg without conditioning keeps alpha on the well-conditioned design",
    "(SELECT ridge_fit_agg(ry, [a1, a2], {'alpha': 5}) AS r FROM rd) s",
    c("r.intercept", lst("coefficients", 1:2)), ridge(Xw, ry, 5), 1e-8))

writeLines(L, file.path(out_dir, "option_passthroughs_r.test"))
cat("wrote", file.path(out_dir, "option_passthroughs_r.test"), "\n")
