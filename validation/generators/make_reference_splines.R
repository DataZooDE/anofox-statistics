# R reference values for test/sql/reference/splines_reference.test (#317):
#
#  * rcs_knots_agg(x, nk [, {'fractied': f}]) = Hmisc::rcspline.eval(x, nk = nk, knots.only = TRUE, fractied = f)
#    (the default knots of rms::rcs)
#  * rcs(x, knots, {'norm': m})             = Hmisc::rcspline.eval(x, knots, inclx = TRUE, norm = m)
#  * lsp(x, knots)                          = rms::lsp(x, knots)
#  * restricted_interaction(rcs(a), rcs(b)) = rms::rcs(a, ka) %ia% rms::rcs(b, kb)
#  * bspline(x, knots, degree)              = splines::splineDesign on the knot vector of sklearn's
#    SplineTransformer (the base knots plus `degree` knots on each side at the outermost spacing),
#    inside the base knots
#  * bspline_knots_agg(x, n)                = seq(min, max, length = n) / quantile(x, type = 7)
#  * default_knot_quantiles(nk)             = seq(outer, 1 - outer, length = nk), RMS Table 2.3
#
# Usage (from the repository root):
#   Rscript validation/generators/make_reference_splines.R
# writes test/sql/reference/splines_reference.test.
suppressMessages({
  library(Hmisc)
  library(rms)
  library(splines)
})

out_file <- file.path("test", "sql", "reference", "splines_reference.test")
fmt <- function(x) ifelse(is.na(x), "NULL", sprintf("%.17g", x))
lst <- function(x) paste0("[", paste(fmt(x), collapse = ", "), "]")
L <- character()
emit <- function(...) L <<- c(L, paste0(...))

# Datasets (rounded so the SQL literals are exact).
set.seed(317)
dsA <- round(20 + 60 * rbeta(150, 2, 3), 2)                     # n = 150, continuous
dsB <- round(rnorm(40, 50, 10), 2)                              # n = 40 < 100: outer knots moved
dsC <- c(rep(0, 45), round(rexp(105, 0.2), 2))                  # 30% ties at the minimum
dsD <- rep(c(1, 2, 3, 4, 5, 6, 7), c(5, 9, 12, 8, 6, 4, 2))     # 7 distinct values
dsE <- c(round(runif(60, 0, 10), 2), rep(10, 20))               # ties at the maximum

table_sql <- function(name, x) {
  emit("statement ok")
  emit("CREATE TABLE ", name, " AS SELECT unnest(", lst(x), "::DOUBLE[]) AS x;")
  emit("")
}

emit("# name: test/sql/reference/splines_reference.test")
emit("# description: #317 spline bases and default knots vs R (Hmisc, rms, splines)")
emit("# group: [reference]")
emit("#")
emit("# Generated by validation/generators/make_reference_splines.R (Hmisc ",
     as.character(packageVersion("Hmisc")), ", rms ", as.character(packageVersion("rms")), ", R ",
     paste(R.version$major, R.version$minor, sep = "."), "). Do not edit by hand.")
emit("#  * rcs_knots_agg = Hmisc::rcspline.eval(x, nk, knots.only = TRUE, fractied) (rms::rcs default knots)")
emit("#  * rcs = rcspline.eval(x, knots, inclx = TRUE, norm); lsp = rms::lsp; restricted_interaction = rms %ia%")
emit("#  * bspline = splines::splineDesign on sklearn's extended knot vector (inside the base knots)")
emit("#  * bspline_knots_agg = seq(min, max, length = n) / quantile(type = 7); default_knot_quantiles = RMS Table 2.3")
emit("")
emit("require anofox_statistics")
emit("")
emit("statement ok")
emit("CREATE MACRO max_abs_diff(a, b) AS CASE WHEN len(a) = len(b) THEN coalesce(list_max(list_transform(",
     "range(1, len(a) + 1), lambda i: abs(a[i] - b[i]))), 0) ELSE 1e300 END;")
emit("")
for (nm in c("dsA", "dsB", "dsC", "dsD", "dsE")) table_sql(nm, get(nm))

# ---- default knots -----------------------------------------------------------
emit("# ---- rcs_knots_agg = rcspline.eval(x, nk, knots.only = TRUE) ----")
emit("")
knot_case <- function(ds, nk, fractied = NULL) {
  x <- get(ds)
  k <- if (is.null(fractied)) rcspline.eval(x, nk = nk, knots.only = TRUE)
       else rcspline.eval(x, nk = nk, knots.only = TRUE, fractied = fractied)
  call <- if (is.null(fractied)) sprintf("rcs_knots_agg(x, %d)", nk)
          else sprintf("rcs_knots_agg(x, %d, {'fractied': %s})", nk, fmt(fractied))
  emit("# ", ds, ": rcspline.eval(x, nk = ", nk, if (!is.null(fractied)) paste0(", fractied = ", fractied), ") = ", lst(k))
  emit("query I")
  emit("SELECT max_abs_diff(", call, ", ", lst(k), ") < 1e-12 FROM ", ds, ";")
  emit("----")
  emit("true")
  emit("")
}
for (nk in 3:7) knot_case("dsA", nk)
for (nk in 3:5) knot_case("dsB", nk)
for (nk in 3:5) knot_case("dsC", nk)
knot_case("dsC", 4, fractied = 0.5)
knot_case("dsD", 5)
knot_case("dsD", 3)
knot_case("dsE", 4)

# rms::rcs(x, 5) uses the same knots
kA5 <- attr(rcs(dsA, 5), "parms")
stopifnot(isTRUE(all.equal(kA5, rcspline.eval(dsA, nk = 5, knots.only = TRUE))))
emit("# rms::rcs(x, 5) knots (the default nk = 5) = ", lst(kA5))
emit("query I")
emit("SELECT max_abs_diff(rcs_knots_agg(x), ", lst(kA5), ") < 1e-12 FROM dsA;")
emit("----")
emit("true")
emit("")

# ---- rcs basis -----------------------------------------------------------------
grid <- c(-5, 0, 20.5, 25, 31.7, 40, 44.44, 52, 60, 66.6, 75, 90)
kA4 <- rcspline.eval(dsA, nk = 4, knots.only = TRUE)
emit("# ---- rcs(x, knots) = rcspline.eval(x, knots, inclx = TRUE, norm) ----")
emit("")
for (norm in 0:2) for (knots in list(kA4, kA5)) {
  B <- rcspline.eval(grid, knots = knots, inclx = TRUE, norm = norm)
  rows <- sapply(seq_along(grid), function(i) sprintf("(%s, %s)", fmt(grid[i]), lst(B[i, ])))
  emit("# rcspline.eval(x, knots = ", lst(knots), ", inclx = TRUE, norm = ", norm, ")")
  emit("query I")
  emit("SELECT count(*) FROM (VALUES ", paste(rows, collapse = ", "), ") t(x, e)")
  emit("WHERE NOT max_abs_diff(rcs(x, ", lst(knots), ", {'norm': ", norm, "}), e) <= 1e-9 * greatest(1, list_max(list_transform(e, lambda v: abs(v))));")
  emit("----")
  emit("0")
  emit("")
}
# Default norm = 2 is rms::rcs
B <- unclass(rcs(grid, kA4))
rows <- sapply(seq_along(grid), function(i) sprintf("(%s, %s)", fmt(grid[i]), lst(B[i, ])))
emit("# rms::rcs(x, knots) (default norm 2)")
emit("query I")
emit("SELECT count(*) FROM (VALUES ", paste(rows, collapse = ", "), ") t(x, e)")
emit("WHERE NOT max_abs_diff(rcs(x, ", lst(kA4), "), e) <= 1e-9 * greatest(1, list_max(list_transform(e, lambda v: abs(v))));")
emit("----")
emit("0")
emit("")

