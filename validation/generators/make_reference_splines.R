# ---- B-splines ---------------------------------------------------------------------
emit("# ---- bspline(x, knots, degree) = splineDesign on the extended knot vector (inside the base knots) ----")
emit("")
extended <- function(t, k) {
  m <- length(t)
  c(t[1] - (k:1) * (t[2] - t[1]), t, t[m] + (1:k) * (t[m] - t[m - 1]))
}
bgrid <- c(0, 0.3, 1.25, 2.5, 3.99, 4, 5.5, 7.2, 8.8, 10)
for (case in list(list(t = c(0, 2.5, 5, 7.5, 10), k = 3), list(t = c(0, 1, 4, 6, 10), k = 2),
                  list(t = c(0, 3, 10), k = 1), list(t = c(0, 2, 5, 9, 10), k = 3))) {
  B <- splineDesign(extended(case$t, case$k), bgrid, ord = case$k + 1, outer.ok = TRUE)
  rows <- sapply(seq_along(bgrid), function(i) sprintf("(%s, %s)", fmt(bgrid[i]), lst(B[i, ])))
  emit("# splineDesign(knots = ", lst(extended(case$t, case$k)), ", ord = ", case$k + 1, ")")
  emit("query I")
  emit("SELECT count(*) FROM (VALUES ", paste(rows, collapse = ", "), ") t(x, e)")
  emit("WHERE NOT max_abs_diff(bspline(x, ", lst(case$t), ", ", case$k, "), e) <= 1e-12;")
  emit("----")
  emit("0")
  emit("")
}

emit("# ---- bspline_knots_agg = seq(min, max, length = n) / quantile(x, seq(0, 1, length = n), type = 7) ----")
emit("")
for (n in c(2, 5, 7)) {
  ku <- seq(min(dsA), max(dsA), length.out = n)
  kq <- unname(quantile(dsA, seq(0, 1, length.out = n), type = 7))
  emit("query II")
  emit("SELECT max_abs_diff(bspline_knots_agg(x, ", n, "), ", lst(ku), ") < 1e-12, ",
       "max_abs_diff(bspline_knots_agg(x, ", n, ", {'knots': 'quantile'}), ", lst(kq), ") < 1e-12 FROM dsA;")
  emit("----")
  emit("true\ttrue")
  emit("")
}

emit("# ---- default_knot_quantiles(nk): RMS Table 2.3 (rcspline.eval: seq(outer, 1 - outer, length = nk)) ----")
emit("")
for (nk in c(3, 4, 5, 6, 7, 10)) {
  outer <- if (nk > 6) 0.025 else if (nk > 3) 0.05 else 0.1
  q <- seq(outer, 1 - outer, length.out = nk)
  emit("query I")
  emit("SELECT max_abs_diff(default_knot_quantiles(", nk, "), ", lst(q), ") < 1e-15;")
  emit("----")
  emit("true")
  emit("")
}

