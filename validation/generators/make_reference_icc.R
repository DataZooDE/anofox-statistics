"# Checked per type: icc, F (= statistic), p_value, ci_lower, ci_upper, method.",
"# ICC2 and ICC2k have no interval (NULL): upstream (anofox-statistics 0.7.0,",
"# correlation::icc) computes it with the plain F = MS_R / MS_E interval of",
"# ICC3 / ICC3k instead of the approximate-F interval of Shrout & Fleiss (1979) /",
"# McGraw & Wong (1996) that psych uses; for sf it is [0.342, 0.946] around",
"# ICC2 = 0.290. The point estimates, F and p of ICC2 / ICC2k match psych.",
"",
"require anofox_statistics",
"",
"# Shrout & Fleiss (1979), Table 4: 6 subjects x 4 judges.",
"statement ok",
"CREATE TABLE sf AS",
"SELECT s::BIGINT AS subject, r::BIGINT AS rater, v::DOUBLE AS rating",
"FROM (VALUES (1, 1, 9), (1, 2, 2), (1, 3, 5), (1, 4, 8),",
"             (2, 1, 6), (2, 2, 1), (2, 3, 3), (2, 4, 2),",
"             (3, 1, 8), (3, 2, 4), (3, 3, 6), (3, 4, 8),",
"             (4, 1, 7), (4, 2, 1), (4, 3, 2), (4, 4, 6),",
