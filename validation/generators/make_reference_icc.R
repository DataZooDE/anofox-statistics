# Reference values for icc_agg, all six Shrout & Fleiss types (#298), held by
# test/sql/reference/icc_reference.test.
#
#   Rscript validation/generators/make_reference_icc.R
#
# Package: psych (psych::ICC). If psych lives in a user library:
#   R_LIBS_USER=~/R/userlib Rscript validation/generators/make_reference_icc.R
# The script also recomputes every ICC from the two-way ANOVA mean squares in
# base R (Shrout & Fleiss 1979, Table 2) and stops if the two disagree.
#
# Datasets:
#  * sf: the 6 subjects x 4 judges example of Shrout & Fleiss (1979), Table 4.
#  * sw: 12 subjects x 3 raters, v = s*0.2 + r*0.3 + sin(s*7 + r), s = 0..11,
#    r = 0..2 (a systematic rater effect, so ICC2 != ICC3). In SQL:
#      SELECT s*0.2 + rr*0.3 + sin(s*7 + rr), s, rr FROM range(12) a(s), range(3) b(rr)
.libPaths(c(path.expand("~/R/userlib"), .libPaths()))
suppressMessages(library(psych))

sf <- matrix(c(9, 2, 5, 8,
               6, 1, 3, 2,
               8, 4, 6, 8,
               7, 1, 2, 6,
               10, 5, 6, 9,
               6, 2, 4, 7), ncol = 4, byrow = TRUE)
sw <- outer(0:11, 0:2, function(s, r) s * 0.2 + r * 0.3 + sin(s * 7 + r))

# Base-R ICCs from the mean squares (the definitions upstream implements).
by_hand <- function(x) {
  n <- nrow(x); k <- ncol(x); gm <- mean(x)
  ssr <- k * sum((rowMeans(x) - gm)^2); ssc <- n * sum((colMeans(x) - gm)^2)
  sst <- sum((x - gm)^2); sse <- sst - ssr - ssc; ssw <- sst - ssr
  msr <- ssr / (n - 1); msc <- ssc / (k - 1)
  mse <- sse / ((n - 1) * (k - 1)); msw <- ssw / (n * (k - 1))
  c(ICC1 = (msr - msw) / (msr + (k - 1) * msw),
    ICC2 = (msr - mse) / (msr + (k - 1) * mse + k * (msc - mse) / n),
    ICC3 = (msr - mse) / (msr + (k - 1) * mse),
    ICC1k = (msr - msw) / msr,
    ICC2k = (msr - mse) / (msr + (msc - mse) / n),
    ICC3k = (msr - mse) / msr)
}

num <- function(v) sprintf("%.15g", v)
close <- function(expr, v) sprintf("abs(%s - (%s)) <= 1e-9 * (1 + abs(%s))", expr, num(v), num(v))

emit <- function(name, x, label) {
  r <- psych::ICC(x, lmer = FALSE)$results
  rownames(r) <- c("ICC1", "ICC2", "ICC3", "ICC1k", "ICC2k", "ICC3k")
  h <- by_hand(x)
  stopifnot(max(abs(h - r$ICC)) < 1e-12)
  out <- character()
  for (t in rownames(r)) {
    checks <- c(close("r.icc", r[t, "ICC"]), close("r.f_statistic", r[t, "F"]),
                close("r.statistic", r[t, "F"]), close("r.p_value", r[t, "p"]))
    # Upstream's ICC2 / ICC2k interval is not psych's: NULL (see the header).
    if (t %in% c("ICC2", "ICC2k")) {
      checks <- c(checks, "r.ci_lower IS NULL AND r.ci_upper IS NULL",
                  "r.conf_low IS NULL AND r.conf_high IS NULL")
    } else {
      checks <- c(checks, close("r.ci_lower", r[t, "lower bound"]),
                  close("r.ci_upper", r[t, "upper bound"]))
    }
    checks <- c(checks, sprintf("r.method = '%s'", t))
    out <- c(out,
             sprintf("# psych::ICC(%s)$results['%s', ]  (%s)", name, t, label),
             paste0("query ", strrep("I", length(checks))),
             paste0("SELECT ", paste(checks, collapse = ",\n       ")),
             sprintf("FROM (SELECT icc_agg(rating, subject, rater, {'type': '%s'}) AS r FROM %s);",
                     tolower(t), name),
             "----", paste(rep("true", length(checks)), collapse = "\t"), "")
  }
  out
}

