# --- pooling ----------------------------------------------------------------
completed <- lapply(seq_len(aw$n.impute), function(k) {
  dk <- d
  for (v in c("x1", "x2", "g")) {
    imp <- aw$imputed[[v]]
    rr <- as.integer(rownames(imp))
    if (is.factor(dk[[v]])) {
      dk[[v]] <- as.numeric(dk[[v]])
    }
    dk[[v]][rr] <- imp[, k]
  }
  dk
})

# The interval bounds use upstream's t quantile (statrs StudentsT::inverse_cdf),
# which is accurate to about 1e-8 relative at very large d.f. (Rubin's d.f. can
# exceed 1e5): the bounds are compared to 1e-7.
ci_tol <- "1e-7"

pool_block <- function(title, fits, sql_fit, options = NULL, dfcom = NULL, fit0 = NULL, tol = "1e-9") {
  ci <- if (tol == "1e-9") ci_tol else tol
  mira <- as.mira(fits)
  p <- if (is.null(dfcom)) pool(mira) else pool(mira, dfcom = dfcom)
  s <- summary(p, conf.int = TRUE)
  pp <- p$pooled
  # pooled covariance T = Ubar + (1 + 1/m) B (base R, Rubin's rules)
  m <- length(fits)
  Q <- sapply(fits, coef)
  U <- Reduce(`+`, lapply(fits, vcov)) / m
  B <- cov(t(Q))
  Tm <- U + (1 + 1 / m) * B
  call <- if (is.null(options)) "pool_rubin_agg(fit)" else sprintf("pool_rubin_agg(fit, %s)", options)
  w("# ", title)
  w("statement ok")
  w("CREATE OR REPLACE TABLE pooled AS SELECT ", call, " AS p FROM (", sql_fit, ");")
  w("")
  checks <- c(
    close_scalar("p.intercept", s$estimate[1], tol),
    close_list("p.coefficients", s$estimate[-1], tol),
    close_scalar("p.intercept_std_error", s$std.error[1], tol),
    close_list("p.std_errors", s$std.error[-1], tol),
    close_list("p.t_values", s$statistic[-1], tol),
    close_list("p.df", s$df[-1], tol),
    close_scalar("p.intercept_df", s$df[1], tol),
    close_list("p.p_values", s$p.value[-1], tol),
    close_scalar("p.intercept_p_value", s$p.value[1], tol),
    close_list("p.conf_low", s[["2.5 %"]][-1], ci),
    close_list("p.conf_high", s[["97.5 %"]][-1], ci),
    close_scalar("p.intercept_conf_low", s[["2.5 %"]][1], ci),
    close_list("p.riv", pp$riv[-1], tol),
    close_list("p.lambda", pp$lambda[-1], tol),
    close_list("p.fmi", pp$fmi[-1], tol),
    close_scalar("p.intercept_fmi", pp$fmi[1], tol),
    close_list("p.vcov", as.vector(t(Tm)), tol)
  )
  if (!is.null(fit0)) {
    d1 <- if (is.null(dfcom)) D1(mira, as.mira(fit0)) else D1(mira, as.mira(fit0), dfcom = dfcom)
    r <- d1$result
    checks <- c(checks,
                close_scalar("p.f_statistic", r[1, "F.value"]),
                close_scalar("p.f_df1", r[1, "df1"]),
                close_scalar("p.f_df2", r[1, "df2"]),
                close_scalar("p.f_pvalue", r[1, "P(>F)"]),
                close_scalar("p.f_riv", r[1, "RIV"]))
  }
  w("query I")
  w("SELECT p.n_imputations = ", m, " AND ", paste(checks, collapse = "\n   AND "), " FROM pooled;")
  w("----")
  w("true")
  w("")
}

ols_sql <- "SELECT imputation, ols_fit_agg(x[1], [x[2], x[3], x[4]], {'compute_inference': true}) AS fit FROM imp_w GROUP BY imputation"
lm_fits <- lapply(completed, function(dk) lm(y ~ x1 + x2 + b, data = dk))
lm0 <- lapply(completed, function(dk) lm(y ~ 1, data = dk))
pool_block("OLS y ~ x1 + x2 + b: mice::pool (Barnard-Rubin, dfcom = n - 4) and mice::D1",
           lm_fits, ols_sql, fit0 = lm0)
pool_block("OLS with df_complete = 50 (mice::pool(dfcom = 50), mice::D1(dfcom = 50))",
           lm_fits, ols_sql, options = "{'df_complete': 50}", dfcom = 50, fit0 = lm0)
pool_block("OLS with small_sample = false: Rubin's large-sample d.f. (mice::pool(dfcom = Inf))",
           lm_fits, ols_sql, options = "{'small_sample': false}", dfcom = Inf)

glm_sql <- "SELECT imputation, logistic_fit_agg(x[4], [x[1], x[2], x[3]], {'compute_inference': true, 'tolerance': 1e-12}) AS fit FROM imp_w GROUP BY imputation"
glm_fits <- lapply(completed, function(dk) glm(b ~ y + x1 + x2, family = binomial, data = dk, control = glm.control(epsilon = 1e-14, maxit = 100)))
# logistic_fit_agg's standard errors agree with glm()'s to about 1e-8 (the
# covariance is taken at the last IRLS weights), so this block uses 1e-6.
pool_block("Logistic b ~ y + x1 + x2 (IRLS converged tightly on both sides): mice::pool (dfcom = n - 4)",
           glm_fits, glm_sql, tol = "1e-6")

