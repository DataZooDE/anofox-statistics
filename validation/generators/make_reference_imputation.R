# --- imputation scenarios ---------------------------------------------------
scenario <- function(tag, seed, options, ...) {
  set.seed(seed)
  a <- aregImpute(..., data = d, pr = FALSE)
  m <- a$n.impute
  exp_rows <- character()
  for (v in c("x1", "x2", "g")) {
    col <- match(v, names(d))
    imp <- a$imputed[[v]]
    for (r in seq_len(nrow(imp))) {
      for (k in seq_len(m)) {
        exp_rows <- c(exp_rows, sprintf("(%d, %s, %d, %s)", k, rownames(imp)[r], col, num(imp[r, k])))
      }
    }
  }
  tab <- paste0("imp_", tag)
  w("# ", tag, ": set.seed(", seed, "); aregImpute(", deparse(..1), ", n.impute = ", m, ", ...)")
  w("statement ok")
  w("CREATE TABLE ", tab, " AS SELECT unnest(areg_impute_agg(id, [y, x1, x2, b, g], ", options,
    "), recursive := true) FROM imp_data;")
  w("")
  w("statement ok")
  w("CREATE TABLE ", tab, "_expected AS SELECT * FROM (VALUES")
  w(paste0("    ", exp_rows, collapse = ",\n"))
  w(") t(imputation, id, col, value);")
  w("")
  w("# every completed data set has all rows, without missing values")
  w("query III")
  w("SELECT count(*), count(DISTINCT imputation), sum(CASE WHEN list_count(x) = 5 AND list_bool_and(list_transform(x, lambda v: isfinite(v))) THEN 1 ELSE 0 END) FROM ", tab, ";")
  w("----")
  w(n * m, "\t", m, "\t", n * m)
  w("")
  w("# the imputed values replay R's")
  w("query II")
  w("SELECT count(*), sum(CASE WHEN abs(i.x[e.col] - e.value) <= 1e-12 * (1 + abs(e.value)) THEN 1 ELSE 0 END)")
  w("FROM ", tab, "_expected e JOIN ", tab, " i ON i.imputation = e.imputation AND i.id = e.id;")
  w("----")
  w(length(exp_rows), "\t", length(exp_rows))
  w("")
  w("# observed values are kept")
  w("query I")
  w("SELECT count(*) FROM ", tab, " i JOIN imp_data o ON i.id = o.id")
  w("WHERE i.x[1] IS DISTINCT FROM o.y OR i.x[4] IS DISTINCT FROM o.b")
  w("   OR (o.x1 IS NOT NULL AND i.x[2] <> o.x1) OR (o.x2 IS NOT NULL AND i.x[3] <> o.x2)")
  w("   OR (o.g IS NOT NULL AND i.x[5] <> o.g);")
  w("----")
  w("0")
  w("")
  a
}

