# Reference values for multiple imputation and Rubin pooling (#321):
# areg_impute_agg / areg_impute_by and pool_rubin_agg. Writes
# test/sql/reference/imputation_reference.test.
#
#   Rscript validation/generators/make_reference_imputation.R
#
# Imputation: Hmisc::aregImpute. Upstream anofox-regression replays R's random
# number generator, so with the same seed the imputed values must agree
# exactly (tolerance 1e-12 relative). The data and the five scenarios are those
# of upstream's tests/r_scripts/generate_aregimpute_validation.R.
#
# Pooling: mice::pool (Rubin's rules, Barnard-Rubin d.f. with dfcom = the
# model's df.residual) and mice::D1 (mitml's D1 with Reiter's d.f.) over lm /
# glm fits to the imputed data sets; mice and mitml are taken from
# ~/R/userlib when they are not installed system-wide.
#
# The pooling references are computed from R's own imputations: the extension
# reproduces them exactly (first block), so its per-imputation fits are fits to
# the same data.

