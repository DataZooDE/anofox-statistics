close_scalar <- function(expr, ref, tol = "1e-9") {
  sprintf("abs((%s) - (%s)) <= %s * (1 + abs(%s))", expr, num(ref), tol, num(ref))
}
close_list <- function(expr, ref, tol = "1e-9") {
  sprintf("len(%s) = %d AND list_max(list_transform(range(1, %d), lambda _i: abs((%s)[_i] - (%s)[_i]) / (1 + abs((%s)[_i])))) <= %s",
          expr, length(ref), length(ref) + 1, expr, lst(ref), lst(ref), tol)
}

