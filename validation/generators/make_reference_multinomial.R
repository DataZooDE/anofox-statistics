# Reference values for the unpenalized multinomial logistic regression (#314):
# multinomial_fit_agg(..., {'lambda': 0}) and multinomial_predict against R's
# nnet::multinom. Writes test/sql/reference/multinomial_nnet.test.
#
#   Rscript validation/generators/make_reference_multinomial.R
#
# Requires nnet (a recommended package). The penalized fits (ridge, lasso,
# elastic net) are checked against scikit-learn by make_reference_multinomial.py.
#
# Parameterization: nnet reports K - 1 coefficient rows, each class against the
# first (baseline-category logits). Without a penalty the softmax coefficients
# are only defined up to a common shift; the extension (upstream
# MultinomialLogisticRegressor) reports them centred to sum to zero across the
# classes, as scikit-learn does. The baseline contrasts
# coefficients[k] - coefficients[1] (and the same for the intercepts) are
# invariant and are what is compared with nnet's rows. Probabilities,
# predicted classes and the log-likelihood are compared directly.
#
# nnet's BFGS is run to reltol = 1e-14 so its estimate is the MLE to ~1e-7.

suppressPackageStartupMessages(library(nnet))

out <- "test/sql/reference/multinomial_nnet.test"
num <- function(v) sprintf("%.15g", v)
close <- function(expr, ref, tol) sprintf("abs((%s) - (%s)) <= %s * (1 + abs(%s))", expr, num(ref), tol, num(ref))

L <- character()
w <- function(...) L <<- c(L, paste0(...))

check <- function(title, from, conds) {
  for (s in seq(1, length(conds), by = 6)) {
    chunk <- conds[s:min(length(conds), s + 5)]
    w("# ", title)
    w("query ", strrep("I", length(chunk)))
    w("SELECT")
    w(paste0("    ", chunk, collapse = ",\n"))
    w(from)
    w("----")
    w(paste(rep("true", length(chunk)), collapse = "\t"))
    w("")
  }
}

# Fixed dataset: four classes from a softmax model (not separable).
set.seed(314)
n <- 120
X <- round(matrix(rnorm(n * 3), n, 3), 3)
B <- rbind(c(0, 0, 0), c(1.1, -0.6, 0.2), c(-0.5, 0.9, 0.4), c(0.3, 0.4, -1.0))
eta <- X %*% t(B) + matrix(c(0, 0.3, -0.2, 0.1), n, 4, byrow = TRUE)
P <- exp(eta) / rowSums(exp(eta))
cls <- c("alpha", "beta", "delta", "gamma")
y <- factor(cls[apply(P, 1, function(p) sample(4, 1, prob = p))], levels = cls)
wt <- round(runif(n, 0.5, 2), 2)
d <- data.frame(y = y, x1 = X[, 1], x2 = X[, 2], x3 = X[, 3], wt = wt)

w("# name: test/sql/reference/multinomial_nnet.test")
w("# description: unpenalized multinomial_fit_agg / multinomial_predict (#314) vs R nnet::multinom")
w("# group: [reference]")
w("#")
w("# GENERATED by validation/generators/make_reference_multinomial.R -- do not edit by hand.")
w("# Reference: nnet ", as.character(packageVersion("nnet")), " multinom(y ~ x1 + x2 + x3, reltol = 1e-14).")
w("# nnet's rows are baseline-category logits (class k against the first class); the extension's")
w("# coefficients are centred over the classes, so coefficients[k] - coefficients[1] is compared.")
w("")
w("require anofox_statistics")
w("")
w("statement ok")
w("CREATE TABLE d (id INTEGER, y VARCHAR, x1 DOUBLE, x2 DOUBLE, x3 DOUBLE, wt DOUBLE);")
w("")
w("statement ok")
w("INSERT INTO d VALUES")
w(paste(sprintf("(%d, '%s', %s, %s, %s, %s)", seq_len(n), as.character(y), num(d$x1), num(d$x2), num(d$x3),
                num(d$wt)), collapse = ",\n"), ";")
w("")

ids <- c(1, 9, 40, 77, 120)
cases <- list(
  list(title = "lambda = 0", weights = NULL, sql = "multinomial_fit_agg(y, [x1, x2, x3], {'lambda': 0})"),
  list(title = "lambda = 0, case weights", weights = wt,
       sql = "multinomial_fit_agg(y, [x1, x2, x3], wt, {'lambda': 0})")
)
for (cs in cases) {
  fit <- if (is.null(cs$weights)) {
    multinom(y ~ x1 + x2 + x3, data = d, trace = FALSE, maxit = 10000, reltol = 1e-14, abstol = 1e-300)
  } else {
    multinom(y ~ x1 + x2 + x3, data = d, weights = wt, trace = FALSE, maxit = 10000, reltol = 1e-14,
             abstol = 1e-300)
  }
  cf <- coef(fit) # (K - 1) x (1 + p): intercept first
  from <- sprintf("FROM (SELECT %s AS m FROM d) t;", cs$sql)
  conds <- character()
  for (k in 2:4) {
    conds <- c(conds, close(sprintf("m.intercepts[%d] - m.intercepts[1]", k), cf[k - 1, 1], "1e-6"))
    for (j in 1:3) {
      conds <- c(conds, close(sprintf("m.coefficients[%d][%d] - m.coefficients[1][%d]", k, j, j), cf[k - 1, j + 1],
                              "1e-6"))
    }
  }
  conds <- c(conds, close("m.log_likelihood", as.numeric(logLik(fit)), "1e-8"),
             "m.converged", "m.classes = ['alpha', 'beta', 'delta', 'gamma']",
             close("list_sum(m.intercepts)", 0, "1e-9"))
  check(sprintf("multinomial_fit_agg %s: nnet::multinom baseline contrasts and logLik", cs$title), from, conds)

  pr <- fitted(fit)
  conds <- character()
  for (i in ids) {
    for (k in 1:4) {
      conds <- c(conds, close(sprintf("(SELECT multinomial_predict(t.m, [x1, x2, x3], {'type': 'prob'})[%d] FROM d WHERE id = %d)",
                                      k, i), pr[i, k], "1e-6"))
    }
  }
  check(sprintf("multinomial_fit_agg %s: fitted probabilities", cs$title), from, conds)
  pc <- as.character(predict(fit, d))
  conds <- sprintf("(SELECT predict(t.m, [x1, x2, x3]) FROM d WHERE id = %d) = '%s'", ids, pc[ids])
  check(sprintf("multinomial_fit_agg %s: predicted classes", cs$title), from, conds)
  w("# ", cs$title, ": accuracy = share of rows whose predicted class is their class")
  w("query I")
  w(sprintf("SELECT %s FROM (SELECT %s AS m FROM d) t;", close("m.accuracy", mean(pc == as.character(y)), "1e-12"),
            cs$sql))
  w("----")
  w("true")
  w("")
}

writeLines(L, out)
cat("wrote", out, "\n")
