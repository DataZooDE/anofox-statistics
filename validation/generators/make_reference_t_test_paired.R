#!/usr/bin/env Rscript
# Reference values for test/sql/reference/t_test_one_sample_paired_reference.test
# (#299): t_test_one_sample_agg, t_test_paired_agg and the rank_biserial field
# of wilcoxon_signed_rank_agg.
#
# Usage:  Rscript validation/generators/make_reference_t_test_paired.R
# (re)writes the .test file. Packages: base R + stats only.
#
# * t-tests: stats::t.test(x, mu = mu) and t.test(x, y, paired = TRUE, mu = mu).
# * Cohen's d: (mean(x) - mu) / sd(x) and d_z = (mean(x - y) - mu) / sd(x - y),
#   the definitions of effectsize::cohens_d(x, mu = ) and
#   effectsize::cohens_d(x, y, paired = TRUE) (effectsize is not installed).
# * Matched-pairs rank-biserial: effectsize::rank_biserial(x, y, paired = TRUE)
#   = (T+ - T-) / (T+ + T-) over the ranks of |d| (zeros dropped, average ranks
#   for ties), computed here from that formula. The extension reports the
#   opposite sign (r > 0 when y tends to be larger, as mann_whitney_u_agg's
#   rank-biserial), so the test compares against -r.

out_file <- "test/sql/reference/t_test_one_sample_paired_reference.test"
fmt <- function(x) sprintf("%.17g", as.numeric(x))
lit <- function(x) { s <- fmt(x); if (as.numeric(x) < 0) paste0("(", s, ")") else s }

# Datasets (also inlined as VALUES below)
g1 <- c(5.1, 4.9, 6.2, 5.8, 6.05, 5.5, 5.3, 6.1)
px <- c(12.1, 14.3, 11.8, 15.2, 13.9, 12.7, 14.8, 13.1, 12.4, 15.6)
py <- c(11.5, 13.2, 12.3, 13.9, 13.0, 11.1, 14.6, 11.4, 12.6, 13.85)
# paired with tied |d| and two zero differences
tx <- c(3, 5, 4, 6, 7, 2, 8, 5, 4, 9, 6, 3)
ty <- c(4, 5, 2, 4, 9, 3, 6, 5, 6, 6, 4, 1)

rb_effectsize <- function(x, y, mu = 0) {
  d <- x - y - mu
  d <- d[d != 0]
  r <- rank(abs(d))
  tp <- sum(r[d > 0]); tn <- sum(r[d < 0])
  (tp - tn) / (tp + tn)
}

# One-sided alternatives give R's one-sided interval with an infinite bound
# (anofox-statistics >= 0.8.0 for every t-test; 0.7.0 returned the two-sided
# interval), compared as r.ci_* = +-inf.
ci_check <- function(field, v) {
  if (is.infinite(v)) paste0("r.", field, " = '", if (v > 0) "inf" else "-inf", "'::DOUBLE")
  else paste0("abs(r.", field, " - ", lit(v), ") < 1e-9")
}

L <- character()
add <- function(...) L <<- c(L, paste0(...))
check_t <- function(label, r, d, n, ci = r$conf.int) {
  add("# ", label)
  add("query IIIIIIII")
  add("SELECT abs(r.statistic - ", lit(r$statistic), ") < 1e-9,")
  add("       abs(r.df - ", lit(r$parameter), ") < 1e-12,")
  add("       abs(r.p_value - ", lit(r$p.value), ") <= 1e-12 * (1 + ", fmt(r$p.value), "),")
  add("       ", ci_check("ci_lower", ci[1]), ",")
  add("       ", ci_check("ci_upper", ci[2]), ",")
  add("       abs(r.effect_size - ", lit(d), ") < 1e-9,")
  add("       abs(r.estimate - ", lit(r$estimate), ") < 1e-9,")
  add("       r.n = ", n)
}

add("# name: ", out_file)
add("# description: One-sample / paired / two-sample t-test (incl. one-sided intervals) and matched-pairs rank-biserial vs R (#299)")
add("# group: [reference]")
add("#")
add("# GENERATED by validation/generators/make_reference_t_test_paired.R -- do not edit by hand.")
add("# R ", R.version$major, ".", R.version$minor, ", base stats: t.test(x, mu =), t.test(x, y, paired = TRUE);")
add("# Cohen's d and the rank-biserial from their effectsize definitions (see the generator).")
add("")
add("require anofox_statistics")
add("")
add("statement ok")
add("CREATE TABLE one AS SELECT v::DOUBLE AS v FROM (VALUES ", paste0("(", g1, ")", collapse = ","), ") t(v);")
add("")
add("statement ok")
add("CREATE TABLE pr AS SELECT x::DOUBLE AS x, y::DOUBLE AS y FROM (VALUES ",
    paste0("(", px, ",", py, ")", collapse = ","), ") t(x, y);")
add("")
add("statement ok")
add("CREATE TABLE ties AS SELECT x::DOUBLE AS x, y::DOUBLE AS y FROM (VALUES ",
    paste0("(", tx, ",", ty, ")", collapse = ","), ") t(x, y);")
add("")

for (cfg in list(list(mu = 0, alt = "two.sided", cl = 0.95),
                 list(mu = 5, alt = "two.sided", cl = 0.95),
                 list(mu = 5.5, alt = "less", cl = 0.95),
                 list(mu = 5.5, alt = "greater", cl = 0.90))) {
  r <- t.test(g1, mu = cfg$mu, alternative = cfg$alt, conf.level = cfg$cl)
  d <- (mean(g1) - cfg$mu) / sd(g1)
  alt_sql <- sub(".", "_", cfg$alt, fixed = TRUE)
  check_t(sprintf("R: t.test(g1, mu = %g, alternative = '%s', conf.level = %g)", cfg$mu, cfg$alt, cfg$cl), r, d, length(g1))
  add(sprintf("FROM (SELECT t_test_one_sample_agg(v, {'mu': %g, 'alternative': '%s', 'confidence_level': %g}) AS r FROM one);",
              cfg$mu, alt_sql, cfg$cl))
  add("----")
  add(paste(rep("true", 8), collapse = "\t"))
  add("")
}

for (cfg in list(list(mu = 0, alt = "two.sided", cl = 0.95),
                 list(mu = 0.5, alt = "two.sided", cl = 0.99),
                 list(mu = 0, alt = "greater", cl = 0.95),
                 list(mu = 0, alt = "less", cl = 0.95))) {
  r <- t.test(px, py, paired = TRUE, mu = cfg$mu, alternative = cfg$alt, conf.level = cfg$cl)
  dd <- px - py
  d <- (mean(dd) - cfg$mu) / sd(dd)
  alt_sql <- sub(".", "_", cfg$alt, fixed = TRUE)
  check_t(sprintf("R: t.test(px, py, paired = TRUE, mu = %g, alternative = '%s', conf.level = %g)", cfg$mu, cfg$alt, cfg$cl), r, d, length(px))
  add(sprintf("FROM (SELECT t_test_paired_agg(x, y, {'mu': %g, 'alternative': '%s', 'confidence_level': %g}) AS r FROM pr);",
              cfg$mu, alt_sql, cfg$cl))
  add("----")
  add(paste(rep("true", 8), collapse = "\t"))
  add("")
}

# Ties dataset: paired t-test with default options.
r <- t.test(tx, ty, paired = TRUE)
dd <- tx - ty
check_t("R: t.test(tx, ty, paired = TRUE)", r, mean(dd) / sd(dd), length(tx))
add("FROM (SELECT t_test_paired_agg(x, y) AS r FROM ties);")
add("----")
add(paste(rep("true", 8), collapse = "\t"))
add("")

# t_test_agg (two independent samples, px as group 0, py as group 1): the
# one-sided alternatives give R's one-sided interval (behaviour change in
# anofox-statistics 0.8.0).
add("statement ok")
add("CREATE TABLE two AS SELECT x AS v, 0 AS g FROM pr UNION ALL SELECT y, 1 FROM pr;")
add("")
for (cfg in list(list(kind = "welch", alt = "less", cl = 0.95),
                 list(kind = "welch", alt = "greater", cl = 0.9),
                 list(kind = "student", alt = "greater", cl = 0.95),
                 list(kind = "student", alt = "less", cl = 0.99))) {
  r <- t.test(px, py, var.equal = cfg$kind == "student", alternative = cfg$alt, conf.level = cfg$cl)
  add(sprintf("# R: t.test(px, py, var.equal = %s, alternative = '%s', conf.level = %g)",
              cfg$kind == "student", cfg$alt, cfg$cl))
  add("query IIIII")
  add("SELECT abs(r.statistic - ", lit(r$statistic), ") < 1e-9,")
  add("       abs(r.df - ", lit(r$parameter), ") < 1e-9,")
  add("       abs(r.p_value - ", lit(r$p.value), ") <= 1e-12 * (1 + ", fmt(r$p.value), "),")
  add("       ", ci_check("ci_lower", r$conf.int[1]), ",")
  add("       ", ci_check("ci_upper", r$conf.int[2]))
  add(sprintf("FROM (SELECT t_test_agg(v, g, {'kind': '%s', 'alternative': '%s', 'confidence_level': %g}) AS r FROM two);",
              cfg$kind, cfg$alt, cfg$cl))
  add("----")
  add(paste(rep("true", 5), collapse = "\t"))
  add("")
}

# Rank-biserial
for (ds in list(list(name = "pr", x = px, y = py), list(name = "ties", x = tx, y = ty))) {
  rb <- rb_effectsize(ds$x, ds$y)
  w <- suppressWarnings(wilcox.test(ds$x, ds$y, paired = TRUE, exact = FALSE, correct = TRUE))
  add(sprintf("# R: -rank_biserial(%s) with rank_biserial = (T+ - T-) / (T+ + T-) = %s", ds$name, fmt(rb)))
  add(sprintf("#    wilcox.test(paired = TRUE, exact = FALSE, correct = TRUE): V = %s", fmt(w$statistic)))
  add("query IIIII")
  add("SELECT abs(r.rank_biserial - ", lit(-rb), ") < 1e-12,")
  add("       abs(r.effect_size - ", lit(-rb), ") < 1e-12, r.effect_name = 'rank_biserial',")
  add("       abs(r.statistic - ", lit(w$statistic), ") < 1e-9,")
  # 1e-9: with tied |d| the normal approximation agrees with R to ~1e-11 only.
  add("       abs(r.p_value - ", lit(w$p.value), ") <= 1e-9 * (1 + ", fmt(w$p.value), ")")
  add(sprintf("FROM (SELECT wilcoxon_signed_rank_agg(x, y) AS r FROM %s);", ds$name))
  add("----")
  add(paste(rep("true", 5), collapse = "\t"))
  add("")
}

# Swapping x and y flips the sign of the rank-biserial.
add("query I")
add("SELECT abs((wilcoxon_signed_rank_agg(y, x)).rank_biserial - ", lit(rb_effectsize(px, py)), ") < 1e-12 FROM pr;")
add("----")
add("true")

writeLines(L, out_file)
cat("wrote", out_file, "\n")
