# Reference values for the cluster-robust (sandwich) covariance of the GLM and
# AFT fits: poisson / binomial / logistic / negbinom / gamma / tweedie_fit_agg(y,
# x, cluster, {'vcov': 'cluster'}) against R sandwich::vcovCL(glm(...)) (and
# MASS::glm.nb, statmod::tweedie), aft_fit_agg(time, x, event, cluster, options)
# against survival::survreg(..., cluster = id). The Wald tests are normal (z), as
# lmtest::coeftest(glm, vcov = vcovCL(...)) (coeftest.glm: df = Inf) and
# summary(survreg(..., cluster =)).
#
# The penalized case (a logistic fit with Normal priors on the slopes) has no R
# package equivalent with these priors; it is the documented formula in base R:
# the posterior mode by Newton-Raphson on the log posterior, then
# A (sum_g s_g s_g') A * G / (G - 1) with A = (X'WX + P)^-1, P = diag(0, 1/s^2),
# s_i = (y_i - mu_i) x_i the likelihood scores (upstream GlmResult::cluster_vcov).
#
#   Rscript validation/generators/make_reference_glm_cluster_vcov.R
#
# (Re)writes test/sql/reference/glm_cluster_vcov.test. The dataset is a literal
# constant (no RNG).
suppressMessages({
  library(sandwich)
  library(lmtest)
  library(MASS)
  library(statmod)
  library(survival)
})

out_file <- "test/sql/reference/glm_cluster_vcov.test"

n <- 60
i <- 0:(n - 1)
firm <- letters[((i * 5 + i %/% 7) %% 8) + 1]
yr <- 2000L + ((i * 3 + i %/% 5) %% 5)
x1 <- round(sin(i / 3.1) * 1.2 + (i %% 4) / 4, 2)
x2 <- round(cos(i / 4.3) + (i %% 3) / 3, 2)
fe <- c(a = 0.4, b = -0.3, c = 0.2, d = -0.5, e = 0.3, f = 0.0, g = -0.2, h = 0.5)[firm]
eta <- 0.3 + 0.5 * x1 - 0.3 * x2 + fe
cnt <- round(exp(eta) + ((i * 7) %% 5) / 2)
yb <- as.integer(((i * 13) %% 10) / 10 < plogis(eta - 0.3))
gam <- round(exp(eta) * (0.6 + ((i * 11) %% 9) / 10), 3)
tw <- ifelse(i %% 5 == 0, 0, gam)
lexp <- round(log(1 + (i %% 6)), 4)
tt <- round(exp(1 + 0.4 * x1 - 0.3 * x2 + fe) * (0.5 + ((i * 17) %% 10) / 10), 3)
ev <- as.integer(i %% 4 != 0)
d <- data.frame(id = i + 1, cnt, yb, gam, tw, lexp, tt, ev, x1, x2, firm, yr, stringsAsFactors = FALSE)

