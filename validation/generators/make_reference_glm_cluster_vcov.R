check <- function(comment, call, exprs, refs, tol) {
  if (!all(is.finite(refs))) stop("non-finite reference in: ", comment)
  stopifnot(length(exprs) == length(refs))
  emit("# ", comment)
  emit("query ", strrep("I", length(exprs)))
  emit("SELECT")
  conds <- sprintf("    abs((%s) - (%s)) <= %s * (1 + abs(%s))", exprs, fmt(refs), tol, fmt(refs))
  emit(paste(conds, collapse = ",\n"))
  emit("FROM (SELECT ", call, " AS r FROM d) s;")
  emit("----")
  emit(paste(rep("true", length(exprs)), collapse = "\t"))
  emit("")
}

# Normal Wald inference of coefficients b with covariance V.
wald <- function(b, V) {
  se <- sqrt(diag(V))
  z <- b / se
  list(se = se, z = z, p = 2 * pnorm(-abs(z)), lo = b - qnorm(0.975) * se, hi = b + qnorm(0.975) * se)
}

# One block: slopes, intercept, vcov, vcov_type, n_clusters. `b` and `V` are in
# fitted order (intercept first); `stat` names the statistic field.
block <- function(label, b, V, call, n_clusters, vcov_type, tol, stat = "z_values", log_scale = FALSE) {
  w <- wald(b, V)
  k <- length(b) - if (log_scale) 1 else 0
  ex <- c(); rf <- c()
  for (j in 2:k) {
    ex <- c(ex, sprintf("r.std_errors[%d]", j - 1), sprintf("r.%s[%d]", stat, j - 1),
            sprintf("r.p_values[%d]", j - 1), sprintf("r.conf_low[%d]", j - 1), sprintf("r.conf_high[%d]", j - 1))
    rf <- c(rf, w$se[j], w$z[j], w$p[j], w$lo[j], w$hi[j])
  }
  check(paste0(label, ": slope std_errors, z, p, CI (normal) with V"), call, ex, rf, tol)
  check(paste0(label, ": intercept inference"), call,
        c("r.intercept_std_error", "r.intercept_statistic", "r.intercept_p_value",
          "r.intercept_conf_low", "r.intercept_conf_high"),
        c(w$se[1], w$z[1], w$p[1], w$lo[1], w$hi[1]), tol)
  if (log_scale) {
    check(paste0(label, ": log_scale_std_error"), call, "r.log_scale_std_error", w$se[length(b)], tol)
  }
  vv <- as.vector(t(unclass(V)))
  check(paste0(label, ": vcov (row-major, intercept first) = V"), call, sprintf("r.vcov[%d]", seq_along(vv)), vv, tol)
  emit("# ", label, ": vcov_type and clusters per dimension")
  emit("query TT")
  emit("SELECT r.vcov_type, r.n_clusters::VARCHAR FROM (SELECT ", call, " AS r FROM d) s;")
  emit("----")
  emit(vcov_type, "\t[", paste(n_clusters, collapse = ", "), "]")
  emit("")
}

ng <- function(...) sapply(list(...), function(v) length(unique(v)))
ctl <- glm.control(epsilon = 1e-14, maxit = 100)

# --- Poisson -----------------------------------------------------------------
fp <- glm(cnt ~ x1 + x2, family = poisson, data = d, control = ctl)
popt <- "'tolerance': 1e-12"
block("poisson, firm, default (HC0, cadjust)", coef(fp), vcovCL(fp, cluster = ~firm),
      sprintf("poisson_fit_agg(cnt, [x1, x2], firm, {'vcov': 'cluster', %s})", popt), ng(firm), "cluster_HC0", "1e-08")
block("poisson, firm, HC1", coef(fp), vcovCL(fp, cluster = ~firm, type = "HC1"),
      sprintf("poisson_fit_agg(cnt, [x1, x2], firm, {'vcov': 'cluster', 'hc_type': 'hc1', %s})", popt),
      ng(firm), "cluster_HC1", "1e-08")
block("poisson, firm, cadjust = false", coef(fp), vcovCL(fp, cluster = ~firm, cadjust = FALSE),
      sprintf("poisson_fit_agg(cnt, [x1, x2], firm, {'vcov': 'cluster', 'cadjust': false, %s})", popt),
      ng(firm), "cluster_HC0", "1e-08")
block("poisson, integer year ids", coef(fp), vcovCL(fp, cluster = ~yr),
      sprintf("poisson_fit_agg(cnt, [x1, x2], yr, {'vcov': 'cluster', %s})", popt), ng(yr), "cluster_HC0", "1e-08")
block("poisson, two-way firm x year", coef(fp), vcovCL(fp, cluster = ~ firm + yr),
      sprintf("poisson_fit_agg(cnt, [x1, x2], [firm, yr::VARCHAR], {'vcov': 'cluster', %s})", popt),
      ng(firm, yr), "cluster_HC0", "1e-08")
fpo <- glm(cnt ~ x1 + x2 + offset(lexp), family = poisson, data = d, control = ctl)
block("poisson with an offset column", coef(fpo), vcovCL(fpo, cluster = ~firm),
      sprintf("poisson_fit_agg(cnt, [x1, x2, lexp], firm, {'vcov': 'cluster', 'offset': 3, %s})", popt),
      ng(firm), "cluster_HC0", "1e-08")

# --- Binomial / logistic -------------------------------------------------------
fb <- glm(yb ~ x1 + x2, family = binomial, data = d, control = ctl)
block("binomial (logit), firm", coef(fb), vcovCL(fb, cluster = ~firm),
      "binomial_fit_agg(yb, [x1, x2], firm, {'vcov': 'cluster', 'tolerance': 1e-12})", ng(firm), "cluster_HC0", "1e-07")
block("logistic, firm", coef(fb), vcovCL(fb, cluster = ~firm),
      "logistic_fit_agg(yb, [x1, x2], firm, {'vcov': 'cluster', 'tolerance': 1e-12})", ng(firm), "cluster_HC0", "1e-07")

# --- Negative binomial (theta estimated, held at its estimate as vcovCL(glm.nb)) --
fnb <- glm.nb(cnt ~ x1 + x2, data = d, control = glm.control(epsilon = 1e-14, maxit = 100))
block("negbinom (glm.nb), firm", coef(fnb), vcovCL(fnb, cluster = ~firm),
      "negbinom_fit_agg(cnt, [x1, x2], firm, {'vcov': 'cluster', 'tolerance': 1e-12})", ng(firm), "cluster_HC0", "1e-05")

# --- Gamma (log link) ----------------------------------------------------------
fg <- glm(gam ~ x1 + x2, family = Gamma(link = "log"), data = d, control = ctl)
block("gamma (log), firm", coef(fg), vcovCL(fg, cluster = ~firm),
      "gamma_fit_agg(gam, [x1, x2], firm, {'vcov': 'cluster', 'tolerance': 1e-12})", ng(firm), "cluster_HC0", "1e-06")

# --- Tweedie (p = 1.5, log link) ---------------------------------------------
ft <- glm(tw ~ x1 + x2, family = tweedie(var.power = 1.5, link.power = 0), data = d, control = ctl)
block("tweedie (p = 1.5), firm", coef(ft), vcovCL(ft, cluster = ~firm),
      "tweedie_fit_agg(tw, [x1, x2], firm, {'vcov': 'cluster', 'tolerance': 1e-12})", ng(firm), "cluster_HC0", "1e-06")

# --- Penalized: logistic with Normal(0, 0.5) priors on the slopes ------------
X <- cbind(1, d$x1, d$x2)
P <- diag(c(0, 1 / 0.5^2, 1 / 0.5^2))
beta <- rep(0, 3)
for (it in 1:100) {
  mu <- plogis(drop(X %*% beta))
  W <- mu * (1 - mu)
  grad <- crossprod(X, d$yb - mu) - P %*% beta
  H <- crossprod(X, X * W) + P
  step <- solve(H, grad)
  beta <- beta + drop(step)
  if (max(abs(step)) < 1e-14) break
}
mu <- plogis(drop(X %*% beta))
A <- solve(crossprod(X, X * (mu * (1 - mu))) + P)
S <- X * (d$yb - mu)
G <- length(unique(d$firm))
meat <- Reduce(`+`, lapply(split(seq_len(n), d$firm), function(r) tcrossprod(colSums(S[r, , drop = FALSE]))))
Vp <- A %*% meat %*% A * G / (G - 1)
pen_call <- paste0("logistic_fit_agg(yb, [x1, x2], firm, {'vcov': 'cluster', 'tolerance': 1e-12, ",
                   "'feature_names': ['x1', 'x2'], ",
                   "'prior': MAP {'x1': {'normal': [0.0, 0.5]}, 'x2': {'normal': [0.0, 0.5]}}})")
check("penalized logistic (Normal(0, 0.5) slopes): coefficients = posterior mode", pen_call,
      c("r.intercept", "r.coefficients[1]", "r.coefficients[2]"), beta, "1e-08")
block("penalized logistic: penalized bread (X'WX + P)^-1", beta, Vp, pen_call, G, "cluster_HC0", "1e-07")

# --- AFT: survreg(..., cluster = id) ------------------------------------------
for (dist in c("weibull", "lognormal")) {
  fa <- survreg(Surv(tt, ev) ~ x1 + x2, data = d, dist = dist, cluster = firm,
                control = survreg.control(rel.tolerance = 1e-12, iter.max = 100))
  b <- c(coef(fa), log(fa$scale))
  block(paste0("aft (", dist, "), firm: survreg(cluster =)"), b, fa$var,
        sprintf("aft_fit_agg(tt, [x1, x2], ev, firm, {'distribution': '%s', 'tolerance': 1e-12})", dist),
        ng(firm), "cluster_HC0", "1e-06", log_scale = TRUE)
}
fae <- survreg(Surv(tt, ev) ~ x1 + x2, data = d, dist = "exponential", cluster = firm,
               control = survreg.control(rel.tolerance = 1e-12, iter.max = 100))
block("aft (exponential, fixed scale), firm", coef(fae), fae$var,
      "aft_fit_agg(tt, [x1, x2], ev, firm, {'distribution': 'exponential', 'tolerance': 1e-12})",
      ng(firm), "cluster_HC0", "1e-06")

writeLines(lines, out_file)
cat("wrote", out_file, "\n")
