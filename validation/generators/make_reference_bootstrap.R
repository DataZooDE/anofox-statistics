#!/usr/bin/env Rscript
# =============================================================================
# make_reference_bootstrap.R
#
# Generates test/sql/reference/bootstrap_mean_ci.test (#294):
#
#   bootstrap_mean_ci_agg (method 'iid', 'circular_block', 'stationary' and
#   'moving_block')
#     <- the exact bootstrap standard error of the mean (closed form, IID /
#        circular block / stationary) and percentile intervals of boot::boot /
#        boot::tsboot(sim = "fixed", endcorr = TRUE) / tsboot(sim = "geom") /
#        tsboot(sim = "fixed", endcorr = FALSE) with 200000 replicates
#
#   Rscript validation/generators/make_reference_bootstrap.R      # from repo root
#
# Requires: boot. The series is a literal constant (an AR(1) with phi = 0.6
# drawn once with set.seed(294) and rounded).
#
# The bootstrap is a Monte Carlo method and R's generator differs from the
# extension's, so the replicates cannot agree draw for draw. The checks are
# therefore:
#   * estimate: mean(x), to 1e-12;
#   * std_error: the exact (B -> infinity) bootstrap standard error of the mean,
#       IID:            sqrt(mean((x - xbar)^2) / n)
#       circular block: sqrt(mean((Bbar_i - xbar)^2) / b), Bbar_i the n circular
#                       block means, b = n / l blocks (n is a multiple of l),
#       stationary:     sqrt((g_0 + 2 sum_{i<n} kappa(n, i) g_i) / n), g_i the
#                       sample autocovariances (divisor n) and
#                       kappa(n, i) = (1 - i/n)(1 - q)^i + (i/n)(1 - q)^(n-i),
#                       q = 1 / l (Politis and Romano 1994; Hansen 2005, eq. (7)),
#       moving block:   no closed form here; the SD of R's 200000 replicates,
#     to 2% (Monte Carlo error at B = 50000: ~0.3%);
#   * conf_low / conf_high: the percentile interval of R's bootstrap with
#     200000 replicates, to 0.06 bootstrap standard errors (Monte Carlo error
#     of each 2.5% / 97.5% order statistic at B = 50000: ~0.012 SE).
# =============================================================================
suppressPackageStartupMessages(library(boot))

out_dir <- "test/sql/reference"
set.seed(2940) # the R bootstrap replicates only (the data are constants)

num <- function(v) sprintf("%.17g", v)

x <- c(10.51, 10.82, 11.43, 10.91, 9.21, 9.64, 9.38, 9.09, 8.55, 9.21, 8.25, 10.73, 11.95, 8.96, 8.95, 8.34,
       9.09, 9.25, 10.1, 9.93, 9.84, 8.02, 8.33, 10.16, 11.1, 12.32, 10.94, 10.08, 10.34, 9.88, 9.08, 8.99, 8.87,
       9.14, 7.87, 9.03, 8.87, 9.48, 10.8, 10.86, 11.12, 10.57, 9.78, 11.35, 10.77, 9.99, 9, 9.59, 10.59, 11.15,
       11.29, 10.65, 9.96, 9.01, 8.15, 10.96, 12.38, 9.87, 8.71, 10.84, 9.67, 9.86, 8.95, 8.91, 10.01, 9.55, 10.27,
       8.81, 9.97, 8.52, 9.81, 10.48, 9.54, 9.82, 11.29, 10.86, 7.47, 8.58, 8.16, 8.74, 7.39, 8.84, 9.88, 10.32,
       10.22, 9.04, 8.93, 10.04, 9.29, 8.71, 8.32, 8.75, 8.99, 10.42, 10.01, 10.05, 8.75, 9.45, 11.42, 10.37,
       11.28, 11.33, 11.17, 10.6, 9.36, 11.52, 9.61, 10.36, 8.25, 8.54, 10.87, 10.49, 11.54, 9.5, 8.28, 9.38,
       8.55, 8.74, 8.2, 9.1)
n <- length(x)
xbar <- mean(x)
B_SQL <- 50000
B_R <- 200000

# Percentile interval with the extension's order statistics (0-based
# floor(alpha/2 B) and min(ceil((1 - alpha/2) B), B - 1)).
percentile <- function(t, level) {
  t <- sort(t)
  B <- length(t)
  a <- 1 - level
  c(t[floor(a / 2 * B) + 1], t[min(ceiling((1 - a / 2) * B), B - 1) + 1])
}
se_iid <- sqrt(mean((x - xbar)^2) / n)
se_cbb <- function(l) {
  stopifnot(n %% l == 0)
  bm <- sapply(seq_len(n), function(i) mean(x[((i - 1 + 0:(l - 1)) %% n) + 1]))
  sqrt(mean((bm - xbar)^2) / (n / l))
}
se_sb <- function(l) {
  q <- 1 / l
  cc <- x - xbar
  g <- vapply(0:(n - 1), function(i) sum(cc[1:(n - i)] * cc[(1 + i):n]) / n, 0)
  i <- 1:(n - 1)
  kap <- (n - i) / n * (1 - q)^i + i / n * (1 - q)^(n - i)
  sqrt((g[1] + 2 * sum(kap * g[-1])) / n)
}
mean_stat <- function(d, i) mean(d[i])
t_iid <- boot(x, mean_stat, R = B_R)$t[, 1]
t_cbb <- function(l) tsboot(x, mean, R = B_R, l = l, sim = "fixed", endcorr = TRUE)$t[, 1]
t_sb <- function(l) tsboot(x, mean, R = B_R, l = l, sim = "geom")$t[, 1]
t_mbb <- function(l) tsboot(x, mean, R = B_R, l = l, sim = "fixed", endcorr = FALSE)$t[, 1]

lines <- c(
  "# name: test/sql/reference/bootstrap_mean_ci.test",
  "# description: #294 bootstrap_mean_ci_agg against the exact bootstrap SE and boot::boot / boot::tsboot intervals",
  "# group: [reference]",
  "#",
  "# GENERATED by validation/generators/make_reference_bootstrap.R -- do not edit",
  "# by hand; change the generator and re-run it instead.",
  sprintf("# Reference: %s, boot %s", R.version.string, packageVersion("boot")),
  "# Tolerances: see the generator (Monte Carlo methods; R's generator differs).",
  "",
  "require anofox_statistics",
  "",
  "statement ok",
  "CREATE TABLE series (t INTEGER, x DOUBLE);",
  "",
  "# Rows are inserted in a scrambled order: the block bootstrap must follow ORDER BY t.",
  "statement ok")
ord <- order((seq_len(n) * 37) %% (n + 1))
lines <- c(lines, paste0("INSERT INTO series VALUES\n",
  paste(sprintf("(%d, %s)", ord, x[ord]), collapse = ",\n"), ";"), "")

case <- function(comment, call, level, se, ci, block, method = if (is.na(block)) "iid" else "circular_block") {
  src <- sprintf("(SELECT %s AS r FROM series) s", call)
  tol_ci <- 0.06 * se
  c(paste0("# ", comment),
    "query IIIIIIIII",
    paste0("SELECT\n",
           sprintf("    abs(r.estimate - %s) <= 1e-12,\n", num(xbar)),
           sprintf("    abs(r.std_error - %s) <= 0.02 * %s,\n", num(se), num(se)),
           sprintf("    abs(r.conf_low - %s) <= %s,\n", num(ci[1]), num(tol_ci)),
           sprintf("    abs(r.conf_high - %s) <= %s,\n", num(ci[2]), num(tol_ci)),
           sprintf("    r.conf_level = %s,\n", level),
           sprintf("    r.n = %d,\n", n),
           sprintf("    r.n_bootstrap = %d,\n", B_SQL),
           if (is.na(block)) "    r.block_length IS NULL,\n" else sprintf("    r.block_length = %s,\n", num(block)),
           sprintf("    r.method = '%s'\n", method),
           "FROM ", src, ";"),
    "----",
    paste(rep("true", 9), collapse = "\t"),
    "")
}

lines <- c(lines, case(
  sprintf("IID: exact bootstrap SE %.6f, boot::boot percentile interval", se_iid),
  sprintf("bootstrap_mean_ci_agg(x, {'n_bootstrap': %d})", B_SQL), 0.95, se_iid, percentile(t_iid, 0.95), NA))
lines <- c(lines, case(
  "IID, confidence_level 0.9 (ORDER BY does not change the IID result)",
  sprintf("bootstrap_mean_ci_agg(x, {'n_bootstrap': %d, 'confidence_level': 0.9} ORDER BY t)", B_SQL),
  0.9, se_iid, percentile(t_iid, 0.9), NA))
for (l in c(6, 10)) {
  se <- se_cbb(l)
  lines <- c(lines, case(
    sprintf("circular block bootstrap, l = %d: exact SE %.6f, tsboot(sim = 'fixed', endcorr = TRUE) interval", l, se),
    sprintf("bootstrap_mean_ci_agg(x, {'method': 'circular_block', 'block_length': %d, 'n_bootstrap': %d} ORDER BY t)",
            l, B_SQL), 0.95, se, percentile(t_cbb(l), 0.95), l))
}

for (l in c(5, 7.5)) {
  se <- se_sb(l)
  lines <- c(lines, case(
    sprintf("stationary bootstrap, expected block length %s: exact SE %.6f, tsboot(sim = 'geom') interval", l, se),
    sprintf("bootstrap_mean_ci_agg(x, {'method': 'stationary', 'block_length': %s, 'n_bootstrap': %d} ORDER BY t)",
            l, B_SQL), 0.95, se, percentile(t_sb(l), 0.95), l, "stationary"))
}
tm <- t_mbb(6)
lines <- c(lines, case(
  sprintf("moving block bootstrap, l = 6: SD of tsboot(sim = 'fixed', endcorr = FALSE) replicates %.6f, its interval", sd(tm)),
  sprintf("bootstrap_mean_ci_agg(x, {'method': 'moving_block', 'block_length': 6, 'n_bootstrap': %d} ORDER BY t)", B_SQL),
  0.95, sd(tm), percentile(tm, 0.95), 6, "moving_block"))

lines <- c(lines,
  sprintf("# The AR(1) dependence widens the block-bootstrap SE over the IID one (%.4f, %.4f vs %.4f).",
          se_cbb(6), se_cbb(10), se_iid),
  "query I",
  paste0("SELECT (SELECT bootstrap_mean_ci_agg(x, {'method': 'circular_block', 'block_length': 10} ORDER BY t)",
         ".std_error FROM series) > 1.15 * (SELECT bootstrap_mean_ci_agg(x).std_error FROM series);"),
  "----",
  "true",
  "")

writeLines(lines, file.path(out_dir, "bootstrap_mean_ci.test"))
cat("wrote", file.path(out_dir, "bootstrap_mean_ci.test"), "\n")
cat(sprintf("se_iid %.5f se_cbb6 %.5f se_cbb10 %.5f\n", se_iid, se_cbb(6), se_cbb(10)))
